interface QueuedEvent {
  event_id: string;
  event_name: string;
  occurred_at: string;
  properties: Record<string, unknown>;
}

const buffer: QueuedEvent[] = [];
const STORAGE_KEY = 'analytics_pending_v1';

// ПРИЁМ 1. Свой путь на своём домене вместо чужого адреса.
// Запрос на /e/collect идёт на тот же сайт, что и сам продукт,
// поэтому его не отличить от обычной работы приложения. Это честный
// способ не терять данные тех, кто заблокировал сторонние домены,
// но НЕ индульгенция: собирать без согласия человека всё равно нельзя.
const ENDPOINT = '/e/collect';

function enqueue(event: QueuedEvent): void {
  buffer.push(event);
  // Копию сразу кладём в localStorage — хранилище браузера, которое
  // переживает закрытие вкладки. Если отправить не успеем, следующий
  // визит подхватит.
  persist();
  if (buffer.length >= 20) void flush('размер пачки');
}

function persist(): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(buffer));
  } catch {
    // Место кончилось или режим приватного просмотра. Не наша забота:
    // аналитика НИКОГДА не должна ломать продукт. Молча живём дальше.
  }
}

// ПРИЁМ 2. sendBeacon — специально придуман ровно для этой задачи.
// Он передаёт данные браузеру и говорит: «отправь, даже если страницу
// закроют». Браузер доставляет их сам, уже без нашей страницы.
function flush(reason: string): void {
  if (buffer.length === 0) return;

  const batch = buffer.splice(0, buffer.length);   // забрали всё и очистили
  const body = JSON.stringify({ batch, flush_reason: reason });

  // navigator.sendBeacon возвращает true, если браузер ПРИНЯЛ данные
  // в свою очередь. Это НЕ подтверждение доставки: ответа сервера мы
  // не увидим никогда, у sendBeacon его просто нет.
  const accepted = navigator.sendBeacon(ENDPOINT, new Blob([body], { type: 'application/json' }));

  if (accepted) {
    localStorage.removeItem(STORAGE_KEY);
    return;
  }

  // Не принял (например, пачка слишком большая) — пробуем fetch
  // с флагом keepalive: он тоже разрешает запросу пережить страницу,
  // но у него есть ограничение на размер тела.
  void fetch(ENDPOINT, { method: 'POST', body, keepalive: true }).catch(() => {
    // Не вышло — возвращаем события в буфер и в хранилище.
    buffer.unshift(...batch);
    persist();
  });
}

