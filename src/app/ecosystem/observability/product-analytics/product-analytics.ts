// Событие о деньгах отправляет тот, кто ЗНАЕТ про деньги, —
// то есть сервер, в момент, когда факт уже записан в базу.
// Правило простое: событие рождается там же, где меняется состояние.

// Таблица outbox («исходящие») — обычная таблица в вашей же базе.
// Приём древний и надёжный: событие записывается в ТОЙ ЖЕ транзакции,
// что и заказ. Или записано и то и другое, или ничего.
// Аналогия: секретарь не относит письмо на почту сам — он кладёт его
// в лоток «на отправку», а курьер потом забирает всё, что там лежит.
async function handlePaymentWebhook(payload: PaymentWebhook): Promise<void> {
  await db.transaction(async (tx) => {
    const order = await tx.orders.findById(payload.orderId);

    // Идемпотентность: тот же вебхук может прийти второй и третий раз —
    // платёжные сервисы прямо предупреждают об этом. Уже оплачен —
    // выходим молча, ничего не пишем.
    if (order.status === 'paid') return;

    await tx.orders.update(order.id, { status: 'paid', paidAt: payload.paidAt });

    // Считаем «первый ли это заказ» ЗДЕСЬ, пока данные под рукой.
    // Потом, в отчёте, это будет тяжёлый запрос по всей истории.
    const previousPaidCount = await tx.orders.countPaidByUser(order.userId);

    await tx.eventOutbox.insert({
      // Ключ идемпотентности приёмника: один заказ — одно событие
      // 'order_paid' навсегда, сколько бы раз мы тут ни оказались.
      idempotencyKey: 'order_paid:' + order.id,
      eventName: 'order_paid',
      occurredAt: payload.paidAt,
      userId: order.userId,
      // ГЛАВНАЯ ДЕТАЛЬ ВСЕЙ СЕКЦИИ. Серверу неоткуда узнать, из какого
      // браузера пришёл человек. Значит, анонимный идентификатор надо
      // было сохранить в заказ ещё при оформлении и протащить сюда.
      // Без этого серверное событие не склеится с браузерным путём,
      // и воронка «зашёл → положил в корзину → купил» развалится
      // ровно на последнем шаге.
      anonymousId: order.analyticsAnonymousId,
      properties: {
        order_id: String(order.id),
        amount_minor: order.totalMinor,
        currency: order.currency,
        payment_method: payload.method,
        items_count: order.items.length,
        is_first_order: previousPaidCount === 0,
      },
    });
  });
}

