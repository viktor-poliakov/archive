// ─── РАСКЛАДКА ПО ПОЛУЧАТЕЛЯМ ───
class FanOut implements AnalyticsSink {
  readonly name = 'fan-out';

  constructor(private readonly sinks: ReadonlyArray<AnalyticsSink>) {}

  async send(batch: ReadonlyArray<Envelope>): Promise<void> {
    // Promise.allSettled вместо Promise.all — принципиально.
    // Один упавший получатель не должен утаскивать за собой остальных:
    // если у подрядчика авария, ваше собственное хранилище всё равно
    // должно получить события.
    const results = await Promise.allSettled(this.sinks.map((s) => s.send(batch)));

    results.forEach((result, index) => {
      if (result.status === 'rejected') {
        console.warn('[analytics] получатель не принял:', this.sinks[index].name);
      }
    });
  }
}

