// заменяем на заглушки, чтобы одинаковые страницы схлопнулись
// в одну строку отчёта, а лишнего не осталось.
const KEEP_QUERY_PARAMS = ['utm_source', 'utm_medium', 'utm_campaign', 'page', 'sort'];

function sanitizeUrl(rawUrl: string): { page_path: string; query: Record<string, string> } {
  const url = new URL(rawUrl);

  const path = url.pathname
    .split('/')
    .map((part) => {
      if (/^\\d+$/.test(part)) return ':id';               // /orders/1043 → /orders/:id
      if (/^[0-9a-f]{8,}$/i.test(part)) return ':token';   // длинная шестнадцатеричная строка
      if (part.includes('@')) return ':email';             // адрес почты прямо в пути
      return part;
    })
    .join('/');

  // Из строки запроса оставляем только заранее разрешённые параметры.
  const query: Record<string, string> = {};
  for (const name of KEEP_QUERY_PARAMS) {
    const value = url.searchParams.get(name);
    if (value !== null) query[name] = value.slice(0, 64);
  }

  return { page_path: path, query };
}

