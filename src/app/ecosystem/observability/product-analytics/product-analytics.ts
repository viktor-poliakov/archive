// ─── ПОЧЕМУ РАЗМЕР ВЫБОРКИ СЧИТАЮТ ЗАРАНЕЕ ───
// Идея без формул. Конверсия каждый день гуляет сама по себе: сегодня
// 4.0%, завтра 4.3%, послезавтра 3.8% — и никто ничего не менял.
// Это шум. Чтобы отличить настоящее улучшение от шума, наблюдений
// нужно тем больше, чем меньше ожидаемое улучшение.
// Порядок величины: при базовой конверсии около 4% и надежде поднять
// её на десятую часть от себя самой (с 4.0% до 4.4%) речь идёт
// о десятках тысяч человек НА КАЖДЫЙ вариант. Точное число даёт
// калькулятор размера выборки — их полно, и в него подставляют
// базовую конверсию и ожидаемый эффект.
// Практический вывод, который важнее любой формулы: если у вас
// двести заказов в месяц, вы не сможете измерить улучшение
// на несколько процентов. Никогда. Ни за какой срок. И это нормально:
// маленьким продуктам решения принимают по разговорам с людьми,
// а не по тестам.

// ─── РАСПРЕДЕЛЕНИЕ ПО ВАРИАНТАМ ───
// Ключевое требование: один и тот же человек всегда попадает в один
// и тот же вариант. Иначе он увидит то одно, то другое, и обе
// половины теста испортятся. Поэтому НЕ Math.random(), а устойчивое
// число, посчитанное из идентификатора человека и ключа опыта.
function stableBucket(experimentKey: string, subjectId: string): number {
  const input = experimentKey + ':' + subjectId;
  let hash = 2166136261;
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  // Приводим к диапазону 0..99. Знак убираем сдвигом без знака.
  return (hash >>> 0) % 100;
}

function assignVariant(exp: Experiment, subjectId: string): Variant | 'excluded' {
  const bucket = stableBucket(exp.key, subjectId);
  if (bucket >= exp.trafficShare * 100) return 'excluded';
  return bucket % 2 === 0 ? 'control' : 'treatment';
}

// ─── СОБЫТИЕ ПОКАЗА (exposure) ─── Самая забываемая деталь.
// Считать надо не всех, кому МЫ НАЗНАЧИЛИ вариант, а только тех,
// кто до этого места реально дошёл и увидел разницу. Иначе в тест
// попадут люди, которые ушли с главной и никакой кнопки не видели, —
// они одинаково «не купили» в обеих половинах и просто размажут
// результат до нуля.
function useCheckoutVariant(subjectId: string): Variant | 'excluded' {
  const variant = assignVariant(oneClickCheckout, subjectId);
  if (variant === 'excluded') return 'excluded';

  // Отправляем ровно в тот момент, когда человек увидел вариант.
  analytics.track('experiment_viewed', {
    experiment_key: oneClickCheckout.key,
    variant,
  });

  return variant;
}

// ─── ПРАВИЛА ОСТАНОВКИ ───
// Самая частая ошибка живых команд: подглядывать в результаты каждый
// день и остановить тест в тот момент, когда цифра нравится.
// Так «значимый результат» находится почти всегда — просто потому,
// что шум рано или поздно качнётся в нужную сторону. Это называют
// подглядыванием (peeking), и оно превращает тест в лотерею.
interface ExperimentProgress {
  daysRunning: number;
  observationsPerVariant: number;
  guardrailBroken: boolean;
}

type Decision = 'ждать' | 'можно смотреть результат' | 'остановить немедленно';

function decide(exp: Experiment, p: ExperimentProgress): Decision {
  // Единственная причина остановить раньше срока — сломался
  // предохранитель: выросли отмены, посыпались обращения в поддержку,
  // полезли ошибки. Это не «результат теста», это авария.
  if (p.guardrailBroken) return 'остановить немедленно';

  if (p.daysRunning < exp.minRunDays) return 'ждать';
  if (p.observationsPerVariant < exp.requiredPerVariant) return 'ждать';
  return 'можно смотреть результат';
}

