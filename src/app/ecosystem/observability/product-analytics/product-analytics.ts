// ─── ОШИБКА ВТОРАЯ: ПЕРИОДЫ РАЗНОЙ ДЛИНЫ ───
// «В этом месяце 410 заказов, а в прошлом 366 — рост!»
// Только в этом месяце 31 день, а в прошлом 28. И праздники.
// И акция была в одном из них.
function comparePeriods(
  a: { from: Date; to: Date; value: number },
  b: { from: Date; to: Date; value: number },
): string {
  const daysA = Math.round((a.to.getTime() - a.from.getTime()) / 86400000);
  const daysB = Math.round((b.to.getTime() - b.from.getTime()) / 86400000);

  if (daysA !== daysB) {
    throw new Error('Периоды разной длины: ' + daysA + ' и ' + daysB + ' дней. Сравнение бессмысленно');
  }
  // И ещё одна проверка, про которую забывают: у периодов должен
  // совпадать состав дней недели. Неделя с понедельника по воскресенье
  // и неделя со среды по вторник дадут разные числа сами по себе.
  if (a.from.getDay() !== b.from.getDay()) {
    throw new Error('Периоды начинаются с разных дней недели — недельный ритм всё испортит');
  }

  const delta = ((a.value - b.value) / b.value) * 100;
  return (delta >= 0 ? '+' : '') + delta.toFixed(1) + '%';
}

