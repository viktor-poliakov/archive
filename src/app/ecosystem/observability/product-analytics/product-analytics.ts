// Все примеры — на одном интернет-магазине за один обычный день.
// Никаких формул сложнее деления здесь нет.

// ─── 1. ВОРОНКА (funnel) ───
// Воронка — это упорядоченные шаги, которые человек проходит к цели.
// Название буквальное: сверху широко, снизу узко. Каждый шаг —
// подмножество предыдущего: до второго шага доходят только те,
// кто прошёл первый.
const funnel = [
  { step: 'site_visited', people: 10000 },      // зашли на сайт
  { step: 'catalog_viewed', people: 3200 },     // открыли каталог
  { step: 'cart_item_added', people: 1100 },    // положили товар в корзину
  { step: 'checkout_started', people: 640 },    // начали оформлять
  { step: 'order_paid', people: 410 },          // оплатили
];

// ─── 2. КОНВЕРСИЯ (conversion) ───
// Конверсия — доля перешедших с одного шага на следующий.
// Обычное деление, умноженное на 100, чтобы получить проценты.
// Считать надо ОБА вида: шаговую и сквозную, они отвечают
// на разные вопросы.
function describeFunnel(steps: typeof funnel): void {
  const top = steps[0].people;

  for (let i = 0; i < steps.length; i++) {
    const current = steps[i];
    const previous = i === 0 ? null : steps[i - 1];

    // Сквозная конверсия: от самого верха до этого шага.
    // Отвечает на вопрос «какая доля всех пришедших добралась сюда».
    const overall = (current.people / top) * 100;

    // Шаговая конверсия: от предыдущего шага к этому.
    // Отвечает на вопрос «насколько плох ИМЕННО ЭТОТ переход».
    const stepRate = previous === null ? 100 : (current.people / previous.people) * 100;

    // Отвал (drop-off) — сколько людей потерялось на этом переходе.
    const lost = previous === null ? 0 : previous.people - current.people;

    console.log(
      current.step,
      'людей:', current.people,
      'от начала:', overall.toFixed(1) + '%',
      'от прошлого шага:', stepRate.toFixed(1) + '%',
      'потеряли:', lost,
    );
  }
}

