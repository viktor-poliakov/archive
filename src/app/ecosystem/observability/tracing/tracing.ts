// БЕДА 1. ВОДОПАД СТАНОВИТСЯ НЕЧИТАЕМЫМ.
//   Вместо восьми строк, которые видны целиком, вы открываете трейс
//   на 140 спанов и листаете. Из них 132 короче миллисекунды.
//   Смысл водопада — увидеть проблему ГЛАЗАМИ, за три секунды.
//   Здесь этот смысл потерян полностью: искать секунду среди сотни
//   микросекундных полосок тяжелее, чем читать логи.

// БЕДА 2. ВЫ ПЛАТИТЕ ЗА ЭТО ДЕНЬГАМИ.
//   Хранилища трейсов считают спаны — либо напрямую (квота на спаны),
//   либо через объём данных. Разница между 8 и 140 спанами на запрос —
//   это в 17 раз больше денег за одно и то же понимание. При тысяче
//   запросов в секунду разница перестаёт быть теоретической.

// БЕДА 3. НАКЛАДНЫЕ РАСХОДЫ СТАНОВЯТСЯ ЗАМЕТНЫ.
//   Один спан сам по себе дешёвый: объект в памяти плюс два замера
//   времени. Но сто тридцать спанов на запрос — это уже работа,
//   сравнимая с самой обработкой. Особенно обидно, когда спан
//   оборачивает функцию на 0.01 мс: накладные расходы больше
//   измеряемого, то есть измерение врёт про само себя.

// БЕДА 4. ВАЖНОЕ ТОНЕТ В МЕЛОЧИ.
//   Спан «ждём ответ банка 2 секунды» и спан «отформатировали цену
//   0.01 мс» выглядят в списке одинаково. Внимание — ресурс, и вы
//   его тратите на разгребание шума, который создали сами.

// ═══ КАК НАДО. Правило трёх вопросов ═══
// Перед тем как обернуть шаг спаном, задайте три вопроса:
//
//   1) МОЖЕТ ЛИ ЭТОТ ШАГ ЗАНЯТЬ ЗАМЕТНОЕ ВРЕМЯ? Заметное — это
//      десятки миллисекунд и больше. Ожидание сети, диска, блокировки,
//      тяжёлый расчёт, шифрование, генерация файла — да. Перебор
//      массива из трёх элементов — нет.
//
//   2) МОЖЕТ ЛИ ОН УПАСТЬ САМ, ОТДЕЛЬНО ОТ ОСТАЛЬНОГО? Если у шага
//      есть своя причина отказа («банк не ответил», «промокод не
//      найден»), спан даст вам место, куда записать эту причину.
//
//   3) БУДУ ЛИ Я ПО НЕМУ ИСКАТЬ? Например: «покажи все заказы, где
//      применяли промокод и он не подошёл». Если такой вопрос
//      реалистичен — спан оправдан.
//
// Хотя бы два «да» — ставим спан. Один или ноль — не ставим,
// а нужные подробности кладём АТРИБУТОМ в уже существующий спан.
// Правило одной строкой: СПАН НА КАЖДУЮ ФУНКЦИЮ НЕ НУЖЕН.
// Спан — это шаг, который вам интересен как отрезок времени.

async function createOrderRight(cart, user) {
  // Спана на createOrder не делаем: мы уже внутри спана входящего
  // запроса, который создала автоматика. Второй такой же спан вокруг
  // всего обработчика — это просто дубль, он ничего не добавляет.

  const items = cart.items.map(mapItem);        // без спана
  const total = items.reduce(sumPrices, 0);     // без спана

  // А вот это — настоящий шаг: сеть, чужая служба, своя причина отказа,
  // и по нему точно будут искать. Три «да» из трёх.
  const promo = await tracer.startActiveSpan('promo.apply', async (span) => {
    try {
      // АТРИБУТЫ. Кладём то, что помогает ОТЛИЧИТЬ этот случай
      // от других таких же и понять, почему всё пошло не так.
      span.setAttribute('promo.code_hash', hashCode(cart.promoCode));
      span.setAttribute('cart.items_count', items.length);
      span.setAttribute('cart.total_minor', total);

      const result = await promoService.apply(cart.promoCode, total);

      // РЕШЕНИЕ, которое приняла программа, — самый полезный атрибут.
      // Именно по нему потом ищут: «покажи отказы с причиной expired».
      span.setAttribute('promo.applied', result.applied);
      if (!result.applied) {
        span.setAttribute('promo.reject_reason', result.reason);
      }
      return result;
    } catch (error) {
      // recordException кладёт в спан тип ошибки, сообщение и стек
      // как СОБЫТИЕ внутри спана.
      span.recordException(error);
      // А статус красит спан красным и делает его находимым
      // по фильтру «трейсы с ошибками». Без setStatus спан останется
      // серым, даже если внутри всё сгорело.
      span.setStatus({ code: SpanStatusCode.ERROR, message: 'promo service failed' });
      throw error;
    } finally {
      // ГЛАВНАЯ СТРОЧКА ВСЕГО ПРИМЕРА. end() в finally, а не после
      // return. Забытый end() — это не «спан без длительности»,
      // это ПОТЕРЯННЫЙ спан: он не уедет никуда и в водопаде
      // на его месте будет необъяснимая дырка.
      span.end();
    }
  });

  return { items, total, promo };
}

