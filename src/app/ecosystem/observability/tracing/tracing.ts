// ═══ ЧТО С ЭТИМ СЛУЧИТСЯ В БОЮ ═══

// БЕДА 1. ГОТОВЫЕ ДАШБОРДЫ ПОКАЗЫВАЮТ ПУСТОТУ.
//   Панели и правила, которые идут в комплекте с хранилищем, ищут
