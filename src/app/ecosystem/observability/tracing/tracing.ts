// понятными спанами 700 миллисекунд, и что там было — неизвестно.
// Ручной спан — это подпись на дырке.

// ═══ КАК ОБЫЧНО ДЕЛАЮТ. Спан на каждую функцию ═══
// Логика новичка понятна и по-своему честна: «спаны полезны, значит
