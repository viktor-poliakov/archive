// Никакой магии: у каждого спана есть parentSpanId, и этого достаточно.
// Хранилище просто раскладывает список в дерево одним проходом.

function buildTree(spans) {
  const byId = new Map();
  for (const span of spans) {
    byId.set(span.spanId, { ...span, children: [] });
  }

  const roots = [];
  for (const node of byId.values()) {
    const parent = node.parentSpanId ? byId.get(node.parentSpanId) : null;
    if (parent) {
      parent.children.push(node);      // нашли родителя — подвесили к нему
    } else {
      roots.push(node);                // родителя нет или он ещё не пришёл
    }
  }
  return roots;
}

