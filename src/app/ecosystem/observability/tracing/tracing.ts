const { getNodeAutoInstrumentations } = require('@opentelemetry/auto-instrumentations-node');

// Отправка спанов ПАЧКАМИ, а не по одному. Это важно: сетевой вызов
// на каждый спан стоил бы дороже самой работы, которую он измеряет.
const { BatchSpanProcessor } = require('@opentelemetry/sdk-trace-base');

const exporter = new OTLPTraceExporter({
  // Адрес приёмника. Путь /v1/traces — часть договора OTLP по HTTP.
  // Библиотека умеет дописывать его сама, если дать только хост,
  // но писать явно понятнее: сразу видно, куда стучимся.
  url: 'http://localhost:4318/v1/traces',

  // Сколько ждать ответ приёмника. Если коллектор лежит, попытка
  // не должна висеть вечно и держать память под очередь спанов.
  timeoutMillis: 10000,
});

const spanProcessor = new BatchSpanProcessor(exporter, {
  // Сколько спанов держим в очереди в памяти. Переполнилась — новые
  // спаны молча выбрасываются. Это правильное поведение: телеметрия
  // не имеет права уронить приложение, ради которого она существует.
  maxQueueSize: 2048,

  // Сколько спанов уходит в одном запросе к коллектору.
  maxExportBatchSize: 512,

  // Как часто отправлять, даже если пачка не набралась. 5 секунд —
  // это ваша задержка появления трейса в интерфейсе. Ставить 100 мс
  // не надо: получите поток мелких запросов вместо экономии.
  scheduledDelayMillis: 5000,

  // Таймаут на саму отправку пачки.
  exportTimeoutMillis: 30000,
});

const sdk = new NodeSDK({
  spanProcessors: [spanProcessor],

  instrumentations: [
    getNodeAutoInstrumentations({
      // ВЫКЛЮЧАЕМ датчик файловой системы. Он честно делает спан
      // на каждое чтение файла — и один запрос превращается в двести
      // спанов про чтение шаблонов. Это первое, что выключают все.
      '@opentelemetry/instrumentation-fs': { enabled: false },

      '@opentelemetry/instrumentation-http': {
        // Не трейсим служебные ручки. Проверка живости приходит раз
        // в 5 секунд от каждого балансировщика: это тысячи бесполезных
        // трейсов в час, за которые вы заплатите деньгами.
        ignoreIncomingRequestHook: (request) => {
          const url = request.url || '';
          return url.startsWith('/health') || url.startsWith('/metrics');
        },
      },
    }),
  ],
});

// Запуск. После этой строки датчики стоят и работают.
sdk.start();

// ═══ ЗАКРЫТИЕ: ПОЧЕМУ ЭТО НЕ ФОРМАЛЬНОСТЬ ═══
// Спаны лежат в очереди в памяти до 5 секунд. Если процесс просто
// убить, последняя пачка не уедет. И это будет ровно та пачка,
// в которой описано, как всё падало.
const shutdown = async () => {
  try {
    // shutdown принудительно отправляет всё, что накопилось, и ждёт.
    await sdk.shutdown();
  } catch (error) {
    // Телеметрия НЕ ИМЕЕТ ПРАВА мешать остановке. Записали и вышли.
    console.error('otel shutdown failed', error);
  } finally {
    process.exit(0);
  }
};

process.on('SIGTERM', shutdown);  // так останавливают контейнеры
process.on('SIGINT', shutdown);   // так останавливают вы, из терминала

