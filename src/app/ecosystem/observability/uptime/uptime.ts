// Обёртка «сделай, но не дольше чем». Promise.race возвращает результат
// того обещания, которое выполнилось первым: либо настоящая проверка,
// либо будильник на 800 миллисекунд.
function withTimeout(promise, milliseconds) {
  let timer;
  const alarm = new Promise((resolve, reject) => {
    timer = setTimeout(() => reject(new Error('timeout')), milliseconds);
  });
  return Promise.race([promise, alarm]).finally(() => clearTimeout(timer));
}

