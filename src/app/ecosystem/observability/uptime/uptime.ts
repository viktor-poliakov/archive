const REQUIRED_PARTS = ['whatIsBroken', 'whatStillWorks', 'whatWeDo', 'nextUpdateAt'];

// Стоп-слова: если они появились в тексте, сообщение написано неправильно.
const FORBIDDEN = [
  'латентность',        // говорите «сайт отвечает медленно»
  'upstream',           // покупателю неинтересно, кто ваш поставщик
  'кластер',            // это внутреннее устройство
  'деплой',             // тем более
  'по вине подрядчика', // виноватых наружу не выносят никогда
  'починим через',      // обещать можно только время следующего сообщения
  'единичные случаи',   // для того, у кого не работает, это 100% случаев
  'приносим извинения за возможные неудобства', // неудобства не «возможные»
];

function validateUpdate(update) {
  const problems = [];

  for (const part of REQUIRED_PARTS) {
    if (!update[part]) {
      problems.push('не заполнено обязательное поле: ' + part);
    }
  }

  const text = (update.whatIsBroken + ' ' + update.whatWeDo).toLowerCase();
  for (const word of FORBIDDEN) {
    if (text.includes(word)) {
      problems.push('стоп-слово в тексте: ' + word);
    }
  }

  // Ритм: следующее сообщение не позже чем через 30 минут, даже если
  // новостей нет. «Новостей нет, продолжаем разбираться» — это тоже
  // новость: она означает, что о людях не забыли.
  if (update.nextUpdateAt - update.at > 30 * 60 * 1000) {
    problems.push('слишком редкие обновления: обещайте следующее в пределах 30 минут');
  }

  return problems;
}

