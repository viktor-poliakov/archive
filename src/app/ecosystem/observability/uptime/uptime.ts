const { chromium } = require('playwright');

// Каждый шаг измеряем ОТДЕЛЬНО. Это ключевая мысль: полезен не факт
// «сценарий прошёл», а знание, ГДЕ именно он тормозит или ломается.
async function runCheckoutScenario() {
  const timings = {};
  const browser = await chromium.launch();
  const context = await browser.newContext({
    // Помечаем робота, чтобы его визиты не попали в продуктовую аналитику
    // и чтобы бэкенд мог отличать его заказы от настоящих.
    userAgent: 'synthetic-checkout/1.0 (+https://status.shop.ru)',
    extraHTTPHeaders: { 'X-Synthetic-Check': 'true' },
  });
  const page = await context.newPage();

  // Вспомогательная обёртка: выполнить шаг, замерить время,
  // при падении сказать, КАКОЙ ИМЕННО шаг упал.
  async function step(name, action) {
    const startedAt = Date.now();
    try {
      await action();
      timings[name] = Date.now() - startedAt;
    } catch (error) {
      timings[name] = Date.now() - startedAt;
      error.failedStep = name;
      throw error;
    }
  }

  try {
    await step('open_catalog', async () => {
      await page.goto('https://shop.ru/', { timeout: 15000 });
      // Ждём не «страница загрузилась», а конкретный элемент, без которого
      // покупка невозможна. Пустой каркас страницы нас не устраивает.
      await page.waitForSelector('.add-to-cart', { timeout: 10000 });
    });

    await step('login', async () => {
      await page.goto('https://shop.ru/login');
      await page.fill('input[name="email"]', process.env.SYNTHETIC_USER_EMAIL);
      await page.fill('input[name="password"]', process.env.SYNTHETIC_USER_PASSWORD);
      await page.click('button[type="submit"]');
      await page.waitForSelector('[data-test="account-menu"]', { timeout: 10000 });
    });

    await step('add_to_cart', async () => {
      // Товар — специально созданный, вечно доступный, с ценой 1 рубль,
      // невидимый в каталоге для настоящих покупателей.
      await page.goto('https://shop.ru/p/synthetic-test-item');
      await page.click('.add-to-cart');
      await page.waitForSelector('[data-test="cart-count"]:has-text("1")');
    });

    await step('checkout', async () => {
      await page.goto('https://shop.ru/checkout');
      await page.fill('input[name="address"]', 'Тестовый адрес, дом 1');
      await page.click('[data-test="place-order"]');
      // Ждём не «нет ошибки», а появление номера заказа. Только он
      // доказывает, что заказ действительно создан.
      await page.waitForSelector('[data-test="order-number"]', { timeout: 20000 });
    });

    reportSuccess(timings);
  } catch (error) {
    // В отчёт кладём: какой шаг, сколько ждали, скриншот и запись
    // сетевых запросов. Без этого дежурный получит «сценарий упал»
    // и будет полчаса воспроизводить его руками.
    const screenshot = await page.screenshot();
    reportFailure({ step: error.failedStep, message: error.message, timings, screenshot });
  } finally {
    await browser.close();
  }
}

