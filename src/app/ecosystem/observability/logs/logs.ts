// Промежуточный обработчик (middleware) — функция, через которую
// проходит каждый входящий запрос до основного кода.
function requestContextMiddleware(req, res, next) {
  const requestId = resolveRequestId(req);

  // Возвращаем номер клиенту — чтобы человек мог назвать его в
  // поддержке, а фронтенд — приложить к отчёту об ошибке.
  res.setHeader('x-request-id', requestId);

  const context = {
    requestId,
    method: req.method,
    route: req.route ? req.route.path : req.path,
    ip: anonymizeIp(req.ip),   // усечённый адрес: 95.108.213.0
    userId: null,              // появится после проверки входа
  };

  // run() открывает «кабинет»: всё, что случится внутри next(),
  // включая асинхронные продолжения, увидит этот context.
  requestContext.run(context, next);
}

// Достать контекст можно из любого места, ничего не передавая.
function currentContext() {
  return requestContext.getStore() || {};
}

