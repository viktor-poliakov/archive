const SILENT_ROUTES = new Set(['/healthz', '/readyz', '/metrics', '/favicon.ico']);

function accessLogMiddleware(req, res, next) {
  res.on('finish', () => {
    // Молчим про шумные маршруты — но только если ответ успешный.
    // Упавшая проверка здоровья — это как раз очень интересно.
    if (SILENT_ROUTES.has(req.path) && res.statusCode < 400) return;

    logger.info(
      {
        event: 'http.request.finished',
        method: req.method,
        route: req.route ? req.route.path : req.path,
        status: res.statusCode,
        durationMs: Date.now() - req.startedAt,
      },
      'ответ отправлен',
    );
  });
  next();
}

// ═══ КАК НАДО. ПРИЁМ 4: ЗАЩИТА ОТ ПОВТОРЯЮЩЕЙСЯ ОШИБКИ ═══
// Внешний сервис лёг — и каждый запрос пишет одну и ту же ошибку.
// Тысяча одинаковых строк в секунду не добавляет ни бита знания,
// зато переполняет буфер агента и вытесняет всё остальное.

function createThrottledLogger(windowMs) {
  const lastSeen = new Map();
  return function logOnce(key, level, fields, message) {
    const now = Date.now();
    const previous = lastSeen.get(key) || 0;
    if (now - previous < windowMs) return;   // молчим: уже писали недавно
    lastSeen.set(key, now);
    logger[level]({ ...fields, throttled: true, windowMs }, message);
  };
}

