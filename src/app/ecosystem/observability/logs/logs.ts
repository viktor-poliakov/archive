const express = require('express');
const { logger, requestLogger, currentContext } = require('./logger');

const app = express();

// ПОРЯДОК ВАЖЕН: requestLogger идёт ПЕРВЫМ, до всех остальных
// обработчиков. Иначе часть строк окажется без requestId — а это
// именно те строки, которые пишутся до него, то есть самые ранние
// и самые интересные при разборе.
app.use(requestLogger);

app.use(async (req, res, next) => {
  const user = await authenticate(req);
  if (user) {
    // Дописываем userId в уже существующий контекст: с этого места
    // ВСЕ последующие строки запроса получат его автоматически.
    currentContext().userId = user.id;
  }
  next();
});

app.post('/api/checkout', async (req, res, next) => {
  // Ни requestId, ни userId, ни service здесь не упоминаются —
  // и всё это будет в готовой строке лога.
  logger.debug({ event: 'checkout.started' }, 'начинаем оформление');
  try {
    const order = await createOrder(req.body);
    logger.info({ event: 'order.created', orderId: order.id, total: order.total },
                'заказ создан');
    res.status(201).json({ orderId: order.id });
  } catch (err) {
    next(err);   // отдаём общему обработчику ошибок — там одна запись
  }
});

// Общий обработчик ошибок: ЕДИНСТВЕННОЕ место, где логируются
// неожиданные падения. Клиенту отдаём requestId, чтобы человек мог
// назвать его в поддержке; ничего больше наружу не уходит.
app.use((err, req, res, next) => {
  logger.error({ err, event: 'request.unhandled_error' }, 'необработанная ошибка');
  res.status(500).json({
    error: 'Внутренняя ошибка',
    requestId: currentContext().requestId,
  });
});

// Аварийные ситуации всего процесса — обязательно, иначе падение
// останется без единой строки в логах.
process.on('uncaughtException', (err) => {
  logger.fatal({ err }, 'необработанное исключение, выходим');
  process.exit(1);
});
process.on('unhandledRejection', (err) => {
  logger.fatal({ err }, 'необработанный отказ обещания, выходим');
  process.exit(1);
});

const server = app.listen(process.env.PORT || 3000, () => {
  logger.info({ event: 'service.started', port: server.address().port },
              'сервис запущен');
});

