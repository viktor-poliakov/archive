// ═══ КАК НАДО. ПРИЁМ 2: СЭМПЛИРОВАНИЕ ═══
// Сэмплирование (sampling) — «пиши не все, а каждую N-ю». Годится
// для строк, которые важны как поток, а не поштучно.
// Аналогия: контроль качества на конвейере. Не проверяют каждую
// бутылку — берут одну из сотни и по ней судят о партии.

function createSampler(everyNth) {
  let seen = 0;
  return function shouldLog() {
    seen++;
    return seen % everyNth === 0;
  };
}

const sampleCacheMiss = createSampler(100);   // одна строка из ста

function readFromCache(key) {
  const value = cache.get(key);
  if (value === undefined && sampleCacheMiss()) {
    // sampled: true — обязательное поле! Иначе кто-нибудь через
    // полгода посчитает по этим строкам число промахов кэша
    // и получит цифру в сто раз меньше настоящей.
    logger.debug({ event: 'cache.miss', key, sampled: true, sampleRate: 100 },
                 'промах кэша (образец)');
  }
  return value;
}

