// ─── ВАРИАНТ 3. Частичное маскирование ───
// Иногда значение нужно для разбора, но целиком его хранить нельзя.
// Тогда оставляют «хвостик», по которому человек узнает своё,
// а посторонний ничего не восстановит.

function maskEmail(value) {
  // anna@shop.ru → a***@shop.ru
  const at = String(value).indexOf('@');
  if (at < 1) return '[скрыто]';
  return String(value)[0] + '***' + String(value).slice(at);
}

function maskPhone(value) {
  // +79161234567 → +7916***4567
  const digits = String(value).replace(/\\D/g, '');
  if (digits.length < 8) return '[скрыто]';
  return '+' + digits.slice(0, 4) + '***' + digits.slice(-4);
}

function maskCard(value) {
  // 4276380012345678 → 427638******5678 (это допустимая форма показа)
  const digits = String(value).replace(/\\D/g, '');
  if (digits.length < 12) return '[скрыто]';
  return digits.slice(0, 6) + '*'.repeat(digits.length - 10) + digits.slice(-4);
}

function anonymizeIp(ip) {
  // 95.108.213.44 → 95.108.213.0
  const parts = String(ip).split('.');
  if (parts.length !== 4) return '[скрыто]';
  parts[3] = '0';
  return parts.join('.');
}

