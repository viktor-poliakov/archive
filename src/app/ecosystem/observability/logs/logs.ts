// ─── Промежуточный обработчик: номер запроса и лог доступа ───
const SILENT_ROUTES = new Set(['/healthz', '/readyz', '/metrics']);

function anonymizeIp(ip) {
  const parts = String(ip || '').split('.');
  if (parts.length !== 4) return null;
  parts[3] = '0';
  return parts.join('.');
}

function resolveRequestId(req) {
  const incoming = req.headers['x-request-id'];
  if (typeof incoming === 'string' && /^[a-zA-Z0-9._-]{8,64}$/.test(incoming)) {
    return incoming;
  }
  return crypto.randomUUID();
}

function requestLogger(req, res, next) {
  const requestId = resolveRequestId(req);
  const startedAt = process.hrtime.bigint();

  res.setHeader('x-request-id', requestId);

  const context = {
    requestId,
    userId: null,                      // заполнит проверка входа
    route: req.path,
    ip: anonymizeIp(req.ip),
  };

  requestContext.run(context, () => {
    res.on('finish', () => {
      if (SILENT_ROUTES.has(req.path) && res.statusCode < 400) return;

      const durationMs = Number(process.hrtime.bigint() - startedAt) / 1e6;

      // Уровень зависит от кода ответа. Это важная деталь:
      // 4xx — вина клиента (info), 5xx — наша вина (error).
      const level = res.statusCode >= 500 ? 'error' : 'info';

      logger[level](
        {
          event: 'http.request.finished',
          method: req.method,
          route: req.route ? req.route.path : req.path,
          status: res.statusCode,
          durationMs: Math.round(durationMs * 100) / 100,
          ip: context.ip,
        },
        'запрос обработан',
      );
    });

    next();
  });
}

