// ═══ КАК НАДО. ШАГ 1: ОТКУДА БЕРЁТСЯ НОМЕР ═══
// Правило: если номер уже пришёл во входящем заголовке — берём его.
// Если нет — придумываем свой. Заголовок (header) — это строка
// «имя: значение», которую прикладывают к HTTP-запросу как ярлык
// к посылке; тело запроса при этом не меняется.

const crypto = require('node:crypto');

function resolveRequestId(req) {
  // Три обычных имени заголовка. Первое — от обратного прокси nginx,
  // второе — общепринятое неформальное, третье — стандартное поле
  // распределённой трассировки.
  const incoming =
    req.headers['x-request-id'] ||
    req.headers['x-correlation-id'] ||
    parseTraceparent(req.headers['traceparent']);

  // ВАЖНО про доверие: заголовок пришёл извне, то есть его мог
  // подставить кто угодно. Поэтому чужое значение мы принимаем,
  // но проверяем форму — иначе в наши логи попадёт строка на
  // двадцать килобайт или что-нибудь с переводами строк.
  if (typeof incoming === 'string' && /^[a-zA-Z0-9._-]{8,64}$/.test(incoming)) {
    return incoming;
  }
  return crypto.randomUUID();
}

// О traceparent стоит сказать отдельно, потому что это настоящий
// стандарт, а не самодельное соглашение. Заголовок traceparent описан
// в спецификации W3C Trace Context: её первый уровень (Level 1) —
// полноценная рекомендация W3C, а второй уровень на сегодня — только
// черновик (Candidate Recommendation Draft). Внутри traceparent
// лежат четыре части через дефис: версия, идентификатор трейса,
// идентификатор родительского участка и флаги.
// Рядом с ним живёт tracestate — список дополнительных значений,
// не более 32 членов. Подробно — на странице про трейсинг.

function parseTraceparent(value) {
  if (typeof value !== 'string') return null;
  const parts = value.split('-');
  // 00-4bf92f3577b34da6a3ce929d0e0e4736-00f067aa0ba902b7-01
  //     ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^ вот это и есть traceId
  if (parts.length !== 4 || parts[1].length !== 32) return null;
  return parts[1];
}

