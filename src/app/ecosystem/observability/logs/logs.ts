// ═══ КАК НАДО. ПРИЁМ 1: ИТОГИ ВМЕСТО КАЖДОГО ШАГА ═══
// Правило: в цикле логируем только НЕОБЫЧНОЕ, а обычное — считаем
// и пишем один раз в конце.

async function syncCatalogFixed(products) {
  const startedAt = Date.now();
  const stats = { total: products.length, updated: 0, skipped: 0, failed: 0 };
  const failedSkus = [];

  for (const product of products) {
    // Каждый шаг — на уровне trace. В продакшене этих строк нет
    // вообще, но при разборе их можно включить на пять минут.
    logger.trace({ sku: product.sku }, 'обрабатываю товар');

    try {
      const result = await upsertProduct(product);
      if (result.updated) stats.updated++;
      else stats.skipped++;
    } catch (err) {
      stats.failed++;
      // Ошибки логируем всегда — но не более 20 подробных строк,
      // чтобы сломанный внешний сервис не залил хранилище.
      if (stats.failed <= 20) {
        logger.error({ err, sku: product.sku }, 'товар не удалось обновить');
      }
      if (failedSkus.length < 100) failedSkus.push(product.sku);
    }
  }

  // ОДНА строка с полной картиной. Именно её будут читать.
  logger.info(
    {
      event: 'catalog.sync.finished',
      ...stats,
      failedSkusSample: failedSkus.slice(0, 10),   // образец, а не весь список
      durationMs: Date.now() - startedAt,
    },
    'синхронизация каталога завершена',
  );
}
