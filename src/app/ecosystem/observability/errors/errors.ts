const MASK = '[вычищено]';

// Рекурсивный обход: вложенные объекты и массивы тоже проверяем.
// Ограничитель глубины обязателен — иначе на объекте со ссылкой
// на самого себя обход зациклится и уронит процесс прямо в момент
// отправки ошибки. Это очень обидный способ сломать приложение.
function scrub(value, depth = 0) {
  if (depth > 6 || value == null) return value;

  if (Array.isArray(value)) {
    return value.map((item) => scrub(item, depth + 1));
  }

  if (typeof value === 'object') {
    const result = {};
    for (const [key, item] of Object.entries(value)) {
      const isSensitive = SENSITIVE_KEYS.some((k) => key.toLowerCase().includes(k));
      result[key] = isSensitive ? MASK : scrub(item, depth + 1);
    }
    return result;
  }

  if (typeof value === 'string') {
    return value
      // Адреса почты в свободном тексте: «не найден user@mail.ru».
      .replace(/[\\w.+-]+@[\\w-]+\\.[\\w.]+/g, '[почта]')
      // Длинные последовательности цифр: карты, телефоны, паспорта.
      .replace(/\\b\\d{12,19}\\b/g, '[число]')
      // Токены в стиле JWT: три части через точку.
      .replace(/\\beyJ[\\w-]+\\.[\\w-]+\\.[\\w-]+/g, '[токен]');
  }

  return value;
}

