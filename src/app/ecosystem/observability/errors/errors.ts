const Sentry = require('@sentry/node');

async function createOrderProperly(cart, user, flags) {
  try {
    return await gateway.charge(cart);
  } catch (error) {
    // withScope создаёт временный «конверт» контекста, который живёт
    // только до конца этого блока. Всё, что в него положили, уедет
    // с этим одним отчётом и не протечёт в соседние запросы. Именно
    // из-за протечек не стоит пользоваться глобальным setTag в коде
    // обработчиков: он останется висеть и приклеится к чужим ошибкам.
    Sentry.withScope((scope) => {
      // ТЕГИ — короткие значения из небольшого набора вариантов.
      // По ним можно фильтровать и группировать в интерфейсе, поэтому
      // в теги нельзя писать то, у чего много разных значений
      // (идентификаторы заказов, время, адреса почты) — это забивает
      // хранилище и делает фильтры бесполезными.
      scope.setTag('payment_method', cart.paymentMethod);     // 'saved_card'
      scope.setTag('gateway', 'acquirer-a');
      scope.setTag('feature_flag.new_checkout', flags.newCheckout ? 'on' : 'off');

      // КОНТЕКСТ — произвольные структуры для чтения глазами.
      // Здесь можно то, что нельзя в теги: числа, вложенные объекты.
      scope.setContext('cart', {
        id: cart.id,
        total: cart.total,
        itemsCount: cart.items.length,
        currency: cart.currency,
      });
      scope.setContext('gateway_response', {
        code: error.responseCode,        // '402_TOKEN_EXPIRED'
        requestId: error.gatewayRequestId,
        attempt: error.attempt,
      });

      // ПОЛЬЗОВАТЕЛЬ — то, из чего служба считает «сколько людей
      // задето». Без id это число всегда будет нулём.
      // Ставим ИДЕНТИФИКАТОР, а не почту и не телефон: чтобы посчитать
      // задетых людей, персональные данные не нужны.
      scope.setUser({ id: user.id, segment: user.segment });

      // УРОВЕНЬ. Не всё, что мы отправляем, — катастрофа.
      //   'fatal'   — приложение не может продолжать;
      //   'error'   — сценарий пользователя сломался;
      //   'warning' — плохо, но обошлось (сработал запасной путь);
      //   'info'    — просто заметка.
      scope.setLevel(error.retriable ? 'warning' : 'error');

      Sentry.captureException(error);
    });

    // Пробрасываем ошибку дальше, но НЕ теряем исходную: свойство cause
    // (стандарт JavaScript) сохраняет причину внутри новой ошибки.
    throw new Error('Не удалось оплатить заказ', { cause: error });
  }
}

