// Не больше 5 событий одного вида в минуту с одной вкладки.
const seen = new Map();

function allowByRateLimit(error) {
  const key = (error && error.name ? error.name : 'unknown') + ':' + (error && error.message ? error.message.slice(0, 60) : '');
  const now = Date.now();
  const entry = seen.get(key) || { count: 0, windowStart: now };

  if (now - entry.windowStart > 60000) {
    entry.count = 0;
    entry.windowStart = now;
  }

  entry.count += 1;
  seen.set(key, entry);
  return entry.count <= 5;
}

