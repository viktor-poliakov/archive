    // Чинить по такому событию нечего, оно приходит пустым.
    // Лечится не фильтром, а атрибутом crossorigin на теге script
    // и заголовком Access-Control-Allow-Origin на раздаче.
    if (event.message === 'Script error.') return null;

    // (д) Ограничение частоты. Один сломанный цикл на странице
    // способен отправить десять тысяч одинаковых событий за минуту
    // с одного устройства и съесть месячную квоту до обеда.
    if (!allowByRateLimit(error)) return null;

