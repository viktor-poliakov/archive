const Sentry = require('@sentry/node');

async function applyPromoCode(cartId, code) {
  // Крошка ДО действия: если упадёт внутри, мы будем знать, на чём.
  Sentry.addBreadcrumb({
    category: 'cart',                 // своя категория — по ней потом фильтруют
    message: 'Применение промокода',
    level: 'info',
    data: {
      cartId,
      // ВНИМАНИЕ: сам код промокода — не персональные данные,
      // его писать можно. А вот номер телефона тут писать нельзя.
      promoCode: code,
    },
  });

  const cart = await db.carts.findById(cartId);
  const promo = await db.promos.findByCode(code);

  if (!promo) {
    // Это НЕ ошибка приложения — это нормальный отказ. В службу
    // отслеживания ошибок такое не отправляют, иначе она заполнится
    // опечатками пользователей. Но крошку оставить полезно:
    // если человек упадёт через три шага, мы увидим, что до этого
    // он трижды вводил неверный промокод.
    Sentry.addBreadcrumb({
      category: 'cart',
      message: 'Промокод не найден',
      level: 'warning',
      data: { promoCode: code },
    });
    return { ok: false, reason: 'not_found' };
  }

  const discount = calcDiscount(cart, promo);

  Sentry.addBreadcrumb({
    category: 'cart',
    message: 'Промокод применён',
    level: 'info',
    data: { promoCode: code, discount, total: cart.total - discount },
  });

  return { ok: true, discount };
}

