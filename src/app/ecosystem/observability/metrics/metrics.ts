// СЧЁТЧИК 2. НЕУСПЕШНЫЕ ОПЛАТЫ, РАЗЛОЖЕННЫЕ ПО ПРИЧИНЕ.
const paymentFailures = new client.Counter({
  name: 'payment_failures_total',
  help: 'Сколько попыток оплаты закончились неудачей',
  labelNames: ['provider', 'reason'],
});

// Причина приходит ОТ ЧУЖОГО СЕРВИСА, значит может быть какой угодно
// строкой, вплоть до текста ошибки с номером транзакции внутри.
// Сводим её к своему конечному списку — иначе провайдер однажды
// сам того не зная взорвёт вам хранилище метрик.
const KNOWN_FAILURE_REASONS = [
  'insufficient_funds',   // не хватило денег — это норма, не авария
  'card_expired',
  'declined_by_bank',
  'timeout',              // а вот это уже наша боль
  'provider_error',
];

function normalizeReason(rawReason) {
  return KNOWN_FAILURE_REASONS.includes(rawReason) ? rawReason : 'other';
}

// ─── ГДЕ ИМЕННО СТАВИТЬ УВЕЛИЧЕНИЕ СЧЁТЧИКА ───
async function createOrder(cart, channel) {
  const order = await db.transaction(async (trx) => {
    const created = await trx.orders.insert(cart);
    await trx.orderItems.insertMany(created.id, cart.items);
    return created;
  });

  // ВАЖНО: счётчик увеличиваем ПОСЛЕ того, как транзакция
  // зафиксирована в базе. Не в начале обработчика, не в середине.
  // Метрика должна означать «заказ действительно существует»,
  // а не «мы попытались его создать».
  ordersCreated.inc({ channel });
  return order;
}

async function chargeCard(order, provider) {
  try {
    const result = await provider.charge(order.amount);

    // Провайдер может ответить HTTP 200 и при этом отказать.
    // Смотрим на СМЫСЛ ответа, а не на код HTTP.
    if (result.status !== 'approved') {
      paymentFailures.inc({
        provider: provider.name,
        reason: normalizeReason(result.declineCode),
      });
      return { ok: false };
    }
    return { ok: true };
  } catch (error) {
    // Сеть отвалилась, таймаут, провайдер лежит — это тоже
    // неуспешная оплата, и она обязана попасть в тот же счётчик.
    paymentFailures.inc({ provider: provider.name, reason: 'timeout' });
    throw error;
  }
}

