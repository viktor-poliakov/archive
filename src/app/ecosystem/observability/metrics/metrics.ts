// ─── ШАГ 2. СЧИТАЕМ p95 РУКАМИ, КАК ЭТО ДЕЛАЕТ ХРАНИЛИЩЕ ───
function quantileFromBuckets(buckets, p) {
  const totalCount = buckets[buckets.length - 1].count;   // 41208

  // Какое по счёту наблюдение нас интересует? 95% от общего числа.
  const targetRank = p * totalCount;                      // 39147.6

  // Ищем первый ящик, в котором накопилось столько или больше.
  let previous = { le: 0, count: 0 };
  for (const bucket of buckets) {
    if (bucket.count >= targetRank) {
      // Нашли: искомое значение лежит между границей предыдущего
      // ящика и границей этого. Ниже 0.1 накопилось 31022,
      // ниже 0.25 — 40100, а нам нужно 39147.6 — значит,
      // ответ где-то между 100 и 250 мс.
      //
      // Точнее хранилище не знает: внутри ящика оно НЕ ВИДИТ, как
      // распределены наблюдения. Поэтому оно ПРЕДПОЛАГАЕТ, что внутри
      // ящика значения размазаны ровно, и делит промежуток
      // пропорционально. Это называется линейной интерполяцией.
      const bucketWidth = bucket.le - previous.le;             // 0.15
      const needInside = targetRank - previous.count;          // 8125.6
      const bucketPopulation = bucket.count - previous.count;  // 9078
      return previous.le + bucketWidth * (needInside / bucketPopulation);
      // 0.1 + 0.15 * 0.895 ≈ 0.234 → p95 ≈ 234 мс
    }
    previous = bucket;
  }
  return Infinity;
}

