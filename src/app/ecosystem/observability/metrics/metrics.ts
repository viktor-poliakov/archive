// ─── ШАГ 6. НОРМАЛИЗАЦИЯ МАРШРУТА — САМАЯ ВАЖНАЯ ФУНКЦИЯ В ФАЙЛЕ ───
// В метку route НЕЛЬЗЯ писать req.path. Путь содержит идентификаторы:
// /api/orders/1043, /api/orders/1044, /api/orders/1045 — это три разных
// значения метки, то есть три разных ряда. К вечеру их будет миллион.
// Нужен ШАБЛОН маршрута: /api/orders/:id — один на все заказы.
function normalizeRoute(req) {
  // Express знает шаблон, по которому сработал обработчик.
  // req.route.path даёт '/:id', req.baseUrl — префикс роутера.
  if (req.route && req.route.path) {
    return (req.baseUrl || '') + req.route.path;   // '/api/orders/:id'
  }
  // Сюда попадают запросы, не совпавшие ни с одним маршрутом:
  // сканеры, опечатки, чужие боты. Их путь — произвольный текст
  // от постороннего человека, и пускать его в метку нельзя ни в каком
  // виде: это подарок тому, кто захочет положить наш мониторинг.
  // Поэтому ОДНО фиксированное значение на все такие запросы.
  return 'unmatched';
}

// ─── ШАГ 7. ПОСРЕДНИК, КОТОРЫЙ ВСЁ ЭТО ЗАПОЛНЯЕТ ───
