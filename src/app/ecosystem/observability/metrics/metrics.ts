// ═══ КАК НАДО ═══
// Правило одной фразой: В МЕТКУ МОЖНО КЛАСТЬ ТОЛЬКО ТО, У ЧЕГО
// ЗАРАНЕЕ ИЗВЕСТЕН КОРОТКИЙ СПИСОК ВОЗМОЖНЫХ ЗНАЧЕНИЙ.
// Не «мало значений сегодня», а «список известен заранее и не растёт
// сам по себе от действий пользователей».

// ПРИЁМ 1. НОРМАЛИЗАЦИЯ МАРШРУТА ДО ШАБЛОНА.
// Нам почти никогда не нужен адрес конкретного заказа. Нам нужен
// ШАБЛОН маршрута: не /orders/9f31.../items, а /orders/:id/items.
// Шаблонов в приложении конечное число — ровно столько, сколько
// вы написали обработчиков.

function routeTemplate(req) {
  // В Express шаблон уже есть — фреймворк сам его знает.
  // req.route.path даёт '/orders/:id/items' вместо реального адреса.
  if (req.route && req.route.path) {
    const base = req.baseUrl || '';
    return base + req.route.path;
  }
  // Запрос, не попавший ни в один обработчик (чужие сканеры, опечатки),
  // не должен плодить ряды. Все такие складываем в одну корзину.
  return 'unmatched';
}

// ПРИЁМ 2. ОГРАНИЧЕННЫЙ СПИСОК ЗНАЧЕНИЙ («белый список»).
// Если значение приходит извне — из заголовка, из параметра запроса,
// от платёжного провайдера, — считайте его враждебным. Пропускайте
// через список известных, всё остальное схлопывайте в 'other'.

function limitLabel(value, allowedValues) {
  return allowedValues.includes(value) ? value : 'other';
}

const KNOWN_CLIENTS = ['web', 'ios', 'android'];
const KNOWN_STATUS_CLASSES = ['2xx', '3xx', '4xx', '5xx'];

function statusClass(statusCode) {
  // Отдельные ряды на 200, 201 и 204 обычно не нужны. Класс ответа —
  // нужен всегда. Четыре значения вместо шести десятков.
  return Math.floor(statusCode / 100) + 'xx';
}

// ПРИЁМ 3. ЗДОРОВАЯ ВЕРСИЯ ТОГО ЖЕ САМОГО СЧЁТЧИКА.
const healthyCounter = new client.Counter({
  name: 'http_requests_total',
  help: 'Сколько всего запросов обработано',
  labelNames: ['method', 'route', 'status_class', 'client'],
});

app.use((req, res, next) => {
  res.on('finish', () => {
    healthyCounter.inc({
      method: req.method,                                   // ~5 значений
      route: routeTemplate(req),                            // ~40 значений
      status_class: limitLabel(statusClass(res.statusCode),
                               KNOWN_STATUS_CLASSES),       // 4 значения
      client: limitLabel(req.get('x-client') || 'web',
                         KNOWN_CLIENTS),                    // 3 значения
    });
  });
  next();
});
