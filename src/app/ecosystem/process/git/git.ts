      - "Ничего не переписывается, хеши коммитов сохраняются"
      - "Видны границы задачи, вся задача откатывается одним коммитом"
    cons:
      - "История с развилками, git log читается сложнее"
      - "В main попадают все промежуточные коммиты, включая «опечатка»"

  squash_merge:
    what: "Все коммиты ветки склеиваются в ОДИН новый коммит в main"
    history: "Идеально прямая: одна задача — один коммит"
    pros:
      - "Промежуточный шум («wip», «опечатка») не попадает в main"
      - "Откат задачи — это откат ровно одного коммита"
      - "Самый прощающий вариант: можно не наводить порядок в своей ветке"
    cons:
      - "Теряются отдельные шаги: крупная задача становится одним пятном"
      - "Ветка после склейки считается невлитой — удалять руками"

  rebase_merge:
    what: "Коммиты ветки переносятся поверх main по одному, без коммита слияния"
    history: "Прямая, но каждый коммит сохранён отдельно"
    pros:
      - "Линейная история и при этом видны все шаги"
    cons:
      - "Хеши меняются (см. секцию про перебазирование)"
      - "Требует, чтобы коммиты в ветке были аккуратными — каждый из них"
      - "останется в main навсегда"

