export function applyPromoAt(total, promo, now) {
  if (promo.endsAt && now >= new Date(promo.endsAt)) {
    return total;                       // код просрочен — сумма без изменений
  }
  return applyPromo(total, promo);
}

// ─── РЕФАКТОР ───
// Теперь, когда четыре теста держат поведение, можно навести порядок:
// вынести типы кодов в таблицу, чтобы добавление нового типа не
// требовало правки условий.

const STRATEGIES = {
  percent: (total, value) => total - (total * value) / 100,
  amount: (total, value) => total - value,
};

export function applyPromoAt(total, promo, now) {
  if (promo.endsAt && now >= new Date(promo.endsAt)) return total;

  const strategy = STRATEGIES[promo.type];
  if (!strategy) return total;          // неизвестный тип — не применяем

  return Math.max(0, Math.round(strategy(total, promo.value)));
}

