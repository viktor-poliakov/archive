//   number, там правда number, потому что все значения родились внутри
//   и прошли через проверяющего.
//   СНАРУЖИ линии — сеть, файлы, база, хранилище браузера, переменные
//   окружения, ввод пользователя. Оттуда приезжает то, что приезжает.
//   На самой линии стоит охранник, который вскрывает каждую коробку
//   и смотрит, что внутри. Этого охранника надо поставить руками — сам
//   он не появится.

