const UserPrefsSchema = z.object({
  theme: z.enum(['light', 'dark', 'system']).default('system'),
  fontSize: z.number().int().min(10).max(32).default(14),
  sidebarOpen: z.boolean().default(true),
});

type UserPrefs = z.infer<typeof UserPrefsSchema>;

function loadPrefs(): UserPrefs {
  const stored = localStorage.getItem('prefs');
  if (stored === null) {
    return UserPrefsSchema.parse({});   // все значения по умолчанию
  }

  let raw: unknown;
  try {
    raw = JSON.parse(stored);
  } catch {
    // Там мог лежать мусор — например, обрывок от старой версии.
    return UserPrefsSchema.parse({});
  }

  const parsed = UserPrefsSchema.safeParse(raw);
  if (!parsed.success) {
    // Форма устарела — не падаем, а мягко откатываемся к умолчаниям.
    // Это как раз тот случай, когда ошибка данных НЕ должна ломать экран.
    localStorage.removeItem('prefs');
    return UserPrefsSchema.parse({});
  }

  return parsed.data;
}

