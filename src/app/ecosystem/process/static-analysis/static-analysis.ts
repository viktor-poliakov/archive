const RowSchema = z.object({
  email: z.email(),
  amount: z.coerce.number().nonnegative(),
});

function importRows(rows: unknown[]): { ok: z.infer<typeof RowSchema>[]; bad: string[] } {
  const ok: z.infer<typeof RowSchema>[] = [];
  const bad: string[] = [];

  rows.forEach((row, index) => {
    const parsed = RowSchema.safeParse(row);
    if (parsed.success) {
      ok.push(parsed.data);
    } else {
      // Для загруженного файла падать на первой плохой строке — плохая идея.
      // Пользователю нужен отчёт: что именно и в какой строке не так.
      bad.push('Строка ' + (index + 2) + ': ' + z.prettifyError(parsed.error));
    }
  });

  return { ok, bad };
}

