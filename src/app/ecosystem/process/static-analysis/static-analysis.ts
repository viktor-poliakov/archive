// ═══ ЧТО СЛУЧИТСЯ В БОЮ ═══
//
// Бэкенд-разработчик поменял сериализацию, и теперь возраст приходит строкой.
// Ответ сервера:
//
//   { "id": 7, "name": "Мария", "age": "31", "isAdmin": false }
//
// БЕДА 1. Молчаливо неверный результат.
//   'Через год будет ' + ('31' + 1)  →  'Через год будет 311'
//   Ничего не упало. В интерфейсе просто написана чушь. Такое живёт месяцами.
//
// БЕДА 2. Падение в неожиданном месте.
//   Если бы сервер прислал name: null, строка user.name.toUpperCase()
//   упала бы с TypeError. Причём падение произошло бы в компоненте, который
//   ни в чём не виноват, — а виноват тот, кто написал «: ApiUser» без проверки.
//
// БЕДА 3. Отладка идёт не туда.
//   Разработчик смотрит на стек ошибки, видит компонент профиля и час чинит
//   компонент профиля. Настоящая причина — в сетевом слое, за три файла отсюда.
//
