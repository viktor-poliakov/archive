interface ApiUser {
  id: number;
  name: string;
  age: number;
  isAdmin: boolean;
}

async function loadUser(id: number): Promise<ApiUser> {
  const response = await fetch('/api/users/' + id);
  // ↓ ВОТ ЗДЕСЬ ПРОИСХОДИТ ВСЁ ЗЛО, и оно выглядит абсолютно невинно.
  const user: ApiUser = await response.json();
  return user;
}

async function show(id: number) {
  const user = await loadUser(id);
  console.log(user.name.toUpperCase());
  console.log('Через год будет ' + (user.age + 1));
}

// Проверяющий доволен. Красного подчёркивания нет ни в одной строке.
// В редакторе автодополнение показывает id, name, age, isAdmin.
// Всё выглядит безопасным.

// ═══ ВО ЧТО ЭТО ПРЕВРАЩАЕТСЯ ПОСЛЕ КОМПИЛЯЦИИ ═══
