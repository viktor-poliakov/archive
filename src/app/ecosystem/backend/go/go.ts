// одного конкретного сервиса — и переписали НА GO ТОЛЬКО ЕГО.
// Не всё приложение, а один узел: обработку платежей, шлюз API,
// сервис уведомлений. Именно поэтому Go так часто встречается
// в описаниях вакансий рядом с другими языками, а не вместо них.`;
