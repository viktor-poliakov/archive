// Не «добавь», не «поправь», а «пусть лежит вот это, и точка».
app.put('/products/:id', async (req, res) => {
  const { name, price, color } = req.body;

  // Раз это замена целиком — требуем все обязательные поля.
  // Замена без половины полей — это не замена, а недоразумение.
  if (!name || typeof price !== 'number') {
    return res.status(400).json({ error: 'Для PUT нужны все поля товара' });
  }

  // Запись перезаписывается ЦЕЛИКОМ. Клиент не прислал color —
  // сюда приедет undefined, и в базе поле обнулится.
  const product = await db.replaceProduct(req.params.id, { name, price, color });
  res.status(200).json(product);
});


