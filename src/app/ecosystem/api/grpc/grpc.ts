// ВИД 4: ПОТОК В ОБЕ СТОРОНЫ. Оба говорят, когда захотят.
// Живой случай: сервис такси. Машина шлёт свои координаты каждые две секунды,
// а диспетчер в ответ — новые заказы и изменения маршрута.
//
//   rpc DriverChannel (stream DriverEvent) returns (stream DispatchEvent);

async *driverChannel(incoming) {
  // Слушаем то, что шлёт машина...
  for await (const event of incoming) {
    await db.saveLocation(event.driverId, event.lat, event.lng);

    // ...и в любой момент можем ответить своим сообщением.
    const job = await dispatcher.findJobFor(event.driverId);
    if (job) {
      yield { type: 'NEW_JOB', jobId: job.id, address: job.address };
    }
  }
}

// ВАЖНО НЕ ПЕРЕПУТАТЬ. Это НЕ «вопрос — ответ, вопрос — ответ».
// Два потока полностью независимы: сервер может молчать десять минут,
// а потом прислать три сообщения подряд, никем не спрошенный.`;

