    // меняю я, остальные подождите». Второй участник дождётся и прочитает
    // УЖЕ новый статус — одновременные изменения встают в очередь.
    const { rows } = await tx.query('SELECT status FROM orders WHERE id = $1 FOR UPDATE', [orderId]);
