// Строка из product_variants: вес голого изделия (г) и его размеры (мм)
type VariantSize = { weight_g: number; length_mm: number; width_mm: number; height_mm: number };
// Посылка в единицах СДЭК: вес в граммах, габариты в сантиметрах
type Parcel = { weight: number; length: number; width: number; height: number };

// Коробки «Обжига»: внешние размеры в см (по убыванию) и вес упаковки в граммах —
// внешняя коробка с двойной стенкой, внутренняя коробка, пупырчатая плёнка, бумага
const BOXES = [
  { sizeCm: [20, 15, 15], packagingG: 450 }, // S — кружки
  { sizeCm: [30, 22, 20], packagingG: 650 }, // M — тарелки и миски
  { sizeCm: [36, 26, 26], packagingG: 850 }, // L — вазы
];
const PADDING_CM = 4; // по 2 см плёнки и бумаги с каждой стороны изделия

function packParcel(v: VariantSize): Parcel {
  // Размеры изделия с запасом на упаковку, по убыванию — неважно, как его повернуть в коробке
  const need = [v.length_mm, v.width_mm, v.height_mm].map((mm) => mm / 10 + PADDING_CM).sort((a, b) => b - a);
  // Самая маленькая подходящая коробка: за перевозку воздуха служба берёт деньги
  const box = BOXES.find((b) => b.sizeCm.every((cm, i) => cm >= need[i]));
  if (!box) throw new Error('Изделие не помещается ни в одну коробку — нужна отдельная упаковка');
  const [length, width, height] = box.sizeCm; // габариты — по ВНЕШНЕЙ коробке, а не по изделию
  return { weight: v.weight_g + box.packagingG, length, width, height };
}
// Кружка «Утро» 350 мл: 350 г, 120 × 95 × 100 мм → коробка S → 800 г, 20 × 15 × 15 см
// Ваза «Волна»: 1 400 г, 300 × 210 × 210 мм → коробка L → 2 250 г, 36 × 26 × 26 см

// Объёмный вес: Д × Ш × В (см) / 5000 = кг. Служба считает его сама по нашим габаритам
// (точные правила — в её условиях); функция — чтобы понимать счёт
function volumetricWeightKg(p: Parcel): number {
  return (p.length * p.width * p.height) / 5000; // ваза: 36 × 26 × 26 / 5000 ≈ 4,87 кг против 2,25 кг
}

