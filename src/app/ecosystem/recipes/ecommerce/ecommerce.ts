const HOUR = 60 * 60 * 1000;
const counters = new Map<string, { count: number; resetAt: number }>();

// Засчитывает попытку и возвращает, какая она по счёту в текущем окне
function hit(key: string, windowMs: number): number {
  const now = Date.now();
  const entry = counters.get(key);
  if (!entry || entry.resetAt <= now) {
    counters.set(key, { count: 1, resetAt: now + windowMs }); // началось новое окно
    return 1;
  }
  entry.count += 1;
  return entry.count;
}
// Раз в час выбрасываем истёкшие окна, чтобы Map не рос бесконечно
setInterval(() => {
  const now = Date.now();
  for (const [key, entry] of counters) if (entry.resetAt <= now) counters.delete(key);
}, HOUR);

