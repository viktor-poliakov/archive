// ═══ 1. ПОДКЛЮЧЕНИЕ: СЧЁТЧИК ЗНАЕТ ПРО КОНТЕЙНЕР dataLayer ═══
// В настройках счётчика Метрики включена опция «Электронная коммерция».
// После этого в код счётчика добавляется параметр ecommerce: 'dataLayer' —
// имя массива, из которого Метрика забирает события о товарах:
//   ym(COUNTER_ID, 'init', { /* …остальные настройки… */ ecommerce: 'dataLayer' });
// Сам массив создаём сразу: без него window.dataLayer.push упадёт с ошибкой.
window.dataLayer = window.dataLayer || [];

const COUNTER_ID = 12345678; // номер счётчика из интерфейса Метрики (пример)

// ═══ 2. ОДИН ПЕРЕВОДЧИК «НАШ ВАРИАНТ → ТОВАР ДЛЯ МЕТРИКИ» ═══
// Все события описывают товары одинаково — поэтому одна функция на всех.
function toMetricaProduct(item) {
  return {
    id: item.sku,                   // артикул варианта: 'UTRO-GRAPH-350' (нужен id или name)
    name: item.title,               // 'Кружка «Утро»'
    price: item.priceKopecks / 100, // Метрика ждёт ЧИСЛО В РУБЛЯХ: 145000 коп. → 1450
    brand: 'Обжиг',
    category: 'Посуда/Кружки',      // упрощение для кружки; в жизни — путь из дерева categories
                                    // (у вазы 'Интерьер/Вазы'), через «/», не больше пяти уровней
    variant: item.variantLabel,     // 'графит, 350 мл'
    quantity: item.quantity ?? 1,
  };
}
// Деление на 100 здесь допустимо: это цифры для отчёта, а не деньги.
// Платёж, чек и остатки по-прежнему считаются в целых копейках на сервере.

// Кладёт событие в контейнер в формате Метрики:
// { ecommerce: { currencyCode, <действие>: { actionField?, products } } }
function pushEcommerce(action, products, actionField) {
  const block = { products };
  if (actionField) block.actionField = actionField;
  window.dataLayer.push({ ecommerce: { currencyCode: 'RUB', [action]: block } });
}

// ═══ 3. ВОРОНКА: ПРОСМОТР → КОРЗИНА (И ОБРАТНО) ═══
// detail — человек открыл карточку. Один раз за открытие страницы:
// переключение цвета глазури — это не новый просмотр.
function onProductPageOpen(variant) {
  pushEcommerce('detail', [toMetricaProduct(variant)]);
}

// add — только ПОСЛЕ ответа сервера: если сервер отказал («осталось 0 шт.»),
// товара в корзине нет, и засчитывать нечего.
async function onAddToCart(variant, quantity) {
  const res = await fetch('/api/cart/items', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ variantId: variant.id, quantity }), // только id и количество
  });
  if (!res.ok) return; // показать покупателю ошибку — задача интерфейса, не аналитики
  pushEcommerce('add', [toMetricaProduct({ ...variant, quantity })]);
}

// remove — убрал из корзины или уменьшил количество (quantity — сколько убрал)
function onRemoveFromCart(variant, removedQuantity) {
  pushEcommerce('remove', [toMetricaProduct({ ...variant, quantity: removedQuantity })]);
}

// ═══ 4. НАЧАЛО ОФОРМЛЕНИЯ: ЦЕЛЬ И ClientID ═══
// Среди действий электронной коммерции Метрики нет «начал оформление»,
// поэтому этот шаг воронки отмечаем целью (её заводят в настройках счётчика).
function onCheckoutOpen() {
  ym(COUNTER_ID, 'reachGoal', 'checkout_start');

  // ClientID — номер, под которым Метрика знает этот браузер. Кладём его в скрытое
  // поле формы: сервер сохранит его вместе с заказом (отдельный столбец, в общей схеме
  // его нет) и сможет сам сообщить о покупке, если покупатель не вернётся (блок 7).
  ym(COUNTER_ID, 'getClientID', (clientId) => {
    document.querySelector('input[name="metricaClientId"]').value = clientId;
  });
}

