// ═══ 4. СКИДКИ: ОДНО ПРАВИЛО ОКРУГЛЕНИЯ НА ВЕСЬ МАГАЗИН ═══
// Правило «Обжига»: скидку округляем ВВЕРХ — покупатель платит на копейку меньше, а не больше.
// Эту функцию вызывают и карточка, и корзина, и чек; других округлений в коде нет.
function percentDiscount(amount: Kopecks, percent: number): Kopecks {
  if (!Number.isInteger(percent) || percent < 0 || percent > 100) throw new Error('Процент — целое от 0 до 100');
  return Math.ceil((amount * percent) / 100); // amount * percent — целое, делим один раз
}
