// Владелец вводит «1449,90» или «1 450». Разбираем как ТЕКСТ, а не умножаем дробь:
// 19.99 * 100 даёт 1998.9999999999998, и Math.floor тихо съест копейку.
function parseRublesInput(input: string): Kopecks {
  const cleaned = input.replace(/[\\s₽]/g, '').replace(',', '.'); // «1 449,90 ₽» → «1449.90»
  const match = /^(\\d+)(?:\\.(\\d{1,2}))?$/.exec(cleaned);      // рубли и до двух цифр копеек
  if (!match) throw new Error('Цена должна выглядеть как 1450 или 1449,90');
  const kopecks = (match[2] ?? '').padEnd(2, '0');               // «9» → «90», пусто → «00»
  return assertKopecks(Number(match[1]) * 100 + Number(kopecks));
}
