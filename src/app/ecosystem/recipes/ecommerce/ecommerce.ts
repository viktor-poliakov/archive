// Сам код проверяет только сервер: существует, не истёк, минимальная сумма, лимит использований.
function fixedDiscount(amount: Kopecks, discount: Kopecks): Kopecks {
  return Math.min(amount, discount);
}

// ═══ 5. РАЗНОС СКИДКИ ПО СТРОКАМ ЧЕКА — МЕТОД НАИБОЛЬШЕГО ОСТАТКА ═══
// В чеке нет строки «скидка»: у каждой позиции — уже сниженная цена, а сумма позиций
// обязана совпасть с суммой платежа. Каждой строке — целая часть её доли, нерозданные
// копейки — строкам с самым большим отброшенным «хвостом». Делим только нацело.
function allocateDiscount(lineTotals: Kopecks[], discount: Kopecks): Kopecks[] {
  const total = lineTotals.reduce((sum, line) => sum + line, 0);
  if (total === 0) return lineTotals.map(() => 0);
  const parts = lineTotals.map((line) => {
    const exact = discount * line;                  // доля = exact / total, exact — целое
    const tail = exact % total;                     // отброшенный хвост — тоже целое
    return { share: (exact - tail) / total, tail }; // делится без остатка
  });
  let left = discount - parts.reduce((sum, part) => sum + part.share, 0); // нерозданные копейки
  for (const part of [...parts].sort((a, b) => b.tail - a.tail)) {
    if (left === 0) break;
    part.share += 1; // объект общий с массивом parts — меняем прямо в нём
    left -= 1;
  }
  return parts.map((part) => part.share);
}
// Заказ: 2 × кружка «Утро» (2 900 ₽), тарелка «Полдень» 1 100 ₽, миска «Туман» 890 ₽.
allocateDiscount([290_000, 110_000, 89_000], 30_000); // [17791, 6749, 5460] — ровно 300 ₽
// Точные доли: 177,914… / 67,484… / 54,601… ₽. Вниз — 299,99 ₽, одна копейка осталась;
// её получает тарелка: хвост 0,466 коп. — самый большой. Строки после скидки:
// 272 209 + 103 251 + 83 540 = 459 000 коп. = 4 590 ₽.

// Две кружки за 2 722,09 ₽ — это 1 361,045 ₽ за штуку, а полкопейки в чеке не бывает.
// Разбиваем строку на две, цены в которых отличаются на копейку.
type ReceiptLine = { unitPrice: Kopecks; quantity: number };
function splitForReceipt(lineTotal: Kopecks, quantity: number): ReceiptLine[] {
  const extra = lineTotal % quantity;          // сколько штук получат +1 копейку
  const base = (lineTotal - extra) / quantity; // деление нацело
  const result: ReceiptLine[] = [{ unitPrice: base, quantity: quantity - extra }];
  if (extra > 0) result.unshift({ unitPrice: base + 1, quantity: extra });
  return result;
}
