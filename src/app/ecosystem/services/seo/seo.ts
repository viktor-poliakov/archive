//
// Карта, набранная руками, устаревает на второй день: вышла статья,
// две скрыли, у трёх поменяли текст — и файл уже врёт.
// А врущая карта хуже отсутствующей: вы своими руками отправляете
// робота по адресам, которых нет, и он перестаёт верить файлу целиком.
// Поэтому карту собирают кодом из того же источника, из которого сайт
// берёт страницы, — из базы данных. Тогда она не может разойтись
// с сайтом в принципе.

const fs = require('node:fs/promises');
const path = require('node:path');
const { EOL } = require('node:os');

const SITE = 'https://example.com';   // схема и домен как у живого сайта
const PUBLIC_DIR = './public';        // куда кладём готовые файлы

// Предел стандарта на один файл: 50 000 адресов и 50 МБ в распакованном
// виде. Берём с запасом, чтобы не упереться в предел по байтам.
