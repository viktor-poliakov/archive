// ═══ ШАГ 1. ЗАБИРАЕМ ИЗ БАЗЫ ТОЛЬКО ТО, ЧТО ДОЛЖНО БЫТЬ В ПОИСКЕ ═══
//
// Это самая важная функция во всём файле. В карту кладут ровно те
// адреса, которые отдают код 200, являются каноническими и не закрыты
// от индексации. Условия в WHERE — это и есть три правила, записанные
// на языке базы.

async function loadPostEntries(db) {
  const rows = await db.query(
    "SELECT slug, updated_at FROM posts " +
    "WHERE status = 'published' " +      // черновиков в поиске быть не должно
    "  AND is_noindex = false " +        // закрытые от индексации — мимо
    "  AND canonical_of IS NULL " +      // копии другого адреса — мимо
    "  AND deleted_at IS NULL " +        // удалённые отдают 404 — мимо
    "ORDER BY updated_at DESC"
  );

  return rows.map((row) => ({
    loc: SITE + '/blog/' + row.slug,
    lastmod: formatDate(row.updated_at),
  }));
}

