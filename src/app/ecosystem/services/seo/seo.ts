async function buildSitemaps(db) {
  const entries = loadStaticEntries().concat(await loadPostEntries(db));

  // Страховка от дублей: один и тот же адрес не должен попасть в карту
  // дважды. Иначе карта сама выглядит как источник дублей.
  const seen = new Set();
  const unique = entries.filter((entry) => {
    if (seen.has(entry.loc)) return false;
    seen.add(entry.loc);
    return true;
  });

  const parts = chunk(unique, MAX_URLS_PER_FILE);
  const written = [];

  for (let i = 0; i < parts.length; i += 1) {
    const name = 'sitemap-' + (i + 1) + '.xml';
    await fs.writeFile(path.join(PUBLIC_DIR, name), renderUrlset(parts[i]));
    written.push({ name: name, lastmod: formatDate(Date.now()) });
  }

  // Один файл — указатель не нужен, отдаём карту напрямую.
  // Больше одного — пишем указатель, и именно его адрес попадёт
  // в robots.txt и в кабинет вебмастера.
  if (written.length > 1) {
    const indexPath = path.join(PUBLIC_DIR, 'sitemap.xml');
    await fs.writeFile(indexPath, renderSitemapIndex(written));
  }

  console.log('Адресов в карте: ' + unique.length +
              ', файлов: ' + written.length);
}

