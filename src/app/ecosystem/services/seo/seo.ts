// ═══ ШАГ 2. МЕЛКИЕ ПОМОЩНИКИ ═══

// Дата в формате W3C Datetime. Для карты хватает YYYY-MM-DD.
function formatDate(value) {
  return new Date(value).toISOString().slice(0, 10);
}

// В XML пять символов имеют особое значение. В адресах реально
// встречается амперсанд, но экранируем все — дешевле, чем ловить
// сломанный файл на проде.
function escapeXml(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

// Режем длинный список на куски не длиннее size.
function chunk(items, size) {
  const result = [];
  for (let i = 0; i < items.length; i += size) {
    result.push(items.slice(i, i + size));
  }
  return result;
}


// ═══ ШАГ 3. СОБИРАЕМ САМ XML ═══
//
// Собираем построчно в массив и склеиваем в конце: так не надо думать
// про переводы строк внутри длинной склейки.

function renderUrlset(entries) {
  const lines = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');

  for (const entry of entries) {
    lines.push('  <url>');
    lines.push('    <loc>' + escapeXml(entry.loc) + '</loc>');
    if (entry.lastmod) {
      lines.push('    <lastmod>' + entry.lastmod + '</lastmod>');
    }
    lines.push('  </url>');
  }

  lines.push('</urlset>');
  return lines.join(EOL);
}

function renderSitemapIndex(files) {
  const lines = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push('<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">');

  for (const file of files) {
    lines.push('  <sitemap>');
    lines.push('    <loc>' + SITE + '/' + file.name + '</loc>');
    lines.push('    <lastmod>' + file.lastmod + '</lastmod>');
    lines.push('  </sitemap>');
  }

  lines.push('</sitemapindex>');
  return lines.join(EOL);
}


