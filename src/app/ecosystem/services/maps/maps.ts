// Здесь показан публичный демо-сервер проекта OSRM (Open Source Routing
// Machine). Он бесплатный, но без гарантий и без пробок: для продукта
// поднимают свой экземпляр или берут платный сервис. Схема запроса у
// всех похожая, меняются адрес и имена параметров.
//
// ВНИМАНИЕ на порядок координат в адресе: сначала долгота, потом
// широта. Это самая частая ошибка новичка — точка уезжает в океан.

const OSRM_ROUTE = 'https://router.project-osrm.org/route/v1/driving/';

async function fetchRoute(from, to) {
  const pair = from.lon + ',' + from.lat + ';' + to.lon + ',' + to.lat;
  const url = OSRM_ROUTE + pair + '?overview=full&geometries=geojson';

  const res = await fetch(url);
  if (!res.ok) {
    throw new Error('Сервис маршрутов ответил ' + res.status); // [!error]
  }

  const data = await res.json();
  // Сервис может ответить «всё хорошо» на уровне протокола и
  // «маршрут не найден» внутри тела — проверяем и то, и другое.
  if (data.code !== 'Ok' || data.routes.length === 0) {
    throw new Error('Маршрут не найден: ' + data.code); // [!error]
  }

  const route = data.routes[0];
  return {
    distanceM: Math.round(route.distance), // длина пути, метры
    durationS: Math.round(route.duration), // время в пути, секунды
    // geometry.coordinates — массив пар [долгота, широта]
    line: route.geometry.coordinates,
  };
}


