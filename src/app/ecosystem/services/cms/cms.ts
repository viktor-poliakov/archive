// Код читает новое, а если пусто - старое.
// Сайт не ломается ни на секунду, пока данные не перелиты.
function readAuthor(fields) {
  if (fields.authorFirst || fields.authorLast) {
    return {
      first: fields.authorFirst || '',
      last: fields.authorLast || ''
    };
  }

  const legacy = (fields.author || '').trim();
  if (!legacy) return { first: '', last: '' };

  const parts = legacy.split(/\\s+/);
  return { first: parts[0], last: parts.slice(1).join(' ') };
}


