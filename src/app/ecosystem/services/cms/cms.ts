const cache = new Map();       // в бою вместо Map — Redis или кэш фреймворка
const TTL_MS = 5 * 60 * 1000;  // 5 минут: свежесть новостей это переживёт

async function getCached(url) {
  const hit = cache.get(url);
  if (hit && Date.now() - hit.savedAt < TTL_MS) {
    return hit.value;          // ответ из памяти: ноль запросов к CMS
  }

  const res = await fetch(url);

  if (res.status === 429) {
    // 429 Too Many Requests — мы упёрлись в лимит частоты запросов.
    const wait = res.headers.get('Retry-After') || '60';
    console.error('CMS: лимит исчерпан, повтор через ' + wait + ' с'); // [!error]
    if (hit) {
      return hit.value;        // отдаём устаревший ответ: лучше, чем ошибка
    }
    throw new Error('CMS rate limit');
  }

  const value = await res.json();
  cache.set(url, { value, savedAt: Date.now() });
  return value;
}

