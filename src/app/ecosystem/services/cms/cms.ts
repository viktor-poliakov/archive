const QUIET_MS = 30 * 1000;             // ждём 30 секунд тишины после правки
const MIN_INTERVAL_MS = 5 * 60 * 1000;  // не чаще одной сборки в 5 минут

const pending = new Set();   // адреса, которые ждут пересборки
let quietTimer = null;
let lastRunAt = 0;

const rebuildQueue = {
  async schedule(paths) {
    for (const p of paths) pending.add(p);

    // Каждая новая правка сдвигает таймер вперёд.
    // Двадцать правок подряд дадут один запуск, а не двадцать.
    if (quietTimer) clearTimeout(quietTimer);
    quietTimer = setTimeout(runRebuild, QUIET_MS);
  }
};

async function runRebuild() {
  quietTimer = null;

  const waited = Date.now() - lastRunAt;
  if (waited < MIN_INTERVAL_MS) {
    // Слишком рано. Переносим запуск: адреса остаются в наборе, ничего не теряем.
    quietTimer = setTimeout(runRebuild, MIN_INTERVAL_MS - waited);
    return;
  }

  const batch = Array.from(pending);
  pending.clear();
  lastRunAt = Date.now();

  try {
    await buildSite(batch);
  } catch (err) {
    // Сборка упала - возвращаем адреса в набор и пробуем позже.
    for (const p of batch) pending.add(p);            // [!error]
    console.error('Сборка не удалась:', err.message); // [!error]
    quietTimer = setTimeout(runRebuild, MIN_INTERVAL_MS);
  }
}

