// --- 7. Одна функция применения статуса — и для вебхука, и для сверки ---
async function applyPaymentStatus(order, payment) {
  const map = {
    succeeded: 'paid',
    waiting_for_capture: 'authorized',
    canceled: 'canceled',
    pending: 'awaiting_payment',
  };
  const next = map[payment.status];
  if (!next || next === order.status) return;      // ничего не изменилось

  await orders.transition(order.id, { from: order.status, to: next });
  if (next === 'paid') {
    await warehouse.ship(order.id);
    await fiscal.enqueueReceipt(order.id);          // чек — отдельная операция
  }
}

