async function onInvoicePaid(event) {
  const sub = await subscriptions.findByExternalId(event.object.subscription);
  if (!sub) return;

  await subscriptions.update(sub.id, {
    status: 'active',
    // Дату берём ИЗ СОБЫТИЯ, а не считаем сами «плюс месяц».
    // Провайдер учитывает часовые пояса, короткие месяцы и 29 февраля.
    accessUntil: event.object.period_end,
    failedAttempts: 0,
    graceUntil: null,
  });

  await payments.recordEntry({
    subscriptionId: sub.id,
    kind: 'charge',
    amountMinor: event.object.amount_paid,
    currency: event.object.currency,
    externalId: event.object.id,
  });
}

