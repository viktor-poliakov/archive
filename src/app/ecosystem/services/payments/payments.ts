// --- Маскирующий логгер: чистит данные ДО записи ---

const SENSITIVE_KEYS = new Set([
  'card', 'cardNumber', 'card_number', 'pan', 'number',
  'cvv', 'cvc', 'cvv2', 'securityCode',
  'expiry', 'expMonth', 'expYear', 'exp_month', 'exp_year',
  'authorization', 'apiKey', 'api_key', 'secret', 'password', 'token',
]);

function maskPan(value) {
  const digits = String(value).replace(/\\D/g, '');
  if (digits.length < 12) return '***';
  // Разрешено показывать не больше первых шести и последних четырёх цифр.
  // На практике для разбора инцидентов достаточно последних четырёх.
  return '**** **** **** ' + digits.slice(-4);
}

function sanitize(value, depth) {
  if (depth > 6) return '[too deep]';
  if (value === null || typeof value !== 'object') return value;
  if (Array.isArray(value)) return value.map((item) => sanitize(item, depth + 1));

  const out = {};
  for (const [key, val] of Object.entries(value)) {
    const lower = key.toLowerCase();

    if (SENSITIVE_KEYS.has(key) || SENSITIVE_KEYS.has(lower)) {
      // Отдельно обрабатываем то, что похоже на номер карты:
      // последние четыре цифры реально помогают в разборе.
      out[key] = lower.includes('card') || lower === 'pan' || lower === 'number'
        ? maskPan(val)
        : '[скрыто]';
      continue;
    }

    out[key] = sanitize(val, depth + 1);
  }
  return out;
}

