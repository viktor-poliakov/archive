// отменяется; есть уведомления клиенту и страница самостоятельной отписки.

const HARD_DECLINES = new Set([
  'lost_card',
  'stolen_card',
  'authentication_required',
  'card_not_supported',
]);

async function onPaymentFailed(event) {
  const sub = await subscriptions.findByExternalId(event.object.subscription);
  if (!sub) return;

  const reason = event.object.decline_code;
  const attempt = sub.failedAttempts + 1;

  // 1. Льготный период открываем СРАЗУ, при первом же отказе.
  //    Доступ не отключаем — человек ещё ничего не знает о проблеме.
  const graceUntil = sub.graceUntil ?? daysFromNow(14);

  await subscriptions.update(sub.id, {
    status: 'past_due',
    failedAttempts: attempt,
    lastDeclineCode: reason,
    graceUntil,
  });

  // 2. Жёсткий отказ — повторять бессмысленно. Нужна НОВАЯ карта.
  if (HARD_DECLINES.has(reason)) {
    // Причину пользователю пишем человеческим языком и без деталей банка:
    // «банк отклонил операцию, обновите способ оплаты».
    await notify(sub.userId, 'card_hard_decline', {
      updateUrl: buildUpdateCardUrl(sub),
    });
    return;
  }

  // 3. Мягкий отказ (не хватило средств, временный отказ эмитента) —
  //    провайдер повторит попытку сам по своему расписанию.
  //    Наша работа — предупредить человека и не мешать.
  await notify(sub.userId, 'payment_retry_scheduled', {
    nextAttemptAt: event.object.next_payment_attempt,
    graceUntil,
    updateUrl: buildUpdateCardUrl(sub),
  });
}

