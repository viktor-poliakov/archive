// настраивается на окно 1 неделя / 2 недели / 3 недели / 1 месяц /
// 2 месяца; рекомендуемый по умолчанию вариант — 8 попыток за 2 недели.
// Кастомное расписание допускает до 3 повторов.
// При жёстком отказе (lost_card, stolen_card, authentication_required
// и подобных) повтор без новой карты не выполняется вовсе.
// После исчерпания попыток подписка по настройке переходит в canceled,
