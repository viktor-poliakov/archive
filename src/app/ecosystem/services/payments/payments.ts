// --- 5. Собственно проверка подписи (схема Stripe) ---
const crypto = require('node:crypto');

function verifySignature(rawBody, header, secret) {
  if (!header) throw Object.assign(new Error('no header'), { code: 'missing' });

  // Заголовок Stripe-Signature выглядит так: t=1725360000,v1=5257a869e7...
  const parts = Object.fromEntries(
    header.split(',').map((piece) => piece.split('=')),
  );

  const timestamp = Number(parts.t);
  const signature = parts.v1;                 // схемы, кроме v1, игнорируем
  if (!timestamp || !signature) throw Object.assign(new Error('malformed'), { code: 'malformed' });

  // Защита от повтора старого перехваченного запроса (replay).
  // Официальные библиотеки допускают расхождение в 5 минут.
  const ageSeconds = Math.abs(Date.now() / 1000 - timestamp);
  if (ageSeconds > 300) throw Object.assign(new Error('too old'), { code: 'stale' });

  // Подписывается строка «timestamp + точка + СЫРОЕ тело».
  const signedPayload = timestamp + '.' + rawBody.toString('utf8');
  const expected = crypto.createHmac('sha256', secret).update(signedPayload).digest('hex');

  // Сравнение обязательно постоянного времени: обычное === утекает
  // информацию о том, сколько символов совпало.
  const ok = crypto.timingSafeEqual(Buffer.from(expected), Buffer.from(signature));
  if (!ok) throw Object.assign(new Error('mismatch'), { code: 'mismatch' });

  return JSON.parse(rawBody.toString('utf8'));
}

