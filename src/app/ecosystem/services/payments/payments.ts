// ШАГ 1. Создаём платёж БЕЗ автоматического списания.
async function authorizeOrder(order) {
  const payment = await provider.payments.create({
    amount: { value: order.amountMinor, currency: order.currency },
    capture: false,                       // ← только холд
    confirmation: { type: 'redirect', return_url: RETURN_URL },
    metadata: { orderId: order.id },
    description: 'Заказ №' + order.number,
  });

  await orders.update(order.id, {
    status: 'awaiting_payment',
    paymentId: payment.id,
  });

  return payment.confirmation.confirmation_url;
}

// ШАГ 2. Провайдер прислал вебхук «холд подтверждён» (статус вида
// waiting_for_capture / requires_capture). Только теперь идём на склад.
async function onAuthorized(paymentId) {
  const order = await orders.findByPaymentId(paymentId);

  const reserved = await warehouse.reserve(order.items);
  if (!reserved.ok) {
    // Товара нет — ОТПУСКАЕМ холд. Это не возврат: денег никто не брал,
    // блокировка просто снимается, покупатель видит сумму обратно
    // на балансе обычно в тот же день.
    await provider.payments.cancel(paymentId, { idempotencyKey: 'cancel-' + paymentId });
    await orders.update(order.id, { status: 'canceled', reason: 'out_of_stock' });
    return;
  }

  // Товар есть — списываем. Можно списать МЕНЬШЕ, чем холдировали:
  // остаток эмитент освободит сам. Больше — нельзя.
  const finalAmount = Math.min(order.amountMinor, reserved.actualAmountMinor);

  await provider.payments.capture(paymentId, {
    amount: { value: finalAmount, currency: order.currency },
    idempotencyKey: 'capture-' + paymentId,     // повтор не спишет второй раз
  });

  await orders.update(order.id, { status: 'paid', capturedMinor: finalAmount });
}

// ═══ ГЛАВНАЯ ЛОВУШКА ДВУХШАГОВОЙ СХЕМЫ: ХОЛД НЕ ВЕЧЕН ═══
// Если не сделать capture вовремя, холд ИСТЕКАЕТ, платёж уходит в canceled,
// а деньги возвращаются покупателю. Никто вас не предупредит заранее.
//
// Ориентиры по сроку жизни холда (данные Stripe):
//   • онлайн-платежи: 7 дней — Mastercard, Amex, Discover и Visa CIT
//     (CIT — операция, инициированная самим покупателем);
//   • онлайн, Visa MIT (операция, инициированная продавцом, — например
//     регулярное списание): 5 дней, точнее 4 дня 18 часов;
//   • офлайн-терминал: 5 дней Visa, 2 дня остальные;
//   • Япония в иенах: до 30 дней.
//
// Практический вывод: если вы холдируете, вам НУЖНА фоновая задача, которая
// каждые несколько часов смотрит на зависшие холды и либо списывает,
// либо отменяет их ЗАРАНЕЕ, не дожидаясь истечения.

async function sweepStaleAuthorizations() {
  const stale = await orders.find({
    status: 'authorized',
    authorizedAt: { lessThan: hoursAgo(72) },     // порог заведомо меньше срока холда
  });

  for (const order of stale) {
    // Отменить самому — честнее, чем дать холду молча протухнуть:
    // вы контролируете момент и можете написать покупателю.
    await provider.payments.cancel(order.paymentId, {
      idempotencyKey: 'sweep-' + order.paymentId,
    });
    await orders.update(order.id, { status: 'canceled', reason: 'hold_expired_by_us' });
  }
}

