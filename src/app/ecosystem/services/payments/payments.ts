async function createSubscription(userId, planId) {
  const user = await users.findById(userId);
  const plan = await plans.findById(planId);       // amountMinor, currency, interval

  // Первый платёж делает САМ покупатель: он вводит карту и явно
  // соглашается на регулярные списания. Только так провайдер выдаст токен.
  const setup = await provider.subscriptions.create(
    {
      customer: user.providerCustomerId,
      plan: plan.externalId,
      trial_days: plan.trialDays,                 // 0 — если триала нет
      metadata: { userId: user.id, planId: plan.id },
    },
    { idempotencyKey: 'sub-create-' + user.id + '-' + plan.id },
  );

  // Формулировку согласия показываем на форме оплаты, а сам факт согласия
  // фиксируем у себя: дата, текст, адрес. Это пригодится при споре.
  await subscriptions.insert({
    userId: user.id,
    planId: plan.id,
    externalId: setup.id,                          // идентификатор у провайдера
    status: setup.trial_end ? 'trialing' : 'incomplete',
    accessUntil: setup.current_period_end,         // ← по этому полю мы даём доступ
    consentAt: new Date(),
    consentText: 'Согласие на регулярные списания по тарифу ' + plan.title,
  });

  return setup.confirmation_url;                   // тут покупатель вводит карту
}

