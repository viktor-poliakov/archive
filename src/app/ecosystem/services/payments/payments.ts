async function changePlan(subscriptionId, newPlanId, mode) {
  const sub = await subscriptions.findById(subscriptionId);
  const newPlan = await plans.findById(newPlanId);

  // Шаг 1. Сначала СПРАШИВАЕМ, во что это обойдётся, и показываем человеку.
  // Никогда не меняйте тариф молча: «с меня списали 5 долларов непонятно
  // за что» — прямая дорога к оспариванию операции.
  const preview = await provider.subscriptions.previewChange({
    subscription: sub.externalId,
    plan: newPlan.externalId,
    proration_behavior: 'always_invoice',
  });

  // preview.amount_due — доплата в минорных единицах. Для примера
  // из документации Stripe (переход с 10 на 20 долларов в середине месяца)
  // это 500, то есть 5 долларов: минус 5 кредита за неиспользованный
  // остаток старого тарифа и плюс 10 за остаток периода по новому.
  await confirmations.ask(sub.userId, {
    text: 'Доплата при переходе на тариф ' + newPlan.title,
    amountMinor: preview.amount_due,
    currency: preview.currency,
  });

  // Шаг 2. Применяем. Поведение выбираем осознанно:
  //   'create_prorations' — пересчёт ляжет в следующий счёт (по умолчанию);
  //   'always_invoice'    — выставить счёт и списать сразу;
  //   'none'              — не пересчитывать вовсе (новая цена с нового периода).
  const updated = await provider.subscriptions.update(
    sub.externalId,
    { plan: newPlan.externalId, proration_behavior: mode },
    { idempotencyKey: 'sub-change-' + sub.id + '-' + newPlan.id },
  );

  await subscriptions.update(sub.id, {
    planId: newPlan.id,
    accessUntil: updated.current_period_end,
  });

  // Важно: при ПОНИЖЕНИИ тарифа пересчёт отрицательный. Деньги при этом
  // автоматически НЕ возвращаются — сумма остаётся кредитом на следующий
  // счёт. Если вы обещали клиенту возврат деньгами, возврат надо делать
  // отдельной операцией и осознанно.
}

// ═══ 4. ОТМЕНА: ДВА РАЗНЫХ СЦЕНАРИЯ ═══

async function cancelSubscription(subscriptionId, immediate) {
  const sub = await subscriptions.findById(subscriptionId);

  if (!immediate) {
    // Обычный случай: доступ до конца оплаченного периода,
    // следующего списания не будет. Возвращать нечего, спорить не о чем.
    await provider.subscriptions.update(sub.externalId, { cancel_at_period_end: true });
    await subscriptions.update(sub.id, {
      status: 'canceling',
      // accessUntil НЕ ТРОГАЕМ — человек уже заплатил за этот период.
    });
    return { accessUntil: sub.accessUntil };
  }

  // Немедленная отмена: доступ отключается сразу.
  await provider.subscriptions.cancel(sub.externalId, {
    idempotencyKey: 'sub-cancel-' + sub.id,
  });
  await subscriptions.update(sub.id, {
    status: 'canceled',
    accessUntil: new Date(),
  });

  // Вопрос возврата за неиспользованные дни решает бизнес, а не код.
  // Но решить его надо ДО запуска, иначе решать будет поддержка на ходу.
  return { accessUntil: new Date() };
}

// ═══ 5. ПРОВЕРКА ДОСТУПА: САМОЕ ЧАСТОЕ МЕСТО В КОДЕ ═══
// Вызывается на каждый запрос. Значит, никаких походов в чужой API.

async function hasAccess(userId) {
  const sub = await subscriptions.findActiveByUser(userId);
  if (!sub) return false;

  // Доступ определяется ОДНОЙ датой в нашей базе. Все состояния
  // (триал, активна, отменяется, льготный период) уже свёрнуты в неё
  // обработчиками событий.
  const now = Date.now();
  if (new Date(sub.accessUntil).getTime() > now) return true;

  // Льготный период после неудачного списания — тоже доступ.
  if (sub.graceUntil && new Date(sub.graceUntil).getTime() > now) return true;

  return false;
}

