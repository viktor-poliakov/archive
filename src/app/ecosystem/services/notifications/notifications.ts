const BASE_DELAY_MS = 1000;      // пауза перед первым повтором
const MAX_DELAY_MS = 60000;      // потолок: дольше минуты ждать смысла нет
const MAX_ATTEMPTS = 5;          // всего попыток, включая самую первую

// Пауза удваивается с каждой попыткой: 1с, 2с, 4с, 8с, 16с — это и значит
// слово «экспоненциальная». Затем к ней добавляется случайная величина.
// Зачем добавка: если провайдер лёг и тысяча воркеров получила таймаут
// одновременно, без добавки все они вернутся ровно через 4 секунды —
// в одну и ту же миллисекунду — и уронят его снова, едва он поднялся.
// Со случайной добавкой попытки размазываются по времени.
function nextDelay(attempt) {
  const growing = BASE_DELAY_MS * Math.pow(2, attempt - 1);
  const capped = Math.min(growing, MAX_DELAY_MS);
  const jitter = Math.random() * capped * 0.3;   // разброс до 30 процентов
  return Math.round(capped + jitter);
}

// Если провайдер прислал Retry-After, его слушаемся: он знает лучше нас.
// Заголовок бывает числом секунд ('30') или датой по стандарту HTTP.
function delayFromRetryAfter(err) {
  const header = err.headers && err.headers['retry-after'];
  if (!header) return null;

  const seconds = Number(header);
  if (Number.isFinite(seconds)) return Math.min(seconds * 1000, MAX_DELAY_MS);

  const date = Date.parse(header);
  if (Number.isNaN(date)) return null;
  return Math.min(Math.max(date - Date.now(), 0), MAX_DELAY_MS);
}


