// Подпись считается по БАЙТАМ исходного тела. Если поставить сюда
// express.json(), тело будет уже разобрано в объект, а склеить его
// обратно байт в байт невозможно: изменятся пробелы и порядок ключей,
// и подпись не сойдётся никогда. Поэтому именно на этом маршруте —
// express.raw(), а не привычный разбор JSON.
app.use('/webhooks/email', express.raw({ type: 'application/json' }));


// ───── 2. Проверка подписи ─────────────────────────────────────────────
// Ваш URL для вебхуков открыт всему интернету. Без проверки кто угодно
// пришлёт вам «жалобу на спам» от имени любого адреса.
function isSignatureValid(rawBody, signatureHeader) {
  if (!signatureHeader) return false;

  const expected = crypto
    .createHmac('sha256', WEBHOOK_SECRET)
    .update(rawBody)
    .digest('hex');

  const a = Buffer.from(expected, 'utf8');
  const b = Buffer.from(signatureHeader, 'utf8');

  // Длины разные — timingSafeEqual бросит исключение, сравниваем заранее.
  if (a.length !== b.length) return false;

  // Сравнение за постоянное время: по времени ответа подпись не подобрать.
  return crypto.timingSafeEqual(a, b);
}


