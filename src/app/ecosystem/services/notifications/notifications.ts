async function sendWithRetries(notificationId, payload) {
  let lastError;

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      const result = await providerClient.send(payload);
      metrics.increment('notifications.sent', { attempt: String(attempt) });
      return result;
    } catch (err) {
      lastError = err;

      // Постоянная ошибка: выходим немедленно, не тратя оставшиеся попытки.
      if (!isRetryable(err)) {
        await moveToDeadLetter(notificationId, payload, err, 'permanent');
        console.error('permanent send error', err.status, err.message);  // [!error]
        return null;
      }

      // Попытки кончились: дальше повторять нельзя.
      if (attempt === MAX_ATTEMPTS) break;

      const wait = delayFromRetryAfter(err) || nextDelay(attempt);
      console.warn('retry in ' + wait + ' ms, attempt ' + attempt);
      await sleep(wait);
    }
  }

  // Сюда попадают только те, кто исчерпал все попытки.
  await moveToDeadLetter(notificationId, payload, lastError, 'exhausted');
  console.error('all attempts failed', lastError && lastError.message);  // [!error]
  return null;
}


