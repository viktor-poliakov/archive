async function sendToSubscription(record, message) {
  const payload = JSON.stringify({
    title: message.title,
    body: message.body,
    tag: 'order-' + message.orderId,    // схлопывает повторы по заказу
    url: '/orders/' + message.orderId,  // страница подтянет детали сама
  });

  try {
    await webpush.sendNotification(record.subscription, payload, {
      TTL: 3600,          // секунд служба хранит сообщение для офлайна
      urgency: 'normal',  // low | normal | high — будить ли спящий телефон
      topic: 'order-' + message.orderId,  // заменит непрочитанное старое
    });
    return 'sent';
  } catch (error) {
    return handleSendError(record, error, payload.length);
  }
}


// ═══ ШАГ 3. МЁРТВЫЕ ПОДПИСКИ УДАЛЯЕМ СРАЗУ ═══

async function handleSendError(record, error, payloadSize) {
  const status = error.statusCode;

  if (status === 404 || status === 410) {
    // 404 — такого адреса доставки у службы нет вообще.
    // 410 Gone — был, но человек отписался, снёс сайт или почистил браузер.
    // Оба ответа окончательные: подписка мертва навсегда. // [!error]
    await db.subscriptions.delete(record.id);
    return 'deleted';
  }

  if (status === 429) {
    // Слишком часто. Подписка живая — вернуть в очередь на повтор.
    return 'retry-later';
  }

  if (status === 413) {
    // Тело больше, чем принимает служба. Укоротить нагрузку.
    console.error('push payload too large: ' + payloadSize); // [!error]
    return 'too-large';
  }

  if (status >= 500) {
    return 'retry-later';               // временная проблема службы
  }

  throw error;                          // остальное — наш баг, пусть падает
}


