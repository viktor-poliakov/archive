async function verifyCode(phone, codeFromUser) {
  // Один и тот же ответ на «записи нет», «код истёк» и «код неверный».
  // Разные тексты подсказывают атакующему, куда он попал, а значит
  // ускоряют перебор. Пользователю разницы почти нет, атакующему — большая.
  const FAIL = { ok: false, error: 'invalid_or_expired' };

  const row = await db.otp.findActive(phone);
  if (!row) return FAIL;
  if (row.usedAt !== null) return FAIL;
  if (Date.now() > row.expiresAt) return FAIL;

  // Без этой проверки шестизначный код подбирается скриптом за минуты:
  // миллион вариантов — это очень мало. С пятью попытками шанс угадать
  // примерно пять из миллиона, и это уже приемлемо.
  if (row.attempts >= MAX_ATTEMPTS) {
    await db.otp.expireAllFor(phone);
    return FAIL;
  }
  await db.otp.incAttempts(row.id);

  // Сравниваем отпечатки, а не строки, и делаем это за постоянное время:
  // обычное === выходит на первом несовпавшем байте и выдаёт длину совпадения.
  const given = Buffer.from(fingerprint(phone, codeFromUser), 'hex');
  const stored = Buffer.from(row.hash, 'hex');
  if (!crypto.timingSafeEqual(given, stored)) return FAIL;

  // Гасим код ДО выдачи сессии и атомарно: markUsed вернёт false,
  // если кто-то успел использовать эту строку параллельно.
  const claimed = await db.otp.markUsed(row.id);
  if (!claimed) return FAIL;

  return { ok: true, phone: phone };
}
