// Никакой особой библиотеки не нужно: это обычный HTTP-запрос POST.
// В Node.js версии 18 и новее fetch встроен, устанавливать нечего.

async function sendEmail(mail) {
  const response = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: {
      // Bearer переводится как «предъявитель». Так HTTP-сервисы
      // принимают ключи: слово Bearer, пробел и сам ключ.
      Authorization: 'Bearer ' + apiKey,
      // Говорим серверу, что в теле запроса лежит JSON.
      'Content-Type': 'application/json',
    },
    // Тело запроса — наш объект письма, превращённый в строку JSON.
    body: JSON.stringify(mail),
  });

  // ─── Ответ 2xx: сервис принял письмо в работу ───
  if (response.ok) {
    const data = await response.json();
    // Сохраните этот id рядом с заказом или пользователем: по нему
    // потом найдёте письмо в панели сервиса и в отчёте о доставке.
    console.log('Письмо принято, id =', data.id);
    return data.id;
  }

  // Тело ошибки читаем как текст: некоторые сервисы при сбое
  // отдают HTML-страницу, и JSON.parse на ней просто упадёт.
  const details = await response.text();

  // ─── Ответ 4xx: виноват наш запрос ───
  if (response.status >= 400 && response.status < 500) {
    // 401 и 403 — ключ неверный, просрочен или отозван.
    // 422 — сервис не принял поля письма: пустая тема, чужой домен в from.
    // 429 — слишком много запросов, вы упёрлись в лимит частоты.
    console.error('Сервис отклонил письмо:', response.status, details);  // [!error]
    // Повторять такой запрос бессмысленно: пока не почините — не примут.
    // Исключение — 429: его можно повторить, но позже и реже.
    throw new Error('Письмо отклонено, повтор не поможет');  // [!error]
  }

  // ─── Ответ 5xx: сломалось на стороне сервиса ───
  // Наш запрос в порядке, просто у них авария. Такое повторяют:
  // через 1 секунду, через 5, через 25 — и не чаще раза в минуту потом.
  console.error('Сервис недоступен:', response.status, details);  // [!error]
  throw new Error('Временная ошибка сервиса, повторим позже');  // [!error]
}


