//   inline     - показать в окне (картинка, PDF);
//   attachment - предложить сохранить, имя берётся из filename.
// Для кириллических имён нужен второй параметр, filename (RFC 5987):
function contentDisposition(originalName) {
  const ascii = originalName.replace(/[^A-Za-z0-9._ -]+/g, '_');
  return 'attachment; filename="' + ascii + '"; '
    + "filename*=UTF-8''" + encodeURIComponent(originalName);
}


