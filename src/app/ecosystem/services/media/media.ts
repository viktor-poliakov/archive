// кода, а не из запроса, но лишняя проверка стоит одну строку.
const ALLOWED_KINDS = ['avatar', 'attachment', 'invoice', 'video'];

function datePath(date) {
  const iso = date.toISOString().slice(0, 10);  // '2026-09-04'
  return iso.split('-').join('/');              // '2026/09/04'
}

function randomId() {
  // crypto.randomUUID() есть и в браузере, и в Node.js (18+).
  // Убираем дефисы: остаётся 32 шестнадцатеричных символа.
  // Угадать такой идентификатор перебором нереально.
  return crypto.randomUUID().split('-').join('');
}

