// ═══ ФОНОВАЯ УБОРКА: РАСХОЖДЕНИЯ БЫВАЮТ В ДВЕ СТОРОНЫ ═══
//
// База и хранилище — два разных места, и они неизбежно расходятся.
// Сторона 1: объект в хранилище есть, записи в базе нет.
// Сторона 2: запись в базе есть, объекта в хранилище нет.
// Разбираем обе, и у каждой своё лечение.

// Порог возраста. Всё, что моложе — не трогаем ни при каких условиях:
// возможно, файл прямо сейчас загружается, а запись ещё не создана.
const ORPHAN_AGE_MS = 6 * 60 * 60 * 1000; // шесть часов

// Предохранитель: сколько объектов разрешено удалить за один проход.
// Если уборка вдруг решила снести тысячи файлов — что-то сломалось,
// и лучше остановиться и посмотреть, чем «успешно» вычистить бакет.
const MAX_DELETES_PER_RUN = 500;

// storage — тонкая обёртка над клиентом хранилища. Внутри у неё
// перечисление объектов постранично и удаление по ключу.
// db — обычный доступ к базе.

async function cleanupOrphans(storage, db, log, options) {
  const dryRun = options.dryRun !== false; // по умолчанию только показать
  const now = Date.now();
  let deleted = 0;
  let cursor = undefined;

  // ─── СТОРОНА 1: ОБЪЕКТ БЕЗ ЗАПИСИ ───
  //
  // Откуда берётся: браузер получил ссылку, залил файл — и всё.
  // Вкладку закрыли, сеть отвалилась, приложение упало
  // до того, как успело подтвердить загрузку.
  do {
    const page = await storage.listObjects({ prefix: 'u/', cursor });
    cursor = page.nextCursor;

    // Ключи страницы спрашиваем у базы ОДНИМ запросом, а не по одному:
    // тысяча отдельных запросов на тысячу объектов — верный способ
    // положить базу собственной уборкой.
    const keys = page.objects.map((object) => object.key);
    const known = await db.manyKeys(
      'select storage_key from media where storage_key = any($1)',
      [keys],
    );
    const knownSet = new Set(known);

    for (const object of page.objects) {
      if (knownSet.has(object.key)) continue; // запись есть, всё в порядке

      const ageMs = now - object.lastModified.getTime();
      if (ageMs < ORPHAN_AGE_MS) {
        // Молодой объект без записи — это, скорее всего, файл,
        // который загружается прямо сейчас. Не трогаем.
        log.debug('skip young orphan ' + object.key);
        continue;
      }

      if (deleted >= MAX_DELETES_PER_RUN) {
        log.error('предохранитель: слишком много удалений за проход'); // [!error]
        return { deleted, stopped: true };
      }

      log.warn('orphan object ' + object.key + ' age ' + Math.round(ageMs / 3600000) + 'h');
      if (!dryRun) {
        await storage.deleteObject(object.key);
        deleted += 1;
      }
    }
  } while (cursor);

  // ─── СТОРОНА 2: ЗАПИСЬ БЕЗ ОБЪЕКТА ───
  //
  // Откуда берётся: объект удалили руками через панель хранилища,
  // перепутали рабочее и тестовое окружение, потеряли при переносе.
  // Такие ряды НЕ удаляем: пользователь имеет право знать,
  // что его файл потерян. Пометим и покажем честной надписью.
  const rows = await db.many(
    'select id, storage_key from media ' +
      "where status = 'ready' and deleted_at is null " +
      'order by created_at desc limit 1000',
  );

  for (const row of rows) {
    const exists = await storage.headObject(row.storage_key);
    if (exists) continue;

    log.error('файл потерян в хранилище: ' + row.storage_key); // [!error]
    if (!dryRun) {
      await db.run("update media set status = 'missing' where id = $1", [row.id]);
    }
  }

  return { deleted, stopped: false };
}


