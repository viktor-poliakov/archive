// ═══ Обработка загруженной картинки: Node.js + библиотека sharp ═══
// Установка: npm install sharp
//
// Один прогон по большой фотографии занимает процессор на секунды и
// десятки мегабайт памяти. Поэтому такой код живёт в фоновой задаче,
// а не в обработчике HTTP-запроса: запрос лишь кладёт файл в
// хранилище и ставит задание в очередь.

import { randomUUID } from 'node:crypto';
import sharp from 'sharp';

// Форматы, которые мы вообще согласны принимать.
const ALLOWED_FORMATS = ['jpeg', 'png', 'webp', 'avif'];

// Ширины производных картинок в точках. Больше трёх-четырёх
// вариантов заводить обычно незачем.
const TARGET_WIDTHS = [320, 640, 1280];

// Предел площади: 40 млн точек — это примерно 6000 x 6600.
// Ни аватарке, ни картинке в статье больше не нужно.
const MAX_PIXELS = 40000000;


// ─── Открываем файл с ограничениями, а не «как получится» ───
function openSafely(originalBuffer) {
  return sharp(originalBuffer, {
    // Вторая линия защиты: sharp сам откажется распаковывать
    // картинку, у которой в заголовке заявлено больше точек.
    limitInputPixels: MAX_PIXELS,
    // Не пытаться дочитать битый файл: лучше честная ошибка.
    failOn: 'error',
  });
}

async function processUpload(originalBuffer, ownerId, storage, db) {
  // ─── Шаг 1. Читаем заголовок, не распаковывая картинку ───
  // metadata() разбирает только служебное начало файла: там лежат
  // формат, ширина, высота и метка ориентации при съёмке.
  const head = await openSafely(originalBuffer).metadata();

  // ─── Шаг 2. Проверяем разумность ДО тяжёлой обработки ───
  if (!ALLOWED_FORMATS.includes(head.format)) {
    throw new Error('Формат не принимаем: ' + head.format); // [!error]
  }
  if (!head.width || !head.height) {
    throw new Error('В файле не читаются размеры сторон'); // [!error]
  }

  const declaredPixels = head.width * head.height;
  if (declaredPixels > MAX_PIXELS) {
    // Защита от «картинки-бомбы»: сам файл может весить 2 КБ, а в
    // заголовке заявлено 60000 x 60000 точек. Распаковка такого
    // заголовка просит гигабайты памяти и роняет процесс целиком.
    throw new Error('Слишком крупно: ' + declaredPixels + ' точек'); // [!error]
  }

  // ─── Шаг 3. Оригинал сохраняем первым и больше не трогаем ───
  // Через год выйдет новый формат — и все производные можно будет
  // пересобрать из этого файла заново.
  const folder = 'uploads/' + ownerId + '/' + randomUUID();
  await storage.put(folder + '/original.' + head.format, originalBuffer);

  // ─── Шаг 4. Поворот по данным съёмки ───
  // Телефон почти всегда пишет точки «как есть», в ориентации
  // матрицы, и добавляет в служебные данные пометку вида
  // «при показе поверни на 90 градусов». Вызов rotate() без
  // аргументов читает эту пометку и реально разворачивает точки.
  // Если пометку выбросить и не применить — все портретные фото
  // лягут набок.
  const base = openSafely(originalBuffer).rotate();

  // Если пометка просила поворот на 90 или 270 градусов, стороны
  // меняются местами. Значения 5..8 — это как раз такие случаи.
  const turned = head.orientation >= 5 && head.orientation <= 8;
  const realWidth = turned ? head.height : head.width;
  const realHeight = turned ? head.width : head.height;

  // ─── Шаг 5. Служебные данные в производные не переносим ───
  // sharp по умолчанию НЕ копирует их в результат: модель камеры,
  // дата съёмки и координаты остаются только в оригинале.
  // Поэтому вызова withMetadata() здесь нет — он вернул бы
  // координаты обратно в публичный файл. Нужен цветовой профиль —
  // переносите только его: .keepIccProfile().

  const derivatives = [];

  // ─── Шаг 6. Уменьшаем в набор размеров, сохраняем два формата ───
  for (const width of TARGET_WIDTHS) {
    // Маленькую картинку не растягиваем: выйдет мыло и лишний файл.
    if (width > realWidth) continue;

    // clone() даёт независимую копию конвейера: одну заготовку
    // можно разветвить на несколько выходов.
    const resized = base.clone().resize({
      width,
      fit: 'inside',            // вписать целиком, не обрезая
      withoutEnlargement: true, // никогда не увеличивать
    });

    // WebP — для всех современных браузеров, JPEG — как запас.
    const webp = await resized.clone().webp({ quality: 78 }).toBuffer();
    const jpeg = await resized.clone().jpeg({ quality: 80 }).toBuffer();

    await storage.put(folder + '/w' + width + '.webp', webp);
    await storage.put(folder + '/w' + width + '.jpg', jpeg);

    derivatives.push({ width, webpBytes: webp.length, jpegBytes: jpeg.length });
  }

  // ─── Шаг 7. Заготовки для вёрстки: средний цвет и мини-копия ───
  // stats() считает статистику по точкам и среди прочего отдаёт
  // самый заметный цвет — им можно залить место заранее.
  const stats = await base.clone().stats();
  const dot = stats.dominant;
  const averageColor = 'rgb(' + dot.r + ', ' + dot.g + ', ' + dot.b + ')';

  // Мини-копия шириной 16 точек, размытая и сжатая жёстко. Весит
  // сотни байт, поэтому её можно вставить прямо в разметку строкой.
  const tiny = await base
    .clone()
    .resize({ width: 16 })
    .blur(1.2)
    .webp({ quality: 40 })
    .toBuffer();
  const tinyDataUrl = 'data:image/webp;base64,' + tiny.toString('base64');

  // ─── Шаг 8. Пишем в базу то, что понадобится странице ───
  const record = {
    id: folder,
    ownerId: ownerId,
    format: head.format,
    width: realWidth,
    height: realHeight,
    averageColor: averageColor,
    tinyDataUrl: tinyDataUrl,
    derivatives: derivatives,
  };
  await db.images.insert(record);
  return record;
}


