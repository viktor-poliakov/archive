// ═══ ЧАСТЬ 1. ПРОГРЕСС ОТПРАВКИ: ТОЛЬКО XMLHttpRequest ═══
// Обычный fetch НЕ сообщает, сколько байт уже ушло в сеть.
// Поэтому для индикатора отправки берут старый XMLHttpRequest:
// у него есть отдельный объект xhr.upload с событием прогресса.

function uploadWithProgress(file, url, handlers) {
  const onProgress = handlers.onProgress; // процент 0..100
  const onPhase = handlers.onPhase;       // 'sending' | 'finishing' | 'done'
  const signal = handlers.signal;         // для кнопки «Отмена»

  return new Promise((resolve, reject) => {
    const xhr = new XMLHttpRequest();
    xhr.open('PUT', url);
    xhr.timeout = 10 * 60 * 1000; // 10 минут на один файл
    onPhase('sending');

    // ВАЖНО: прогресс ОТПРАВКИ живёт на xhr.upload.
    // Такое же событие на самом xhr — это прогресс ПОЛУЧЕНИЯ ответа,
    // и индикатор на нём будет стоять на нуле до самого конца.
    xhr.upload.addEventListener('progress', (event) => {
      if (!event.lengthComputable) {
        onProgress(null); // размер неизвестен: крутим неопределённую полоску
        return;
      }
      onProgress(Math.round((event.loaded / event.total) * 100));
    });

    // Байты кончились, но работа НЕТ: хранилище ещё дописывает и склеивает.
    // Показываем отдельную фазу, иначе человек видит замершие 100%
    // и жмёт кнопку второй раз.
    xhr.upload.addEventListener('load', () => onPhase('finishing'));

    xhr.addEventListener('load', () => {
      if (xhr.status >= 200 && xhr.status < 300) {
        onPhase('done');
        resolve(xhr.responseText);
      } else {
        reject(new Error('Хранилище ответило ' + xhr.status)); // [!error]
      }
    });
    xhr.addEventListener('error', () => {
      reject(new Error('Пропала сеть, файл не загружен')); // [!error]
    });
    xhr.addEventListener('timeout', () => {
      reject(new Error('Загрузка идёт слишком долго')); // [!error]
    });
    xhr.addEventListener('abort', () => {
      reject(new DOMException('Отменено пользователем', 'AbortError'));
    });

    // Одна и та же кнопка «Отмена» работает и здесь, и во fetch-версии.
    if (signal) signal.addEventListener('abort', () => xhr.abort());

    xhr.send(file); // File и Blob можно отправлять как есть
  });
}


