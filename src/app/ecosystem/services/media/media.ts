// server/validate-upload.js — три уровня проверки принятого файла
// ─────────────────────────────────────────────────────────────────────

import { open } from 'node:fs/promises';
import path from 'node:path';

// ── УРОВЕНЬ 1. Размер ──
const MAX_BYTES = 5 * 1024 * 1024;

// ── УРОВЕНЬ 2. Заявленный тип ──
// Белый список: перечисляем разрешённое и допустимые для него расширения.
const ALLOWED = new Map([
  ['image/png', ['.png']],
  ['image/jpeg', ['.jpg', '.jpeg']],
  ['image/gif', ['.gif']],
  ['image/webp', ['.webp']],
  ['application/pdf', ['.pdf']],
]);

// НАИВНАЯ версия, которую пишут почти все: чёрный список расширений.
// Она не проверяет ничего. Расширение переименовывается в один клик,
// а перечислить все опасные форматы невозможно в принципе.
function looksSafeNaive(fileName) {
  const ext = path.extname(fileName).toLowerCase();
  const banned = ['.exe', '.php', '.sh', '.bat'];         // [!error]
  return !banned.includes(ext);                            // [!error]
}

// ── УРОВЕНЬ 3. Настоящее содержимое ──
// Подпись формата — это первые байты файла, по которым видно,
// чем он является на самом деле. Отправитель их не выбирает:
// без правильной подписи файл не откроет ни одна программа.
const SIGNATURES = [
  { type: 'image/png', bytes: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  { type: 'image/jpeg', bytes: [0xff, 0xd8, 0xff] },
  { type: 'image/gif', bytes: [0x47, 0x49, 0x46, 0x38] },   // 'GIF8'
  { type: 'application/pdf', bytes: [0x25, 0x50, 0x44, 0x46] }, // '%PDF'
];

function startsWith(head, bytes) {
  if (head.length < bytes.length) return false;
  for (let i = 0; i < bytes.length; i += 1) {
    if (head[i] !== bytes[i]) return false;
  }
  return true;
}

// WebP устроен хитрее: 'RIFF' в байтах 0..3, длина в 4..7,
// и только потом 'WEBP' в байтах 8..11.
function isWebp(head) {
  return head.length >= 12
    && head.toString('latin1', 0, 4) === 'RIFF'
    && head.toString('latin1', 8, 12) === 'WEBP';
}

function detectRealType(head) {
  if (isWebp(head)) return 'image/webp';
  for (const rule of SIGNATURES) {
    if (startsWith(head, rule.bytes)) return rule.type;
  }
  return null;   // подпись не из белого списка — значит, не принимаем
}

// Читаем только начало файла: 32 байта хватает на все подписи выше.
async function readHead(filePath, length = 32) {
  const file = await open(filePath, 'r');
  try {
    const head = Buffer.alloc(length);
    const { bytesRead } = await file.read(head, 0, length, 0);
    return head.subarray(0, bytesRead);
  } finally {
    await file.close();
  }
}

// Правильная проверка: все три уровня по очереди, ошибки собираем в список.
export async function validateUpload({ filePath, fileName, declaredType, size }) {
  const problems = [];

  // 1. Размер. В браузере он тоже проверяется, но только ради опечатки
  // пользователя: запрос можно отправить и без вашей страницы.
  if (!Number.isInteger(size) || size <= 0) {
    problems.push('размер файла неизвестен');
  } else if (size > MAX_BYTES) {
    problems.push('файл больше 5 МБ');
  }

  // 2. Заявленный тип и расширение — это то, что СКАЗАЛ отправитель.
  // Проверяем их только для быстрого отказа, доверия к ним нет.
  const ext = path.extname(fileName).toLowerCase();
  const allowedExts = ALLOWED.get(declaredType);
  if (!allowedExts) {
    problems.push('тип ' + declaredType + ' не в белом списке');
  } else if (!allowedExts.includes(ext)) {
    problems.push('расширение ' + ext + ' не подходит типу ' + declaredType);
  }

  // 3. Настоящее содержимое. Единственная проверка, которую нельзя обмануть
  // переименованием: смотрим на сами байты.
  const head = await readHead(filePath);
  const realType = detectRealType(head);
  if (!realType) {
    problems.push('формат не распознан или запрещён');
  } else if (allowedExts && realType !== declaredType) {
    problems.push('внутри ' + realType + ', а заявлен ' + declaredType);
  }

  if (problems.length > 0) {
    const error = new Error('Файл отклонён: ' + problems.join('; ')); // [!error]
    error.status = 415;
    throw error;
  }

  // Возвращаем настоящий тип: дальше в базу пишем ЕГО, а не слова браузера.
  return { realType, ext, size };
}

