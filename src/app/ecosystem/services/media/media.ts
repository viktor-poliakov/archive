// Тело запроса — сам объект File, без FormData и без обёрток.
async function putToStorage(uploadUrl, file) {
  const res = await fetch(uploadUrl, {
    method: 'PUT',
    headers: { 'content-type': file.type },  // должен совпасть с подписанным
    body: file,
  });
  if (!res.ok) {
    throw new Error('Хранилище отказало, код ' + res.status); // [!error]
  }
}

// Вариант шага 2 с полосой прогресса: fetch не умеет сообщать,
// сколько байт уже ушло, а старый XMLHttpRequest умеет.
function putWithProgress(uploadUrl, file, onProgress) {
  return new Promise((resolve, reject) => {
    const xhr = new XMLHttpRequest();
    xhr.open('PUT', uploadUrl);
    xhr.setRequestHeader('content-type', file.type);
    xhr.upload.onprogress = (event) => {
      if (event.lengthComputable) {
        onProgress(Math.round((event.loaded / event.total) * 100));
      }
    };
    xhr.onload = () => {
      if (xhr.status >= 200 && xhr.status < 300) resolve();
      else reject(new Error('Хранилище отказало, код ' + xhr.status));
    };
    xhr.onerror = () => reject(new Error('Сеть оборвалась'));
    xhr.send(file);
  });
}

// Шаг 3. Подтверждение. Именно оно превращает «объект в хранилище»
// в «файл, о котором знает ваша база». Шаг хрупкий: сеть может пропасть
// ровно между вторым и третьим запросом, поэтому повторяем попытки.
async function confirmUpload(key, attempt = 1) {
  const res = await fetch('/api/uploads/complete', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ key }),
  });
  if (res.ok) return res.json();

  if (attempt < 3) {
    await new Promise((done) => setTimeout(done, attempt * 700));
    return confirmUpload(key, attempt + 1);
  }

  // Все попытки исчерпаны. Объект в хранилище лежит, база о нём не знает:
  // это сирота. Убирать её будет сервер — по уведомлению от хранилища
  // либо уборкой по расписанию.
  throw new Error('Файл загружен, но не подтверждён'); // [!error]
}

export async function uploadFile(file, onProgress) {
  if (file.size > MAX_BYTES) {
    throw new Error('Файл больше 5 МБ'); // [!error]
  }
  const { uploadUrl, key } = await askForLink(file);
  if (onProgress) await putWithProgress(uploadUrl, file, onProgress);
  else await putToStorage(uploadUrl, file);
  return confirmUpload(key);
}
