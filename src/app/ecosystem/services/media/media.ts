// Настоящие имена из AWS SDK v3; у других хранилищ с совместимым
// протоколом (Yandex Object Storage, VK Cloud, MinIO) тот же код,
// меняется только endpoint и регион.
import { S3Client, GetObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

const s3 = new S3Client({ region: 'eu-central-1' });
const BUCKET = 'app-user-files';

// Обработчик: GET /api/files/:id/download
// Отдаёт не сам файл, а адрес, по которому файл можно забрать.
async function handleDownload(req, res) {
  // ── 1. Кто это вообще. Нет сессии - дальше не идём.
  const user = await authenticate(req);
  if (!user) {
    return res.status(401).json({ error: 'Нужно войти' }); // [!error]
  }

  // ── 2. Что за файл. Ищем запись в базе по идентификатору из адреса.
  const record = await db.files.findById(req.params.id);
  if (!record) {
    return res.status(404).json({ error: 'Файл не найден' }); // [!error]
  }

  // ── 3. Имеет ли ЭТОТ пользователь право на ЭТОТ файл.
  // Проверка идёт до подписи. Это принципиально: подпись - это уже
  // выдача доступа, и выдавать его до проверки нельзя ни на секунду.
  const allowed = await canUserReadFile(user, record);
  if (!allowed) {
    // Иногда отвечают 404 вместо 403: если сам факт существования
    // файла - секрет, посторонний не должен узнать даже это.
    return res.status(403).json({ error: 'Нет доступа' }); // [!error]
  }

  // ── 4. Только теперь подписываем адрес, и только на ЧТЕНИЕ.
  const command = new GetObjectCommand({
    Bucket: BUCKET,
    Key: record.storageKey,
    // Имя файла для диалога сохранения передаём параметрами подписи:
    // хранилище подставит их в заголовки своего ответа.
    ResponseContentDisposition: contentDisposition(record.originalName),
    ResponseContentType: record.mimeType,
  });

  // expiresIn - срок жизни подписи в секундах. 300 - это пять минут.
  const url = await getSignedUrl(s3, command, { expiresIn: 300 });

  // ── 5. Отдаём адрес клиенту. Он ведёт прямо в хранилище или на CDN,
  // мимо вашего сервера: байты через вас больше не идут.
  return res.json({ url: url, expiresIn: 300 });
}

