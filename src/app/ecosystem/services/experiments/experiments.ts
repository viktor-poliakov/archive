// ШАГ 2. РАСПРЕДЕЛЕНИЕ ПОЛЬЗОВАТЕЛЯ ПО ВАРИАНТУ
// ──────────────────────────────────────────────────────────────────
// Один человек всегда должен видеть один и тот же вариант. Поэтому
// вариант не разыгрывают монеткой при каждой загрузке, а ВЫЧИСЛЯЮТ
// из постоянного идентификатора: одинаковый вход — одинаковый выход.

// Стабильный хеш строки (алгоритм FNV-1a). Даёт одно и то же число
// для одной и той же строки — сегодня, завтра и на другом сервере.
function stableHash(text) {
  let hash = 2166136261;                // стартовое число алгоритма
  for (let i = 0; i < text.length; i++) {
    hash = hash ^ text.charCodeAt(i);   // подмешиваем очередной символ
    hash = Math.imul(hash, 16777619);   // умножаем на «магическое» число
  }
  return hash >>> 0;                    // делаем число неотрицательным
}

// Ключ эксперимента подмешан к идентификатору специально: в другом
// эксперименте тот же человек попадёт в другую группу, и два теста
// не «слипнутся» друг с другом.
function assignVariant(userId, experimentKey) {
  const bucket = stableHash(experimentKey + ':' + userId) % 100;  // число 0..99
  return bucket < 50 ? 'control' : 'treatment';
}


