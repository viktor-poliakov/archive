// FNV-1a — обычная быстрая хеш-функция. Криптостойкость здесь не нужна:
// мы ничего не защищаем, нам надо лишь ровно размазать людей по корзинам.
// Главное её свойство: одна и та же строка ВСЕГДА даёт одно и то же число.
function hashString(input) {
  let hash = 0x811c9dc5;               // стартовое число, часть алгоритма
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);       // подмешиваем очередной символ
    hash = Math.imul(hash, 0x01000193); // умножение в 32-битной арифметике
  }
  return hash >>> 0;                   // приводим к целому без знака
}

// Номер корзины — всегда число от 0 до 99.
// Имя флага в строке обязательно: иначе у человека будет одна корзина
// на все флаги сразу и подопытными везде окажутся одни и те же люди.
function bucketOf(flagKey, subjectId) {
  return hashString(flagKey + ':' + subjectId) % 100;
}


