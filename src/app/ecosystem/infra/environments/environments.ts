export function isEnabled(key: string, userId: string): boolean {
  const flag = cache.get(key);

  // Флага нет в базе — считаем ВЫКЛЮЧЕННЫМ. Безопасное поведение по умолчанию:
  // опечатка в имени должна оставлять старое поведение, а не включать новое.
  if (!flag || !flag.enabled) return false;

  if (flag.rolloutPercent >= 100) return true;
  if (flag.rolloutPercent <= 0) return false;

  // Постепенная раскатка. Ключевое требование: ОДИН И ТОТ ЖЕ пользователь
  // должен получать ОДИН И ТОТ ЖЕ ответ всегда. Поэтому не Math.random(),
  // а устойчивое число, посчитанное из его идентификатора и имени флага.
  // Имя флага в основе — чтобы разные флаги попадали на разных людей,
  // иначе «первые 10%» получат сразу все эксперименты подряд.
  const bucket = stableHash(key + ':' + userId) % 100;
  return bucket < flag.rolloutPercent;
}

// Простая устойчивая свёртка строки в число (алгоритм FNV-1a).
// Для распределения по корзинам её достаточно; для безопасности — нет.
function stableHash(input: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return Math.abs(h);
}

