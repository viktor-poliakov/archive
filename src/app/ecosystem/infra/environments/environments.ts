const problems: string[] = [];

function required(name: string): string {
  const raw = process.env[name];
  // Пустая строка — тоже «не задано». В панелях хостинга легко случайно
  // сохранить переменную с пустым значением, и это надо ловить.
  if (raw === undefined || raw.trim() === '') {
    problems.push('  * ' + name + ' — обязательная переменная, значение не задано');
    return '';
  }
  return raw.trim();
}

function optional(name: string, fallback: string): string {
  const raw = process.env[name];
  return raw === undefined || raw.trim() === '' ? fallback : raw.trim();
}

function requiredNumber(name: string, fallback?: number): number {
  const raw = process.env[name];
  if (raw === undefined || raw.trim() === '') {
    if (fallback !== undefined) return fallback;
    problems.push('  * ' + name + ' — обязательное число, значение не задано');
    return 0;
  }
  const value = Number(raw);
  // Number('abc') даёт NaN, а NaN тихо расползается по всем вычислениям.
  if (!Number.isFinite(value)) {
    problems.push('  * ' + name + ' — ожидалось число, пришло: "' + raw + '"');
    return 0;
  }
  return value;
}

function requiredBoolean(name: string, fallback: boolean): boolean {
  const raw = process.env[name];
  if (raw === undefined || raw.trim() === '') return fallback;
  const value = raw.trim().toLowerCase();
  if (value === 'true' || value === '1') return true;
  if (value === 'false' || value === '0') return false;
  problems.push('  * ' + name + ' — ожидалось true или false, пришло: "' + raw + '"');
  return fallback;
}

function oneOf<T extends string>(name: string, allowed: readonly T[], fallback: T): T {
  const raw = (process.env[name] ?? '').trim();
  if (raw === '') return fallback;
  if (!allowed.includes(raw as T)) {
    problems.push('  * ' + name + ' — допустимо только: ' + allowed.join(', ') + '; пришло: "' + raw + '"');
    return fallback;
  }
  return raw as T;
}

