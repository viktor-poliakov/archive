// сервис на обычной машине, специализированный сервис перекодирования.
// Тот, у кого нет предела в десятки секунд. Он берёт задачу из очереди,
// работает сколько нужно и в конце выставляет status: 'ready'.
// Браузер тем временем опрашивает GET /api/video-jobs/<jobId>
// и показывает пользователю «обрабатывается».

// ═══ ОТДЕЛЬНО И ВАЖНО: ФУНКЦИЯ ОБЯЗАНА БЫТЬ ИДЕМПОТЕНТНОЙ ═══
// Идемпотентная — значит «повторный вызов с теми же данными
// не делает лишнего и не портит результат».
//
// Почему это не пожелание, а требование: ПЛАТФОРМА МОЖЕТ ПОЗВАТЬ ВАС ПОВТОРНО.
// Причины повтора, все реальные:
//   • сеть моргнула, платформа не получила подтверждение и вызвала снова;
//   • очередь гарантирует доставку «хотя бы один раз» — значит, иногда дважды;
//   • пользователь дважды нажал кнопку;
//   • браузер повторил запрос сам после разрыва.
//
// НЕидемпотентно: каждый вызов создаёт новую работу, списывает деньги ещё раз,
// шлёт ещё одно письмо. Идемпотентно — так:

export default async function idempotentUploadHandler(request) {
  const form = await request.formData();
  const productId = form.get('productId');

  // Ключ приходит ОТ КЛИЕНТА и не меняется при повторе той же попытки.
  // Клиент генерирует его один раз перед отправкой формы.
  const idempotencyKey = request.headers.get('idempotency-key');
  if (!idempotencyKey) {
    return Response.json({ error: 'idempotency-key required' }, { status: 400 });
  }

  // Уже видели этот ключ? Значит, это повтор. Возвращаем ТОТ ЖЕ ответ,
  // ничего не делая заново. Пользователю снаружи разницы не видно.
  const existing = await db.findVideoJobByKey(idempotencyKey);
  if (existing) {
    return Response.json({ jobId: existing.jobId, status: existing.status }, { status: 202 });
  }

  const jobId = crypto.randomUUID();
  const sourceKey = 'uploads/' + productId + '/' + jobId + '.mp4';
  await storage.put(sourceKey, form.get('video'));

  // Вставка с ограничением уникальности по idempotencyKey — на случай,
  // если два повтора пришли ОДНОВРЕМЕННО и оба не нашли записи выше.
  // Проверка «а есть ли уже» без уникального индекса ничего не гарантирует.
  await db.createVideoJob({ jobId, productId, sourceKey, idempotencyKey, status: 'queued' });
  await queue.send('video-transcode', { jobId, productId, sourceKey });

  return Response.json({ jobId, status: 'queued' }, { status: 202 });
}

