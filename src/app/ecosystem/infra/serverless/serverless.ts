  // Шаг 1. Положить исходник. Это быстро и предсказуемо.
  await storage.put(sourceKey, file);

  // Шаг 2. Записать в базу, что работа принята и ещё не сделана.
  // Пользователю будет что показать, а нам — что чинить, если зависнет.
  await db.createVideoJob({ jobId, productId, sourceKey, status: 'queued' });

  // Шаг 3. Положить задачу в очередь. Миллисекунды: мы кладём записку,
  // а не делаем работу. Про очереди подробно — в разделе «Очереди задач».
  await queue.send('video-transcode', { jobId, productId, sourceKey });

  // Шаг 4. Ответить СРАЗУ и честно: «принято, ещё не готово».
  // 202 Accepted — код именно про это.
  return Response.json({ jobId, status: 'queued' }, { status: 202 });
