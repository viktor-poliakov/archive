let isShuttingDown = false;

async function shutdown(signal) {
  // Защита от повторного входа: сигнал может прийти дважды
  // (например, вы нажали Ctrl+C, а потом нетерпеливо ещё раз).
  if (isShuttingDown) return;
  isShuttingDown = true;

  console.log('Получен сигнал ' + signal + ', начинаю аккуратное завершение');

  // ШАГ 1. ПРЕДОХРАНИТЕЛЬ. Заводим таймер принудительного выхода
  // ПЕРВЫМ делом — до всех await, иначе он не заведётся, если
  // какой-то из шагов зависнет навсегда.
  const forceExit = setTimeout(() => {
    console.error('Не уложились в отведённое время — выхожу принудительно');
    process.exit(1);
  }, 15000);

  // unref() говорит: «этот таймер сам по себе не должен держать
  // процесс живым». Если всё закроется за две секунды — процесс
  // выйдет через две секунды, а не будет ждать таймер.
  forceExit.unref();

  try {
    // ШАГ 2. Перестаём принимать НОВЫЕ соединения.
    // Важно: server.close() НЕ рвёт уже идущие запросы —
    // он лишь закрывает «входную дверь» и ждёт, пока доработают текущие.
    await new Promise((resolve, reject) => {
      server.close((err) => (err ? reject(err) : resolve()));
    });
    console.log('Все запросы, которые были в работе, обслужены');

    // ШАГ 3. Теперь, когда запросов нет, отпускаем ресурсы.
    // Порядок важен: сначала клиенты, потом база — иначе последний
    // запрос обратится в уже закрытый пул соединений.
    await queueWorker.close();   // работник очереди дорабатывает задачу
    await pool.end();            // пул соединений с PostgreSQL
    await redis.quit();          // соединение с Redis

    clearTimeout(forceExit);
    console.log('Завершение прошло штатно');
    process.exit(0);
  } catch (err) {
    console.error('Ошибка при завершении', err);
    process.exit(1);
  }
}

