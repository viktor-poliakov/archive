// ═══ ХУЖЕ: ВНЕШНИЙ ПУЛЕР ═══
//
// Часто между приложением и PostgreSQL ставят ещё один пул —
// отдельную программу, например PgBouncer. В режиме transaction
// pooling («пул на транзакцию») серверное соединение отдаётся
// клиенту ТОЛЬКО НА ВРЕМЯ ТРАНЗАКЦИИ, а потом уходит к другому.
//
// Документация PgBouncer (раздел features) прямо помечает SET и RESET
// как «Never» поддерживаемые в этом режиме. Причина ровно та,
// что описана выше: сессионное состояние переживает транзакцию
// и достаётся следующему клиенту.
//
// То есть с внешним пулером обычный SET app.tenant_id не просто
// рискован — он гарантированно ведёт себя не так, как вы думаете.

// ═══ КАК НАДО ═══
//
// Штатное решение: делать переменную ЛОКАЛЬНОЙ ДЛЯ ТРАНЗАКЦИИ.
// Два эквивалентных способа:
//   SET LOCAL app.tenant_id = '...';
//   SELECT set_config('app.tenant_id', '...', true);   // true = local
// В обоих случаях по завершении транзакции значение исчезает само.

async function withTenant(pool, ctx, work) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    // Значение передаём ПАРАМЕТРОМ, а не склейкой строк —
    // иначе получаем ещё и SQL-инъекцию поверх утечки.
    // Третий аргумент true делает переменную транзакционной:
    // после COMMIT/ROLLBACK её не существует.
    await client.query('SELECT set_config($1, $2, true)', [
      'app.tenant_id',
      ctx.tenantId,
    ]);

    const result = await work(client);

    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    // Даже если что-то пошло не так, соединение возвращается
    // в пул БЕЗ следов арендатора: транзакция закрыта,
    // транзакционная переменная умерла вместе с ней.
    client.release();
  }
}

