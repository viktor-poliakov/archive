// Базовый класс. Все репозитории наследуются от него и получают
// готовый «доводчик».
class TenantScopedRepository {
  constructor(pool, ctx, table) {
    if (!(ctx instanceof TenantContext)) {
      // Вот здесь и происходит главное. Забыть арендатора нельзя:
      // объект просто не создастся.
      throw new Error('Репозиторий требует TenantContext');
    }
    this.pool = pool;
    this.ctx = ctx;
    this.table = table;
  }

  // Внутренний помощник: любой запрос через него получает
  // условие по арендатору ПЕРВЫМ, а параметры пользователя
  // сдвигаются на одну позицию.
  async find(whereSql, params = []) {
    // Параметры пользователя нумеруются с $2, потому что $1 занят
    // арендатором. Это не косметика: так невозможно случайно
    // «перебить» условие арендатора своим.
    const shifted = whereSql.replace(/\\$(\\d+)/g, (_, n) => '$' + (Number(n) + 1));
    const sql =
      'SELECT * FROM ' + this.table +
      ' WHERE tenant_id = $1' +
      (shifted ? ' AND (' + shifted + ')' : '');
    const rows = await this.pool.query(sql, [this.ctx.tenantId, ...params]);
    return rows;
  }

  async findById(id) {
    const rows = await this.find('id = $1', [id]);
    return rows[0] ?? null;
  }

  async insert(data) {
    // Арендатор проставляется НАМИ, а не приходит из данных.
    // Если он всё же пришёл снаружи — это подозрительно, и мы
    // отказываем, а не «доверяем последнему значению».
    if ('tenant_id' in data && data.tenant_id !== this.ctx.tenantId) {
      throw new Error('Попытка записать строку в чужого арендатора');
    }
    const row = { ...data, tenant_id: this.ctx.tenantId };
    const cols = Object.keys(row);
    const placeholders = cols.map((_, i) => '$' + (i + 1));
    const sql =
      'INSERT INTO ' + this.table +
      ' (' + cols.join(', ') + ') VALUES (' + placeholders.join(', ') + ') RETURNING *';
    const rows = await this.pool.query(sql, Object.values(row));
    return rows[0];
  }

  async updateById(id, patch) {
    const cols = Object.keys(patch);
    // $1 — арендатор, $2 — id, дальше значения.
    const sets = cols.map((c, i) => c + ' = $' + (i + 3));
    const sql =
      'UPDATE ' + this.table + ' SET ' + sets.join(', ') +
      ' WHERE tenant_id = $1 AND id = $2 RETURNING *';
    const rows = await this.pool.query(
      sql,
      [this.ctx.tenantId, id, ...Object.values(patch)],
    );
    // Ноль строк означает «такой записи у ЭТОГО арендатора нет».
    // Отвечаем «не найдено», а не «запрещено»: иначе мы подсказываем,
    // что запись существует у кого-то другого.
    return rows[0] ?? null;
  }

  async deleteById(id) {
    const rows = await this.pool.query(
      'DELETE FROM ' + this.table + ' WHERE tenant_id = $1 AND id = $2 RETURNING id',
      [this.ctx.tenantId, id],
    );
    return rows.length > 0;
  }
}

