class InvoiceRepository extends TenantScopedRepository {
  constructor(pool, ctx) {
    super(pool, ctx, 'invoices');
  }

  // Прикладные методы пишутся уже без мыслей об арендаторе —
  // он подставится сам.
  listUnpaid(limit = 50) {
    return this.find("status = $1 ORDER BY created_at DESC LIMIT " + Number(limit), ['unpaid']);
  }

  overdue(days = 30) {
    return this.find(
      "status = 'unpaid' AND created_at < now() - ($1 || ' days')::interval",
      [String(days)],
    );
  }
}

