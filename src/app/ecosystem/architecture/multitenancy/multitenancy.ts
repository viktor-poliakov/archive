class TenantRegistry {
  constructor(controlPlaneDb, cache) {
    this.db = controlPlaneDb;   // отдельная маленькая база платформы
    this.cache = cache;
  }

  // Разрешение арендатора: по короткому имени возвращаем всё,
  // что нужно знать о его размещении.
  async resolve(slug) {
    const cached = await this.cache.get('registry:' + slug);
    if (cached) return cached;

    const row = await this.db.query(
      'SELECT id, slug, tier, region, db_alias, schema_name, status ' +
      'FROM tenant_placements WHERE slug = $1',
      [slug],
    );
    if (row.length === 0) return null;

    const placement = row[0];

    // Кэш короткий: сюда попадают переезды между базами, и мы
    // не хотим, чтобы после переезда часть серверов ещё десять
    // минут ходила в старую базу. Пять минут — разумный компромисс.
    await this.cache.set('registry:' + slug, placement, { ttlSeconds: 300 });
    return placement;
  }
}

