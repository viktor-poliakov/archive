// ═══ ЛОВУШКА 2. RLS МОЖЕТ ИСПОРТИТЬ ПЛАНЫ ЗАПРОСОВ ═══
//
// Политика — это обычный предикат, и хорошая новость в том, что она
// УМЕЕТ пользоваться индексом. Поэтому первое и обязательное:
// индекс, начинающийся с tenant_id, должен существовать. Без него
// каждая политика превращается в полный просмотр таблицы.
//
// Плохая новость сложнее и звучит так.
//
// БЕДА 1. Не все ваши условия можно вычислить раньше политики.
//   В PostgreSQL у функций и операторов есть свойство LEAKPROOF —
//   «не протекающий». Оно означает: эта функция не может выдать
//   информацию об аргументах через сообщение об ошибке.
//   Пример утечки без этого свойства: функция падает с текстом
//   «не могу разделить на ноль: значение 4815» — и вот вы уже узнали
//   значение из чужой строки, которую не имели права видеть.
//
//   Поэтому база НЕ ИМЕЕТ ПРАВА выполнять ваши не-LEAKPROOF условия
//   ДО условия политики. А раз условие нельзя выполнить раньше —
//   его нельзя и «провалить» внутрь просмотра индекса. Результат:
//   вместо аккуратного index scan получается seq scan, полный
//   просмотр таблицы, и запрос, который был быстрым, становится
//   медленным.
//
//   Масштаб проблемы: по подсчёту, приводившемуся в переписке
//   разработчиков PostgreSQL (ориентировочная, вторичная цифра),
//   387 встроенных операторов НЕ являются LEAKPROOF против
//   588, которые являются. То есть шанс наткнуться — заметный.
//
// БЕДА 2. Историческое наследие.
//   Изначально RLS реализовывался через подзапрос с барьером
