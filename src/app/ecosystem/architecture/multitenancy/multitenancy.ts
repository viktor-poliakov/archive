// ═══ ШАГ 2. ВЫГРУЗКА ═══

async function exportTenantData(ctx) {
  const bundle = new ExportBundle('tenant-' + ctx.tenantId);

  // 2.1. Данные из базы. Идём по описи таблиц, а не по памяти:
  // список таблиц берём из самой базы, чтобы новая таблица
  // попадала в выгрузку автоматически.
  for (const table of await listTenantTables()) {
    const rows = await streamQuery(
      'SELECT * FROM ' + table + ' WHERE tenant_id = $1',
      [ctx.tenantId],
    );
    // Пишем потоком, а не собираем в память: у крупного клиента
    // это могут быть гигабайты.
    await bundle.addJsonLines(table + '.jsonl', rows);
  }

  // 2.2. Файлы. В хранилище они лежат под префиксом арендатора —
  // если вы следовали карте течей, пункт про файлы.
  await bundle.addFiles('files/', storage.list('tenants/' + ctx.tenantId + '/'));

  // 2.3. Человекочитаемая часть. Выгрузка из ста файлов JSON
  // формально закрывает вопрос, но клиенту нужны его счета,
  // а не ваши внутренние структуры. Дайте хотя бы CSV
  // по главным сущностям — это то, что реально откроют.
  await bundle.addCsv('invoices.csv', await exportInvoicesForHumans(ctx));

  // 2.4. Опись: что внутри, за какой период, когда сделано.
  await bundle.addJson('manifest.json', {
    tenantId: ctx.tenantId,
    generatedAt: new Date().toISOString(),
    tables: await listTenantTables(),
    formatVersion: 1,
  });

  return bundle.finalize();   // ссылка живёт ограниченное время
}

// ═══ ШАГ 3. УДАЛЕНИЕ. И ЧТО ЕМУ МЕШАЕТ ═══
//
// Здесь начинается самое интересное, потому что «просто удалить»
// не получается.

async function deleteTenant(tenantId, options) {
  // ── ЭТАП 1. МЯГКОЕ УДАЛЕНИЕ (обычно 30 дней) ──────────────────
  // Клиент отключён, данные ещё есть. Это защита от ошибки:
  // «мы передумали» и «нажали не ту кнопку» случаются регулярно,
  // а вот «верните из небытия» — не работает.
  await registry.setStatus(tenantId, 'suspended');
  await sessions.revokeAllForTenant(tenantId);      // всех выкинуть
  await queues.cancelPendingForTenant(tenantId);    // задачи снять
  await cache.deleteByPrefix('t:' + tenantId + ':');
  await search.deleteByTenant(tenantId);
  await webhooks.disableForTenant(tenantId);        // и внешние вызовы

  if (!options.hardDeleteNow) {
    await scheduler.schedule('tenant.hard-delete', {
      tenantId,
      runAt: daysFromNow(30),
    });
    return { state: 'suspended', hardDeleteAt: daysFromNow(30) };
  }

  // ── ЭТАП 2. ЖЁСТКОЕ УДАЛЕНИЕ ──────────────────────────────────
  // Порядок важен: сначала дети, потом родители, иначе внешние
  // ключи не дадут. Или один DELETE по корню с каскадом,
  // если схема выстроена как в разделе про общую таблицу.
  await withTenant(pool, new TenantContext(tenantId, 'offboarding'), async (db) => {
    for (const table of await listTenantTablesInDeletionOrder()) {
      await db.query('DELETE FROM ' + table + ' WHERE tenant_id = $1', [tenantId]);
    }
  });

  await storage.deletePrefix('tenants/' + tenantId + '/');
  await analytics.deleteByTenant(tenantId);
  await thirdParty.removeCustomer(tenantId);   // почта, платежи, поддержка

  // Свидетельство об удалении — оно нужно и клиенту, и вам.
  // Обратите внимание: в нём НЕТ персональных данных, только факт.
  await auditLog.write({
    event: 'tenant.deleted',
    tenantId,
    at: new Date().toISOString(),
    locations: TENANT_DATA_LOCATIONS.map((l) => l.kind),
  });

  return { state: 'deleted' };
}

