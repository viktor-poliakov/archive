// Контекст арендатора — маленький объект, который создаётся один раз
// на входящий запрос и дальше передаётся везде.
class TenantContext {
  constructor(tenantId, source) {
    // Первая линия обороны — простая проверка на входе.
    // Если сюда прилетело undefined, null или пустая строка,
    // мы падаем ГРОМКО и сразу, а не тихо отдаём чужие данные.
    if (typeof tenantId !== 'string' || tenantId.length === 0) {
      throw new Error('TenantContext: пустой tenantId — это всегда ошибка');
    }
    this.tenantId = tenantId;
    // source нужен для расследований: откуда мы вообще взяли
    // арендатора — из токена, из поддомена, из фоновой задачи.
    this.source = source;
    Object.freeze(this); // чтобы никто не переписал по дороге
  }
}

