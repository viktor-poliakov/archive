// квитанцией — кассир видит номер, находит запись «оплачено» и просто
// отдаёт вам копию чека, а не берёт деньги снова.

async function chargeCardSafely(order) {
  // Ключ создаётся ОДИН раз ДО цикла и не меняется между попытками.
  // Это принципиально: ключ внутри цикла превращает приём в тыкву.
  const idempotencyKey = order.idempotencyKey ?? crypto.randomUUID();

  const maxAttempts = 3;

  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    try {
      const response = await fetchWithTimeout('https://pay.example.com/charge', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          // Тот самый ключ. Название заголовка у каждого шлюза своё,
          // но приём общепринятый и поддерживается практически всеми.
          'Idempotency-Key': idempotencyKey,
        },
        body: JSON.stringify({ amount: order.total, card: order.cardToken }),
      }, 2000);

      // 2xx — успех, выходим.
      if (response.ok) return await response.json();

      // 4xx (кроме 429) — наша ошибка. Повторять НЕТ СМЫСЛА:
      // ответ будет тот же. Выходим сразу.
      if (response.status >= 400 && response.status < 500 && response.status !== 429) {
        throw new PaymentRejectedError(await response.text());
      }

      // 429 и 5xx — возможно, временно. Их повторять можно.
    } catch (e) {
      if (e instanceof PaymentRejectedError) throw e;   // не повторяем
      if (attempt === maxAttempts) throw e;             // попытки кончились
    }

    // ПАУЗА ПЕРЕД СЛЕДУЮЩЕЙ ПОПЫТКОЙ.
    // Растущая («экспоненциальная»): 200 мс, 400 мс, 800 мс.
    // Плюс случайная добавка (её называют jitter) — чтобы тысяча
    // клиентов не пришла повторять в одну и ту же миллисекунду.
    const base = 200 * Math.pow(2, attempt - 1);
    const jitter = Math.random() * base;
    await new Promise((resolve) => setTimeout(resolve, base + jitter));
  }

  throw new Error('оплата не прошла после ' + maxAttempts + ' попыток');
}

