// ═══ КОГДА СОЕДИНЕНИЕ БЕРУТ ВРУЧНУЮ (транзакции) ═══
//
// Транзакция — это несколько запросов, которые должны выполниться
// целиком или не выполниться вовсе. Все они обязаны идти по ОДНОМУ
// соединению, поэтому его берут явно. И обязательно возвращают.

async function withTransaction(fn) {
  const client = await pool.connect();       // взяли линию из пула
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (e) {
    await client.query('ROLLBACK');
    throw e;
  } finally {
    client.release();                        // ВЕРНУЛИ линию в пул
  }
}

// finally здесь не украшение. Без него любая ошибка внутри транзакции
// навсегда забирает одно соединение из пула. Десять таких ошибок —
// и пул из десяти линий мёртв, приложение стоит.

// ═══ ЧТО ПРОИСХОДИТ, КОГДА ПУЛ КОНЧИЛСЯ ═══
//
// Все линии заняты, приходит новый запрос. Дальше по шагам:
//
//   1. Запрос встаёт в очередь ожидания внутри процесса.
//   2. Пользователь видит крутящийся кружок — ответа нет.
//   3. Проходит connectionTimeoutMillis, запрос падает с ошибкой
//      вида «timeout exceeded when trying to connect».
//   4. Пользователь жмёт кнопку ещё раз — очередь становится длиннее.
//
// САМОЕ ВАЖНОЕ: симптом при этом обманчивый. В журнале база показывает
// быстрые запросы («у нас всё хорошо, 3 мс»), а пользователи видят
// пятисекундные ошибки. Потому что время уходит не на запрос,
// а на ОЖИДАНИЕ соединения. Отсюда правило: измеряйте отдельно
// «сколько ждали линию» и «сколько выполнялся запрос».
//
// Три типичные причины исчерпания пула:
//   • утечка — где-то забыли release();
//   • длинные запросы держат линии (отчёт на 40 секунд);
//   • внешний вызов ВНУТРИ транзакции — соединение занято, пока
//     платёжный шлюз думает. Никогда так не делайте.

// ═══ КАКОГО РАЗМЕРА ДЕЛАТЬ ПУЛ ═══
