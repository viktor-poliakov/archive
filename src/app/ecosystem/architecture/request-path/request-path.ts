// ═══ ЧТО С ЭТИМ СЛУЧИТСЯ В БОЮ ═══
//
// БЕДА 1. Каждый запрос платит за открытие соединения.
//   Сам SQL выполняется, скажем, за 2 мс, а открытие соединения —
//   десятки миллисекунд. Пользователь ждёт не работу, а подготовку
//   к работе.
//
// БЕДА 2. Под нагрузкой это кладёт базу.
//   500 запросов в секунду — это 500 попыток открыть соединение.
//   У PostgreSQL число соединений ограничено (параметр max_connections,
//   часто около сотни), и каждое стоит памяти. Когда лимит исчерпан,
//   база отвечает «sorry, too many clients already» — и падает ВСЁ,
//   включая те запросы, которые могли бы обслужиться.
//
// БЕДА 3. Забытый client.end() при ошибке.
//   В примере выше при исключении в query соединение не закроется
//   никогда. Каждая ошибка навсегда отъедает одну линию. Утечка
//   соединений — классика, и проявляется она через часы после выкладки.

// ═══ КАК НАДО: ОДИН ПУЛ НА ВЕСЬ ПРОЦЕСС ═══

