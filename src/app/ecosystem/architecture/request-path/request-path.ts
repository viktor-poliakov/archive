class OrderService {
  constructor(unitOfWork, payments, jobs) {
    this.unitOfWork = unitOfWork;
    this.payments = payments;
    this.jobs = jobs;
  }

  async placeOrder({ customerId, customerEmail, items, promoCode, idempotencyKey }) {
    // --- ЧАСТЬ А. Транзакция в базе: считаем и резервируем.  ~25 мс
    const draft = await this.unitOfWork.run(async ({ products, orders }) => {
      const ids = items.map((i) => i.productId);

      // ОДИН запрос на все товары — не N штук в цикле.        ~6 мс
      const found = await products.findManyForUpdate(ids);
      const byId = new Map(found.map((p) => [p.id, p]));

      let total = 0;
      for (const item of items) {
        const product = byId.get(item.productId);
        if (!product) throw new ProductNotFoundError(String(item.productId));
        if (product.stock < item.qty) throw new OutOfStockError(String(item.productId));
        total += Number(product.price) * item.qty;
      }

      // Чистые правила — работают за микросекунды.
      total = OrderService.applyPromo(total, promoCode);
      total += OrderService.deliveryPrice(total);

      await products.decreaseStock(items);                    // ~7 мс
      const orderId = await orders.insert({                   // ~5 мс
        customerId, total, status: 'awaiting_payment',
      });

      return { orderId, total };
    });
    // Транзакция ЗАКРЫТА. Это принципиально: дальше идёт внешний
    // вызов, и держать на нём соединение с базой нельзя ни секунды.

    // --- ЧАСТЬ Б. Оплата. Чужой сервис, самое долгое место. ~140 мс
    // Таймаут 2 с, ключ идемпотентности тот же, что у запроса.
    const payment = await this.payments.charge({
      amount: draft.total,
      customerId,
      idempotencyKey,
    });

    // --- ЧАСТЬ В. Отмечаем оплату. Короткая транзакция.      ~6 мс
    await this.unitOfWork.run(async ({ orders }) => {
      await orders.markPaid(draft.orderId, payment.id);
    });

    // --- ЧАСТЬ Г. Всё необязательное — в фон.                ~4 мс
    // Письмо, счёт, склад, аналитика. Пользователь их не ждёт.
    await this.jobs.enqueueMany([
      { name: 'order.email',     payload: { orderId: draft.orderId, customerEmail } },
      { name: 'order.invoice',   payload: { orderId: draft.orderId } },
      { name: 'order.warehouse', payload: { orderId: draft.orderId } },
      { name: 'order.analytics', payload: { orderId: draft.orderId } },
    ]);

    return { orderId: draft.orderId, total: draft.total, status: 'paid' };
  }
}

