class OutOfStockError extends Error {}
class ProductNotFoundError extends Error {}

class OrderService {
  constructor(unitOfWork, jobs) {
    this.unitOfWork = unitOfWork;   // умеет открыть транзакцию
    this.jobs = jobs;               // умеет поставить фоновую задачу
  }

  // ПРАВИЛА ДЕЛА — чистые функции, их можно проверить за миллисекунду.
  static applyPromo(total, promoCode) {
    return promoCode === 'WELCOME10' ? total * 0.9 : total;
  }

  static deliveryPrice(total) {
    return total >= 5000 ? 0 : 350;
  }

  async createOrder({ customerId, customerEmail, items, promoCode }) {
    return this.unitOfWork.run(async ({ products, orders }) => {
      const ids = items.map((i) => i.productId);
      const found = await products.findManyForUpdate(ids);
      const byId = new Map(found.map((p) => [p.id, p]));

      let total = 0;
      for (const item of items) {
        const product = byId.get(item.productId);
        if (!product) throw new ProductNotFoundError(String(item.productId));
        if (product.stock < item.qty) throw new OutOfStockError(String(item.productId));
        total += Number(product.price) * item.qty;
      }

      total = OrderService.applyPromo(total, promoCode);
      total += OrderService.deliveryPrice(total);

      await products.decreaseStock(items);
      const orderId = await orders.insert({ customerId, total, status: 'new' });

      // Письмо НЕ отправляем — ставим задачу. Отправкой займётся
      // отдельный процесс, и пользователь его не ждёт.
      this.jobs.enqueue('order.created', { orderId, customerEmail });

      return { orderId, total };
    });
  }
}

