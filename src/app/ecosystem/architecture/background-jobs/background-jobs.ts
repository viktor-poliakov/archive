export async function syncCatalogChunk({ shopId, cursor = 0, batchSize = 500 }) {
  // 1. Берём один кусок, а не всё сразу.
  const products = await db.products.findByShop(shopId, {
    afterId: cursor,
    limit: batchSize,
  });

  // 2. Кусков больше нет — работа закончена.
  if (products.length === 0) {
    await db.syncRuns.update({ shopId }, { status: 'done' });
    return { done: true };
  }

  // 3. Обрабатываем кусок.
  for (const product of products) {
    const remote = await fetch('https://partner.example.com/p/' + product.sku, {
      signal: AbortSignal.timeout(10000),
    });
    await db.products.update(product.id, await remote.json());
  }

  const lastId = products[products.length - 1].id;

  // 4. Сохраняем прогресс В БАЗУ. Именно эта строка превращает
  //    «начать заново» в «продолжить с места остановки».
  await db.syncRuns.update({ shopId }, { cursor: lastId, updatedAt: new Date() });

  // 5. Ставим СЛЕДУЮЩИЙ кусок отдельной задачей и выходим.
  //    Каждый кусок — это отдельная короткая задача со своими
  //    повторами, своей арендой и своей записью в метриках.
  await syncQueue.add('sync-chunk', { shopId, cursor: lastId, batchSize });

  return { processed: products.length, cursor: lastId };
}

