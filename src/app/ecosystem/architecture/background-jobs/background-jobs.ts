export async function replayDead({ jobName, since, limit = 500 }) {
  const jobs = await deadQueue.getJobs(['waiting'], 0, 10000);
  let replayed = 0;

  for (const job of jobs) {
    if (replayed >= limit) break;
    if (jobName && job.data.name !== jobName) continue;
    if (since && job.data.failedAt < since) continue;

    // Ставим обратно в исходную очередь. jobId с пометкой replay
    // нужен, чтобы не столкнуться с исходным идентификатором.
    await emailQueue.add(job.data.name, job.data.data, {
      jobId: 'replay:' + job.data.originalJobId,
      attempts: 3,
    });
    await job.remove(); // убираем из мёртвой очереди
    replayed++;
  }

  return { replayed };
}


