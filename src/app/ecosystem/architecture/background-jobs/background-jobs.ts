// Нужен потолок на всю задачу, и он должен быть согласован
// с арендой: пока задача работает, аренда продлевается, а по
// истечении потолка задача честно падает и уходит в повтор.

async function withDeadline(promise, ms, label) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), ms);
  try {
    return await Promise.race([
      promise(controller.signal),
      new Promise((_, reject) =>
        controller.signal.addEventListener('abort', () =>
          reject(new Error('Превышен предел времени: ' + label)),
        ),
      ),
    ]);
  } finally {
    clearTimeout(timer); // иначе таймер удержит процесс от выхода
  }
}

