export async function buildReport({ taskId, userId }) {
  await db.tasks.update(taskId, { status: 'running', startedAt: new Date() });

  try {
    const chunks = await getMonthChunks(userId); // например, 12 кусков

    for (let i = 0; i < chunks.length; i++) {
      await processChunk(chunks[i]);

      // Обновляем прогресс. Не чаще раза в секунду: иначе база
      // получит тысячи бессмысленных обновлений.
      await db.tasks.update(taskId, {
        progress: Math.round(((i + 1) / chunks.length) * 100),
        // Понятная человеку строка ценнее процентов.
        stage: 'Обрабатываю месяц ' + (i + 1) + ' из ' + chunks.length,
      });
    }

    const fileKey = await saveReportFile(userId);
    await db.tasks.update(taskId, {
      status: 'done',
      progress: 100,
      resultKey: fileKey,
      finishedAt: new Date(),
    });

    return { fileKey };
  } catch (err) {
    // Записываем провал ТОЛЬКО когда попытки кончились: иначе
    // пользователь увидит «ошибка», а задача успешно доедет
    // со второй попытки.
    await db.tasks.update(taskId, {
      status: 'failed',
      // Текст для человека, а не стектрейс. Технические подробности
      // уходят в систему ошибок, а не на экран пользователю.
      error: 'Не удалось собрать отчёт. Мы уже разбираемся.',
      finishedAt: new Date(),
    });
    throw err;
  }
}


