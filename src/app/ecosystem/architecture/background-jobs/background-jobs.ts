// Мёртвая очередь без ритуала разбора бесполезна: это та же куча,
// только в другом месте. Минимальный работающий ритуал:
//
//   ЕЖЕДНЕВНО. Автоматический отчёт «сколько задач умерло за сутки,
//     сгруппировано по тексту ошибки». Пять строк — читается за
//     минуту, и сразу видно, что сломалось.
//   ЕЖЕНЕДЕЛЬНО. Кто-то из команды разбирает накопившееся:
//     чинит, повторяет, удаляет заведомо мусорное.
//   ОПОВЕЩЕНИЕ. Если за час умерло больше N задач — будить дежурного.
//     Обычный порог: заметно больше обычного дневного фона.

export async function dailyDeadReport() {
  const jobs = await deadQueue.getJobs(['waiting'], 0, 10000);
  const dayAgo = Date.now() - 24 * 3600 * 1000;

  const groups = new Map();
  for (const job of jobs) {
    if (job.data.failedAt < dayAgo) continue;
    // Нормализуем текст ошибки: убираем идентификаторы и числа,
    // иначе каждая ошибка окажется уникальной и группировки не будет.
    const key =
      job.data.name + ' :: ' + String(job.data.failedReason).replace(/\\d+/g, 'N');
    groups.set(key, (groups.get(key) ?? 0) + 1);
  }

  const lines = [...groups.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, 10)
    .map(([reason, count]) => count + ' x ' + reason);

  return 'Умерло за сутки: ' + jobs.length + '\\n' + lines.join('\\n');
}


