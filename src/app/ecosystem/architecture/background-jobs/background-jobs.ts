async function handler(job) {
  try {
    return await sendOrderEmail(job.data);
  } catch (err) {
    // UnrecoverableError — специальный класс BullMQ: задача
    // немедленно уходит в failed, оставшиеся попытки не тратятся.
    if (isPermanent(err)) {
      throw new UnrecoverableError('Постоянная ошибка: ' + err.message);
    }
    // Всё остальное — обычный throw, будет повтор по стратегии.
    throw err;
  }
}

function isPermanent(err) {
  const status = err.response?.status;
  if (status && status >= 400 && status < 500 && status !== 429) {
    return true; // 4xx кроме 429 — наша вина, повтор не поможет
  }
  if (err instanceof TypeError) return true;   // баг в коде
  if (err instanceof SyntaxError) return true; // кривой JSON
  return false;
}


