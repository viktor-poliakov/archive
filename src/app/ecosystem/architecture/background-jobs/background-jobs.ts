import { handlers } from './handlers.js'; // { 'order-created': fn, ... }

const MODE = process.env.JOBS_MODE || 'queue'; // queue | inline | collect

export const collected = []; // для режима collect (тесты)

export async function enqueue(queueName, jobName, data, opts = {}) {
  // РЕЖИМ collect: ничего не выполняем, только записываем факт.
  // Тест потом проверит, что задача была поставлена.
  if (MODE === 'collect') {
    collected.push({ queueName, jobName, data, opts });
    return { id: 'collected-' + collected.length };
  }

  // РЕЖИМ inline: выполняем прямо здесь и сейчас.
  // Удобно для отладки и для тестов, где важен результат работы.
  if (MODE === 'inline') {
    const handler = handlers[jobName];
    if (!handler) throw new Error('Нет обработчика: ' + jobName);
    await handler(data);
    return { id: 'inline' };
  }

  // РЕЖИМ queue: обычный, боевой.
  return await queues[queueName].add(jobName, data, opts);
}

