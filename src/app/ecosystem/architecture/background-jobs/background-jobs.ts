// пяти работающих врачах — это пять минут. Три человека при одном
// ушедшем на обед враче — это час.

async function reportQueueLatency(queue, name) {
  // Берём самую старую ожидающую задачу. Порядок в списке
  // waiting — от старых к новым, поэтому нужен первый элемент.
  const [oldest] = await queue.getWaiting(0, 0);

  const latencySeconds = oldest
    ? (Date.now() - oldest.timestamp) / 1000
    : 0; // очередь пуста — ожидание нулевое

  metrics.gauge('queue.latency_seconds', latencySeconds, { queue: name });
  return latencySeconds;
}

