export async function sendOrderEmail({ orderId }) {
  const order = await db.orders.findById(orderId);

  // Заказ мог исчезнуть или измениться, пока задача ждала.
  // Это НОРМАЛЬНАЯ ситуация, а не ошибка.
  if (!order) return { skipped: 'order-not-found' };
  if (order.status === 'cancelled') return { skipped: 'cancelled' };

  const user = await db.users.findById(order.userId);
  if (!user || user.deletedAt) return { skipped: 'user-gone' };

  // Тяжёлый файл не передаём через очередь: он лежит в объектном
  // хранилище, а мы работаем со ссылкой на него.
  const pdfUrl = await storage.signedUrl(order.invoiceKey, { ttl: 3600 });

  await mailer.send({ to: user.email, attachmentUrl: pdfUrl });
  return { sentTo: user.email };
}


