app.get('/tasks/:id', async (req, res) => {
  const task = await db.tasks.findById(req.params.id);
  if (!task || task.userId !== req.user.id) {
    return res.status(404).json({ error: 'not found' });
  }

  res.json({
    status: task.status,        // queued | running | done | failed
    progress: task.progress,    // 0..100
    stage: task.stage,          // человеческая строка
    // Ссылку на результат отдаём только когда он есть,
    // и подписанную на короткое время.
    downloadUrl:
      task.status === 'done'
        ? await storage.signedUrl(task.resultKey, { ttl: 600 })
        : null,
    error: task.status === 'failed' ? task.error : null,
  });
});


// ═══ СПОСОБ 1: ОПРОС (POLLING) ═══
//
// Фронтенд сам спрашивает «ну как там?» с растущим интервалом.
// Простой, надёжный, работает везде. Начинать стоит с него.

async function waitForTask(taskId, onUpdate) {
  let delay = 1000;                 // первый опрос через секунду
  const deadline = Date.now() + 15 * 60 * 1000; // не ждём вечно

  while (Date.now() < deadline) {
    const res = await fetch('/tasks/' + taskId);
    const task = await res.json();
    onUpdate(task); // рисуем прогресс на экране

    if (task.status === 'done' || task.status === 'failed') return task;

    await new Promise((r) => setTimeout(r, delay));
    // Интервал растёт: 1с, 1.5с, 2.2с... но не больше 10 секунд.
    // Так мы не долбим сервер тысячей запросов на долгой задаче.
    delay = Math.min(delay * 1.5, 10000);
  }
  throw new Error('Слишком долго');
}

