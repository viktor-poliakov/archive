// Шаг 4. Повторы с нарастающей паузой и разбросом.
// Пауза нарастает, чтобы не добивать лежачего.
// Разброс (jitter) нужен, чтобы сто наших копий не пошли на
// повтор в одну и ту же миллисекунду и не устроили удар по складу.
async function callStockWithRetries(
  items: CartItem[],
  idempotencyKey: string,
): Promise<Reservation> {
  let lastError: unknown;

  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      return await callStockOnce(items, idempotencyKey);
    } catch (error) {
      lastError = error;

      // Повторяем ТОЛЬКО то, что имеет смысл повторять.
      if (!(error instanceof RetryableError)) {
        throw error;
      }
      if (attempt === MAX_ATTEMPTS) {
        break;
      }

      const backoff = BASE_BACKOFF_MS * 2 ** (attempt - 1);
      const jitter = Math.random() * backoff;
      await sleep(backoff + jitter);
    }
  }

  throw new StockUnavailableError('склад недоступен', { cause: lastError });
}

