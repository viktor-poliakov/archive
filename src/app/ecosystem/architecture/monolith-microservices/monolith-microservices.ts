// ИДЕЯ НА ПАЛЬЦАХ.
// Одну неделимую операцию заменяем ЦЕПОЧКОЙ маленьких шагов.
// Каждый шаг фиксируется сразу и по-настоящему. К каждому шагу
// заранее написан ОТМЕНЯЮЩИЙ шаг. Если цепочка сломалась на
// третьем шаге — выполняем отмены для второго и первого, в
// обратном порядке.
//
