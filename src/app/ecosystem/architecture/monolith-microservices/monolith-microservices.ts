// (БРОКЕР — это программа-посредник, куда складывают сообщения,
// чтобы их потом забрали другие. Как почтовый ящик: вы бросили
// письмо и ушли, а получатель заберёт его, когда сможет.)
//
// ИДЕЯ ЯЩИКА НА ПАЛЬЦАХ. Раз надёжно мы умеем писать только в
// СВОЮ базу — давайте писать событие тоже в свою базу, в
// отдельную таблицу, В ТОЙ ЖЕ ТРАНЗАКЦИИ. Тогда «заказ создан» и
// «событие про заказ записано» — одно неделимое действие. А
// отправкой из таблицы в брокер займётся отдельный работник.
//
// Аналогия: лоток «на отправку» на столе. Вы кладёте в него
// письмо тем же движением, что и подшиваете документ в папку.
// Курьер приходит потом и забирает всё, что в лотке. Если курьер
// заболел — письма не потерялись, они лежат в лотке.

// Таблица в ВАШЕЙ базе, рядом с бизнес-таблицами:
//
//   CREATE TABLE outbox (
//     id          uuid PRIMARY KEY,
//     topic       text        NOT NULL,
//     payload     jsonb       NOT NULL,
//     created_at  timestamptz NOT NULL DEFAULT now(),
//     sent_at     timestamptz            -- NULL, пока не отправлено
//   );

async function createOrderOutbox(userId: string, items: CartItem[]) {
  const tx = await db.begin();
  try {
    const order = await tx.insertOrder(userId, items);

    // ТА ЖЕ транзакция. Либо будет и заказ, и запись о событии,
    // либо не будет ни того, ни другого. Щель закрыта.
    await tx.query(
      'INSERT INTO outbox (id, topic, payload) VALUES ($1, $2, $3)',
      [randomUUID(), 'order.created', JSON.stringify({ orderId: order.id })],
    );

    await tx.commit();
    return order;
  } catch (error) {
    await tx.rollback();
    throw error;
  }
}

// Отдельный работник — «релей» — забирает и отправляет:

async function outboxRelay() {
  const rows = await db.query(
    'SELECT * FROM outbox WHERE sent_at IS NULL ORDER BY created_at LIMIT 100',
  );

  for (const row of rows) {
    await broker.publish(row.topic, row.payload);
    await db.query('UPDATE outbox SET sent_at = now() WHERE id = $1', [row.id]);
    // Если процесс упадёт МЕЖДУ этими двумя строками, событие
    // уйдёт второй раз. Это нормально и ожидаемо: гарантия здесь
    // «не менее одного раза». Значит, ПОЛУЧАТЕЛЬ обязан уметь
    // переживать повтор — тот же ключ идемпотентности, что и в
    // предыдущем разделе.
  }
}

