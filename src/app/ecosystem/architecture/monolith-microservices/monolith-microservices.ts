// Нужно узнать цену товара со скидкой. В монолите это выглядит так:

import { getPrice } from '../services/pricing';

const price = getPrice(productId, user.discountTier);

// Что тут произошло:
//   - вызов занял микросекунды (это доли миллисекунды);
//   - он не мог «не дойти»;
//   - он не мог ответить дважды;
//   - если внутри случилась ошибка, вы получили обычное
//     исключение с понятным стеком вызовов;
//   - вам не нужны ни таймауты, ни повторы, ни отдельный клиент.
//
// Запомните этот кусочек. Ниже, в разделе про цену сетевого
// вызова, мы посмотрим, во что превращаются эти две строки, когда
// pricing переезжает в отдельный сервис.

// ───────────────────────────────────────────────────────────────
// ПОДАРОК 2. ТРАНЗАКЦИЯ: ЛИБО ВСЁ, ЛИБО НИЧЕГО
// ───────────────────────────────────────────────────────────────

// Оформление заказа. Нужно сделать три вещи, и они должны
// произойти вместе:
//   1) создать заказ;
//   2) списать товар с остатка;
//   3) записать строки заказа.
//
// Если списали остаток, а заказ не создали — товар пропал у всех
// и ни у кого не появился. Если создали заказ, но не списали
// остаток — продадим последний экземпляр дважды.
//
// В одной базе это решается одной командой.

async function createOrder(userId: string, items: CartItem[]) {
  // BEGIN — «начинаю неделимое действие».
  const tx = await db.begin();
  try {
    // 1. Сам заказ.
    const order = await tx.query(
      'INSERT INTO orders (user_id, status) VALUES ($1, $2) RETURNING id',
      [userId, 'new'],
    );

    for (const item of items) {
      // 2. Списываем остаток. Условие "quantity >= $2" защищает
      //    от ухода остатка в минус: если товара не хватает,
      //    строк изменится ноль.
      const updated = await tx.query(
        'UPDATE stock_items SET quantity = quantity - $2 ' +
          'WHERE product_id = $1 AND quantity >= $2',
        [item.productId, item.qty],
      );

      if (updated.rowCount === 0) {
        // Товара не хватило — валим всё целиком.
        throw new Error('OUT_OF_STOCK');
      }

      // 3. Строка заказа.
      await tx.query(
        'INSERT INTO order_items (order_id, product_id, qty) VALUES ($1, $2, $3)',
        [order.id, item.productId, item.qty],
      );
    }

    // COMMIT — «всё, применяй разом».
    await tx.commit();
    return order;
  } catch (error) {
    // ROLLBACK — «отменяй всё, что я тут наделал».
    // База сама вернёт остатки и удалит недоделанный заказ.
    await tx.rollback();
    throw error;
  }
}

