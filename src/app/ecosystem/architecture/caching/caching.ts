const NOT_FOUND = '__none__';   // особая метка. Обычные данные
                                // такой строкой быть не могут
const TTL_FOUND = 300;          // 5 минут для найденного
const TTL_MISSING = 30;         // 30 секунд для ненайденного

async function getProduct(id) {
  const key = 'product:v1:' + id;

  const cached = await safeGet(key);
  if (cached === NOT_FOUND) {
    // Попадание! Мы уже знаем, что такого товара нет.
    // В базу НЕ идём.
    metrics.increment('cache.hit', { kind: 'negative' });
    return null;
  }
  if (cached !== null) {
    metrics.increment('cache.hit', { kind: 'positive' });
    return JSON.parse(cached);
  }

  metrics.increment('cache.miss');
  const product = await db.products.findById(id);

  if (product) {
    await safeSet(key, JSON.stringify(product), ttlWithJitter(TTL_FOUND));
  } else {
    // Вот оно. Запоминаем сам факт отсутствия.
    await safeSet(key, NOT_FOUND, ttlWithJitter(TTL_MISSING));
  }

  return product;
}

