const TTL_SECONDS = 300;   // 5 минут. Осознанное решение, не случайность

async function getProduct(id) {
  const key = 'product:v1:' + id;
  //           ^^^^^^^ ^^      ^^
  //           |       |       └─ что именно: конкретный товар
  //           |       └───────── версия формата записи (см. ниже)
  //           └───────────────── к чему относится

  // ── ШАГ 1. Спрашиваем кэш. И НИКОГДА не падаем из-за него ──
  let cached = null;
  try {
    cached = await redis.get(key);
  } catch (err) {
    // Кэш недоступен — это не повод отказать человеку.
    // Пишем в лог (чтобы дежурный увидел) и идём дальше.
    logger.warn('cache read failed', { key, err: err.message });
    metrics.increment('cache.error', { op: 'get' });
  }

  // ── ШАГ 2. Проверяем ЯВНО на null, а не «на правдивость» ──
  if (cached !== null && cached !== undefined) {
    metrics.increment('cache.hit', { entity: 'product' });
    try {
      return JSON.parse(cached);
    } catch {
      // В кэше лежит испорченная строка (например, кто-то положил
      // туда данные старого формата). Это не повод падать:
      // считаем это промахом и идём в базу.
      metrics.increment('cache.corrupt');
    }
  }

  metrics.increment('cache.miss', { entity: 'product' });

  // ── ШАГ 3. Считаем по-настоящему ──
  // Здесь ошибка НЕ подавляется: если базы нет, ответа нет,
  // и человек должен об этом узнать честно.
  const product = await db.products.findById(id);

  // ── ШАГ 4. Кладём в кэш ТОЛЬКО то, в чём уверены ──
  if (product) {
    try {
      await redis.set(
        key,
        JSON.stringify(product),
        'EX',              // EX = срок жизни в секундах
        TTL_SECONDS
      );
    } catch (err) {
      // Не смогли положить — ну и ладно. Ответ у нас уже есть.
      logger.warn('cache write failed', { key, err: err.message });
      metrics.increment('cache.error', { op: 'set' });
    }
  }
  // Случай, когда товара нет, разобран отдельно —
  // см. кэширование отрицательных ответов ниже.

  // ── ШАГ 5. Возвращаем ──
  return product;
}

