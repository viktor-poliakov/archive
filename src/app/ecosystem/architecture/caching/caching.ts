// ═══════════════════════════════════════════════════════════════
// ГЛАВНЫЙ ПРИЁМ ВСЕЙ СТРАНИЦЫ: «ПРОВЕРИЛ — ПОСЧИТАЛ — ПОЛОЖИЛ»
