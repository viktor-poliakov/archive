const metrics = require('./metrics');

async function getWithMetrics(key, ttl, compute, entity) {
  const started = Date.now();

  let cached = null;
  try {
    cached = await redis.get(key);
  } catch (err) {
    // Отдельный счётчик ошибок кэша. Он важнее доли попаданий:
    // если кэш недоступен, доля попаданий тоже упадёт, и без
    // этого счётчика вы будете искать причину не там.
    metrics.increment('cache.error', { op: 'get', entity });
  }

  if (cached !== null) {
    metrics.increment('cache.hit', { entity });
    metrics.timing('cache.hit.duration', Date.now() - started, { entity });
    return JSON.parse(cached);
  }

  metrics.increment('cache.miss', { entity });
  const value = await compute();
  // Сколько стоит промах — это и есть цена вашего кэша.
  // Если промах стоит 3 мс, кэш вам, возможно, не нужен вообще.
  metrics.timing('cache.miss.duration', Date.now() - started, { entity });

  try {
    await redis.set(key, JSON.stringify(value), 'EX', ttl);
  } catch (err) {
    metrics.increment('cache.error', { op: 'set', entity });
  }
  return value;
}

