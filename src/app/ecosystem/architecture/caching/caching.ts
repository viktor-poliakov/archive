// ═══ КАК НАДО: СЧИТАЕТ ТОЛЬКО ОДИН, ОСТАЛЬНЫЕ ЖДУТ ═══
//
// Приём называется single-flight («один полёт») или просто
// «блокировка на пересчёт». Идея на человеческом языке:
//
//   кто первый добежал — тот и считает,
//   остальные подождут у двери и получат готовое.

async function getWithLock(key, ttlSeconds, compute) {
  // ── 1. Обычная попытка взять из кэша ──
  const cached = await safeGet(key);
  if (cached !== null) return JSON.parse(cached);

  // ── 2. Промах. Пробуем ЗАХВАТИТЬ ПРАВО на пересчёт ──
  // SET ... NX EX 10 означает: «поставь ключ, ТОЛЬКО ЕСЛИ его нет,
  // и пусть он сам исчезнет через 10 секунд».
  // NX (not exists) делает операцию атомарной: даже если сто
  // процессов выполнят её одновременно, успех будет ровно у одного.
  const lockKey = key + ':lock';
  const token = crypto.randomUUID();   // наша личная подпись на замке
  const gotLock = await redis.set(lockKey, token, 'NX', 'EX', 10);

  if (gotLock) {
    // ── 3a. МЫ — тот самый один. Считаем по-настоящему ──
    try {
      const value = await compute();
      await redis.set(key, JSON.stringify(value), 'EX', ttlSeconds);
      return value;
    } finally {
      // Снимаем замок, но ТОЛЬКО ЕСЛИ он всё ещё наш.
      // Если мы считали дольше 10 секунд, замок мог истечь
      // и достаться другому — чужой замок трогать нельзя.
      await releaseLockIfMine(lockKey, token);
    }
  }

  // ── 3b. Замок занят. Ждём того, кто считает ──
  for (let attempt = 0; attempt < 50; attempt++) {
    await sleep(100);                       // 50 попыток по 100 мс = 5 с
    const value = await safeGet(key);
    if (value !== null) return JSON.parse(value);   // дождались!
  }

  // ── 4. Не дождались. Тот, кто считал, видимо, умер ──
  // Считаем сами. Да, это дублирование работы. Но лучше
  // сделать лишнюю работу, чем отдать человеку ошибку.
  return await compute();
}

// Снятие замка обязано быть атомарным: «проверь подпись и удали».
// Двумя отдельными командами это делать нельзя — между ними
// замок может истечь и достаться другому процессу.
const RELEASE_SCRIPT = [
  'if redis.call("get", KEYS[1]) == ARGV[1] then',
  '  return redis.call("del", KEYS[1])',
  'else',
  '  return 0',
  'end'
].join('\\n');

function releaseLockIfMine(lockKey, token) {
  return redis.eval(RELEASE_SCRIPT, 1, lockKey, token);
}

