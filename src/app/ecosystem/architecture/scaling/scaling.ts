function planPools({ dbMaxConnections, reservedForAdmins, maxCopies }) {
  // Оставляем запас: миграции, административные подключения,
  // резервное копирование, ваш psql в момент аварии.
  const availableForApp = dbMaxConnections - reservedForAdmins;

  // Делим доступное на максимальное число копий — округляя ВНИЗ.
  const perCopy = Math.floor(availableForApp / maxCopies);

  return {
    availableForApp,
    perCopy,
    // Если perCopy получился 0 или 1 — это сигнал, что напрямую
    // ходить в базу столькими копиями уже нельзя. Нужен пулер.
    needsExternalPooler: perCopy < 3,
  };
}

console.log(planPools({ dbMaxConnections: 100, reservedForAdmins: 20, maxCopies: 100 }));
// { availableForApp: 80, perCopy: 0, needsExternalPooler: true }
//
// Читается это так: сто копий физически не могут держать
// собственные пулы к базе со стандартным max_connections.
// Не «неудобно», а не могут.


// ═══ КАК НАДО: ВНЕШНИЙ ПУЛЕР ═══
//
// Пулер (connection pooler) — отдельная программа, которая стоит
// МЕЖДУ приложением и базой. Приложения подключаются к пулеру
// (их могут быть тысячи), а пулер держит к базе небольшое число
// настоящих соединений и переиспользует их между всеми.
//
// Аналогия: гардероб в театре. Зрителей восемьсот, а окошек в гардеробе
// четыре. Никто не пытается выдать каждому зрителю персональное окошко —
// очередь движется быстро именно потому, что окошек мало и они заняты делом.
//
//   приложение ×100 (по 20 соединений) → пулер → база (20 соединений)
//
// ⚠ Важно: ВСТРОЕННОГО пулера в PostgreSQL нет. Актуальная версия — 18
// (18.6 от 13 августа 2026), PostgreSQL 19 сейчас в статусе Beta 3.
// Утверждения блогов о «встроенном пулинге в PG 18» документацией
// не подтверждаются.
//
// Что реально применяют:
//   • PgBouncer — самый распространённый. Версия 1.21.0 добавила
//     поддержку именованных подготовленных запросов; актуальная 1.25.2
//     (май 2026), в ней исправлена уязвимость CVE-2026-6667
//     (команда KILL_CLIENT выполнялась без проверки прав).
//     В свежих версиях подготовленные запросы включены по умолчанию,
//     max_prepared_statements = 200.
//   • pgcat — альтернатива на Rust, активно развивается.
//   • Supavisor — от Supabase, на Elixir, мультитенантный.
//   • Управляемые варианты: у Cloud SQL есть Managed Connection Pooling
//     в статусе GA; в Azure Database for PostgreSQL Flexible Server
//     PgBouncer встроен.

// Конфигурация PgBouncer, разобранная по строчкам:
//
//   [databases]
//   shop = host=10.0.2.5 port=5432 dbname=shop
//
//   [pgbouncer]
//   pool_mode = transaction
//   max_client_conn = 2000      ← сколько клиентов пустим К СЕБЕ
//   default_pool_size = 20      ← сколько соединений держим К БАЗЕ
//
// pool_mode — самая важная строка, разберём режимы:
//
//   session     — соединение с базой закреплено за клиентом до конца
//                 его сессии. Экономии почти нет.
//   transaction — соединение выдаётся на время ТРАНЗАКЦИИ и сразу
