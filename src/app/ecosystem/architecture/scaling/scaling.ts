// Идея: одновременно обрабатываем не больше N запросов. Остальные ждут,
// но ждут ОГРАНИЧЕННОЙ длины очередь — и ждут ограниченное время.
// Это и есть «сорок мест в кафе».

class AdmissionControl {
  constructor({ maxConcurrent, maxQueued, maxWaitMs }) {
    this.maxConcurrent = maxConcurrent;   // сколько работаем одновременно
    this.maxQueued = maxQueued;           // сколько готовы держать в ожидании
    this.maxWaitMs = maxWaitMs;           // сколько максимум ждём в очереди
    this.running = 0;
    this.queue = [];
  }

  async run(task) {
    if (this.running >= this.maxConcurrent) {
      // ЗДЕСЬ ГЛАВНОЕ РЕШЕНИЕ: очередь переполнена — отказываем СРАЗУ.
      // Быстрый отказ намного лучше медленного: клиент узнаёт правду
      // за миллисекунды и не держит соединение.
      if (this.queue.length >= this.maxQueued) {
        const err = new Error('overloaded');
        err.status = 503;
        throw err;
      }
      await this.waitForSlot();
    }

    this.running++;
    try {
      return await task();
    } finally {
      this.running--;
      const next = this.queue.shift();
      if (next) next.resolve();
    }
  }

  waitForSlot() {
    return new Promise((resolve, reject) => {
      const entry = { resolve, reject };
      this.queue.push(entry);
      // Ограничение времени ожидания: если места не нашлось за maxWaitMs,
      // отказываем. Ждать дольше бессмысленно — клиент уже отвалился.
      setTimeout(() => {
        const i = this.queue.indexOf(entry);
        if (i !== -1) {
          this.queue.splice(i, 1);
          const err = new Error('queue_timeout');
          err.status = 503;
          reject(err);
        }
      }, this.maxWaitMs);
    });
  }
}

