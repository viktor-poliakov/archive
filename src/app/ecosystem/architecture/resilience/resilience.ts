// ЧТО СЛУЧИТСЯ.
// Рекомендации задумались на 30 секунд. Запросы к ним копятся.
// Они занимают память, соединения, места в пуле, время планировщика.
// Через несколько секунд оформление заказа — операция, которая к рекомендациям
// вообще не имеет отношения, — начинает отваливаться, потому что свободных мест
// в общем пуле не осталось.
// Итог: необязательная функция уронила обязательную. Это чистая потеря денег.

// ═══ КАК НАДО: ОТДЕЛЬНЫЙ ЛИМИТ НА КАЖДУЮ ЗАВИСИМОСТЬ ═══

// Семафор — счётчик разрешений. Проще некуда: есть N пропусков, взял — работай,
// закончил — верни. Нет свободных пропусков — либо жди в очереди, либо уходи.
class Bulkhead {
  constructor(name, { limit, queueLimit = 0, queueTimeoutMs = 200 }) {
    this.name = name;
    this.limit = limit;                   // сколько вызовов идёт одновременно
    this.queueLimit = queueLimit;         // сколько ждут своей очереди
    this.queueTimeoutMs = queueTimeoutMs; // сколько максимум ждут в очереди
    this.active = 0;
    this.queue = [];
  }

  async run(action) {
    await this.acquire();
    try {
      return await action();
    } finally {
      this.release();
    }
  }

  acquire() {
    if (this.active < this.limit) {
      this.active++;
      return Promise.resolve();
    }

    // Мест нет. Если очередь запрещена или переполнена — отказываем СРАЗУ.
    // Быстрый отказ лучше бесконечной очереди: очередь — это та же вода в трюме.
    if (this.queue.length >= this.queueLimit) {
      const e = new Error('Переборка ' + this.name + ': нет свободных мест');
      e.code = 'EBULKHEAD_FULL';
      return Promise.reject(e);
    }

    return new Promise((resolve, reject) => {
      const entry = { resolve, reject, timer: null };

      // Ждать в очереди тоже нельзя вечно — иначе очередь станет новым узким местом.
      entry.timer = setTimeout(() => {
        const i = this.queue.indexOf(entry);
        if (i !== -1) this.queue.splice(i, 1);
        const e = new Error('Переборка ' + this.name + ': не дождались очереди');
        e.code = 'EBULKHEAD_TIMEOUT';
        reject(e);
      }, this.queueTimeoutMs);

      this.queue.push(entry);
    });
  }

  release() {
    const next = this.queue.shift();
    if (next) {
      clearTimeout(next.timer);
      next.resolve(); // место передаём следующему, счётчик active не меняем
    } else {
      this.active--;
    }
  }

  // Для метрик: занятость переборки — отличный ранний сигнал беды.
  stats() {
    return { name: this.name, active: this.active, queued: this.queue.length, limit: this.limit };
  }
}

