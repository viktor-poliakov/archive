// --- Сторона сервера ---
//
// Таблица, в которой живут ключи. Первичный ключ по key — это и есть замок:
// вторая вставка того же значения физически невозможна, за этим следит база.
//
//   CREATE TABLE idempotency_keys (
//     key           text PRIMARY KEY,
//     user_id       bigint NOT NULL,
//     status        text NOT NULL,          -- in_progress | done
//     response_body jsonb,
//     created_at    timestamptz NOT NULL DEFAULT now()
//   );

app.post('/orders', async (req, res) => {
  const key = req.get('idempotency-key');
  if (!key) return res.status(400).json({ error: 'нужен заголовок idempotency-key' });

  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    // Пытаемся застолбить ключ. Если он уже занят — ничего не вставится.
    const claimed = await client.query(
      'INSERT INTO idempotency_keys (key, user_id, status) VALUES ($1, $2, $3) ' +
        'ON CONFLICT (key) DO NOTHING RETURNING key',
      [key, req.user.id, 'in_progress'],
    );

    if (claimed.rowCount === 0) {
      // Ключ занят: это повтор. Смотрим, чем закончилась первая попытка.
      await client.query('ROLLBACK');
      const prev = await pool.query(
        'SELECT status, response_body FROM idempotency_keys WHERE key = $1 AND user_id = $2',
        [key, req.user.id],
      );
      const row = prev.rows[0];

      if (row && row.status === 'done') {
        // Первая попытка успела — отдаём ТОТ ЖЕ ответ. Второго заказа не создаём.
        return res.json(row.response_body);
      }
      // Первая попытка ещё выполняется (случай C выше). Честно просим подождать:
      // 409 — «конфликт», клиент повторит позже и не создаст дубликат.
      return res.status(409).json({ error: 'запрос уже выполняется, повторите позже' });
    }

    // Ключ наш — выполняем работу в той же транзакции.
    const order = await client.query(
      'INSERT INTO orders (user_id, total, status) VALUES ($1, $2, $3) RETURNING id',
      [req.user.id, req.body.total, 'new'],
    );
    const body = { orderId: order.rows[0].id };

    await client.query(
      'UPDATE idempotency_keys SET status = $1, response_body = $2 WHERE key = $3',
      ['done', body, key],
    );
    await client.query('COMMIT');

    res.json(body);
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
});

