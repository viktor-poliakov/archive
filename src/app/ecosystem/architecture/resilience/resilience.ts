// ═══ КАК НАДО: ПОЛНАЯ РЕАЛИЗАЦИЯ ═══

class CircuitBreaker {
  constructor(name, options = {}) {
    this.name = name;

    // Настройки. Числа ниже — разумная отправная точка, а не истина.
    this.failureThreshold = options.failureThreshold ?? 0.5; // доля неудач для размыкания
    this.minimumRequests = options.minimumRequests ?? 20;    // меньше — статистике не верим
    this.windowMs = options.windowMs ?? 10000;               // окно наблюдения
    this.openMs = options.openMs ?? 30000;                   // сколько держим паузу

    this.state = 'closed';   // closed | open | half_open
    this.events = [];        // [{ at, ok }] — последние исходы
    this.openedAt = 0;       // когда разомкнули
    this.probeInFlight = false; // идёт ли сейчас пробный запрос
  }

  prune(now) {
    const from = now - this.windowMs;
    while (this.events.length && this.events[0].at < from) this.events.shift();
  }

  // Считаем долю неудач в окне.
  failureRatio(now) {
    this.prune(now);
    if (this.events.length < this.minimumRequests) return 0; // мало данных — не паникуем
    const failed = this.events.filter((e) => !e.ok).length;
    return failed / this.events.length;
  }

  record(ok) {
    this.events.push({ at: Date.now(), ok });
  }

  open() {
    this.state = 'open';
    this.openedAt = Date.now();
    this.events = []; // статистика прошлого режима больше не нужна
    log.warn('Предохранитель ' + this.name + ' РАЗОМКНУТ: перестаём звонить зависимости');
  }

  close() {
    this.state = 'closed';
    this.events = [];
    this.probeInFlight = false;
    log.info('Предохранитель ' + this.name + ' замкнут: зависимость снова жива');
  }

  // Главный метод. action — функция, которая делает сам вызов.
  async run(action) {
    const now = Date.now();

    if (this.state === 'open') {
      if (now - this.openedAt >= this.openMs) {
        // Пауза выдержана — переходим к пробе.
        this.state = 'half_open';
        this.probeInFlight = false;
      } else {
        // Пауза ещё идёт: отказываем МГНОВЕННО, ни к кому не ходим.
        throw new CircuitOpenError(this.name);
      }
    }

    if (this.state === 'half_open') {
      // Пропускаем ровно ОДИН пробный вызов. Остальные отвергаем:
      // если зависимость ещё не встала, толпа проб уронит её повторно.
      if (this.probeInFlight) throw new CircuitOpenError(this.name);
      this.probeInFlight = true;

      try {
        const result = await action();
        this.close();
        return result;
      } catch (err) {
        this.open();       // проба неудачна — снова пауза, отсчёт с нуля
        throw err;
      }
    }

    // Обычный режим: пропускаем и считаем исходы.
    try {
      const result = await action();
      this.record(true);
      return result;
    } catch (err) {
      // ВАЖНО: считаем неудачей только «инфраструктурные» ошибки.
      // Ответ 404 или 400 — это нормальная работа зависимости, а не её болезнь.
      if (isDependencyFailure(err)) {
        this.record(false);
        if (this.failureRatio(Date.now()) >= this.failureThreshold) this.open();
      }
      throw err;
    }
  }
}

class CircuitOpenError extends Error {
  constructor(name) {
    super('Предохранитель ' + name + ' разомкнут — зависимость временно недоступна');
    this.code = 'ECIRCUIT_OPEN';
  }
}

function isDependencyFailure(err) {
  if (err.code === 'ETIMEDOUT' || err.code === 'ECONNRESET' || err.code === 'ECONNREFUSED') return true;
  return err.status >= 500;
}

