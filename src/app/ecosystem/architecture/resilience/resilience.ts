// ПРАВИЛО 1. Повторяем только то, что имеет смысл повторять.
function isRetriable(err, response) {
  // Не смогли соединиться / оборвалось / не дождались — похоже на сеть, стоит повторить.
  if (err) {
    return err.code === 'ETIMEDOUT' || err.code === 'ECONNRESET' || err.code === 'ECONNREFUSED';
  }
  // 429 — «слишком часто», сосед сам просит подождать.
  // 502/503/504 — сосед временно не в форме.
  if (response.status === 429) return true;
  if (response.status >= 500 && response.status !== 501) return true;
  // Всё остальное (400, 401, 403, 404, 422) — ошибка в самом запросе,
  // повтор ничего не изменит.
  return false;
}

// ПРАВИЛО 2. Пауза растёт, и в неё добавлен случайный разброс.
//
// Растущая пауза (exponential backoff): 200 мс, 400, 800, 1600 — даём соседу
// всё больше времени прийти в себя.
// Случайный разброс (jitter): размазываем повторы во времени, чтобы клиенты
// не ударили в одну секунду. Берём случайное число ОТ НУЛЯ до вычисленной паузы —
// простой и хорошо работающий вариант.
function backoffDelay(attempt, baseMs = 200, capMs = 5000) {
  const exponential = Math.min(capMs, baseMs * Math.pow(2, attempt));
  return Math.random() * exponential; // разброс: от 0 до вычисленной паузы
}

// ПРАВИЛО 3. Если сосед прислал заголовок Retry-After — слушаемся его,
// а не своей формулы. Он лучше знает, когда ему станет легче.
function retryAfterMs(response) {
  const header = response.headers.get('retry-after');
  if (!header) return null;
  const seconds = Number(header);
  return Number.isFinite(seconds) ? seconds * 1000 : null;
}

// ПРАВИЛО 4 — САМОЕ ВАЖНОЕ. ОБЩИЙ БЮДЖЕТ ПОВТОРОВ.
//
// Идея: во всём процессе доля повторов не может превышать, скажем, 10 % от числа
// обычных запросов. Пока всё хорошо, 10 % — огромный запас, повторы работают
// как обычно и никто ничего не замечает. Когда сосед лёг и «повторить» хочется
// всем сразу — бюджет мгновенно исчерпывается, и повторы просто выключаются.
// Сосед получает ровно ту нагрузку, что и в норме, и у него появляется шанс встать.
class RetryBudget {
  constructor(ratio = 0.1, windowMs = 10000) {
    this.ratio = ratio;         // сколько повторов разрешено на один обычный запрос
    this.windowMs = windowMs;   // окно наблюдения — последние 10 секунд
    this.requests = [];         // отметки времени обычных запросов
    this.retries = [];          // отметки времени повторов
  }

  prune(now) {
    const from = now - this.windowMs;
    while (this.requests.length && this.requests[0] < from) this.requests.shift();
    while (this.retries.length && this.retries[0] < from) this.retries.shift();
  }

  recordRequest() {
    const now = Date.now();
    this.prune(now);
    this.requests.push(now);
  }

  // true — повтор разрешён и записан; false — бюджет исчерпан, повторять нельзя.
  tryTakeRetry() {
    const now = Date.now();
    this.prune(now);
    const allowed = this.requests.length * this.ratio;
    if (this.retries.length >= allowed) return false;
    this.retries.push(now);
    return true;
  }
}

const recsBudget = new RetryBudget(0.1, 10000);

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// Собираем всё вместе.
async function callWithRetrySafe(url, { attempts = 3, deadline } = {}) {
  recsBudget.recordRequest();
  let lastError = null;

  for (let attempt = 0; attempt < attempts; attempt++) {
    // На повторных попытках сначала спрашиваем разрешение у бюджета.
    if (attempt > 0 && !recsBudget.tryTakeRetry()) {
      const e = new Error('Бюджет повторов исчерпан — соседу плохо, не добиваем');
      e.code = 'ERETRY_BUDGET';
      throw e;
    }

    try {
      const timeoutMs = deadline ? deadline.forStep(1000) : 1000;
      const response = await fetchWithTimeout(url, {}, timeoutMs);
      if (response.ok) return response;
      if (!isRetriable(null, response)) return response; // 404 повторять незачем

      const wait = retryAfterMs(response) ?? backoffDelay(attempt);
      await sleep(wait);
      lastError = new Error('Ответ ' + response.status);
    } catch (err) {
      if (!isRetriable(err)) throw err;
      lastError = err;
      await sleep(backoffDelay(attempt));
    }
  }

  throw lastError;
}

