async function optional(name, action, fallbackValue) {
  try {
    return await action();
  } catch (err) {
    // Логируем обязательно: деградация должна быть видимой, а не тихой.
    // Иначе половина сайта тихо перестанет работать, и никто не заметит.
    log.warn('Необязательная зависимость ' + name + ' недоступна', {
      code: err.code,
      message: err.message,
    });
    metrics.increment('degraded_dependency', { dependency: name });
    return fallbackValue;
  }
}

