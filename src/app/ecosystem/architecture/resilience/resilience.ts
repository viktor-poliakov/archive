// В браузере и в Node.js ограничение по времени делается через AbortController —
// это «рубильник», которым можно принудительно оборвать запрос.

const DEFAULT_TIMEOUT_MS = 2000;

async function fetchWithTimeout(url, options = {}, timeoutMs = DEFAULT_TIMEOUT_MS) {
  const controller = new AbortController();

  // Через timeoutMs миллисекунд дёргаем рубильник: fetch завершится ошибкой.
  const timer = setTimeout(() => controller.abort(), timeoutMs);

  try {
    return await fetch(url, { ...options, signal: controller.signal });
  } catch (err) {
    // Отличаем «не дождались» от прочих ошибок: это разные метрики и разные
    // решения. Таймаут говорит о перегрузке, а не о неправильном запросе.
    if (err.name === 'AbortError') {
      const e = new Error('Таймаут ' + timeoutMs + ' мс при запросе ' + url);
      e.code = 'ETIMEDOUT';
      throw e;
    }
    throw err;
  } finally {
    // Обязательно снимаем таймер, иначе процесс будет держать его до срабатывания.
    clearTimeout(timer);
  }
}

