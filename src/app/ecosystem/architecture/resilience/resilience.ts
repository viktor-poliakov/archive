// ═══ БЮДЖЕТ ВРЕМЕНИ НА ВЕСЬ ЗАПРОС ═══
//
// Таймаут на один вызов — половина дела. Вызовы складываются в цепочку,
// и сумма таймаутов легко перерастает терпение пользователя.
//
// Плохо: клиент ждёт 3 с, а внутри — авторизация 2 с + профиль 2 с + корзина 2 с,
//        то есть до 6 с. Клиент уйдёт, а вы будете старательно доделывать работу.
//
// Правило: у ЗАПРОСА есть общий срок (дедлайн), и каждый следующий вызов
// получает не свой личный таймаут, а остаток общего.

function createDeadline(totalMs) {
  const endsAt = Date.now() + totalMs;
  return {
    // Сколько времени осталось на всё оставшееся.
    left() {
      return Math.max(0, endsAt - Date.now());
    },
    // Таймаут для очередного шага: не больше желаемого и не больше остатка.
    forStep(desiredMs) {
      const remaining = this.left();
      if (remaining <= 0) {
        const e = new Error('Бюджет времени на запрос исчерпан');
        e.code = 'EDEADLINE';
        throw e;
      }
      return Math.min(desiredMs, remaining);
    },
  };
}

