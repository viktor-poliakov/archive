// их длина равна единице. Тогда знаменатель формулы выше равен единице,
// и косинус сводится к скалярному произведению - вдвое меньше арифметики.
// Проверяется одной строкой: посчитайте длину, должно выйти примерно 1.000.
function dotProduct(a, b) {
  let sum = 0;
  for (let i = 0; i < a.length; i++) {
    sum += a[i] * b[i];
  }
  return sum;
}

function vectorLength(v) {
  return Math.sqrt(dotProduct(v, v));
}


