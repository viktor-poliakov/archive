// Ни один из двух кусков не отвечает на вопрос про срок возврата.       // [!error]


// ═══ ХОРОШО: СНАЧАЛА ПО ЗАГОЛОВКАМ, ПОТОМ ПО АБЗАЦАМ ═══

// Документ уже размечен автором: заголовки, абзацы, списки.
// Эта разметка — бесплатная подсказка о том, где кончается одна мысль.

function splitByHeadings(markdown) {
  const blocks = [];
  let current = { heading: '', lines: [] };

  for (const line of markdown.split('\\n')) {
    if (line.startsWith('#')) {
      if (current.lines.length) blocks.push(current);
      current = { heading: line.replace(/^[# ]+/, ''), lines: [] };
    } else {
      current.lines.push(line);
    }
  }
  if (current.lines.length) blocks.push(current);
  return blocks;
}

// Внутри блока набираем абзацы в кусок, пока он не дорос до целевого размера.
function packParagraphs(block, target, maxSize) {
  const chunks = [];
  let buffer = [];
  let size = 0;

  for (const paragraph of block.lines.join('\\n').split('\\n\\n')) {
    const text = paragraph.trim();
    if (text === '') continue;

    // Редкий случай: один абзац больше потолка — режем его по предложениям.
    if (text.length > maxSize) {
      for (const piece of packSentences(text, target)) chunks.push(piece);
      continue;
    }
    if (size + text.length > target && buffer.length) {
      chunks.push(buffer.join('\\n\\n'));
      buffer = [];
      size = 0;
    }
    buffer.push(text);
    size += text.length;
  }
  if (buffer.length) chunks.push(buffer.join('\\n\\n'));
  return chunks.map((text) => ({ heading: block.heading, text }));
}

function packSentences(text, target) {
  const out = [];
  let buffer = '';
  for (const sentence of text.split('. ')) {
    if (buffer.length + sentence.length > target && buffer !== '') {
      out.push(buffer.trim());
      buffer = '';
    }
    buffer += sentence + '. ';
  }
  if (buffer.trim() !== '') out.push(buffer.trim());
  return out;
}


