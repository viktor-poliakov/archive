// Косинусная близость: смотрят ли два вектора в одну сторону.
//   1.0 - одно направление, тексты про одно и то же
//   0.0 - никакой связи
//   ниже нуля - разнонаправленность
// Длина текста на результат почти не влияет: деление на длины её снимает.
function cosineSimilarity(a, b) {
  let dot = 0;
  let lengthA = 0;
  let lengthB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    lengthA += a[i] * a[i];
    lengthB += b[i] * b[i];
  }
  return dot / (Math.sqrt(lengthA) * Math.sqrt(lengthB));
}

