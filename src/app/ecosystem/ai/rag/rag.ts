// На входе — массив страниц, каждая страница это массив строк.
function cleanPdfPages(pages) {
  const repeated = findRepeatedLines(pages);   // колонтитулы: одно и то же везде
  const kept = [];

  for (const lines of pages) {
    for (const line of lines) {
      const trimmed = line.trim();
      if (trimmed === '') continue;
      if (isPageNumber(trimmed)) continue;     // '7', '— 7 —' — это не содержание
      if (repeated.has(trimmed)) continue;     // 'ООО Ромашка. Договор оферты'
      kept.push(trimmed);
    }
  }
  return joinHyphenBreaks(kept).join(' ');
}

function isPageNumber(line) {
  const digits = line.replace(/[^0-9]/g, '');
  return digits !== '' && digits.length <= 4 && line.length <= 9;
}

function findRepeatedLines(pages) {
  const counter = new Map();
  // Колонтитулы живут по краям: смотрим две первые и две последние строки.
  for (const lines of pages) {
    const edges = [...lines.slice(0, 2), ...lines.slice(-2)];
    for (const line of new Set(edges.map((s) => s.trim()))) {
      counter.set(line, (counter.get(line) || 0) + 1);
    }
  }
  const half = Math.max(2, Math.ceil(pages.length / 2));
  return new Set([...counter].filter((pair) => pair[1] >= half).map((pair) => pair[0]));
}

function joinHyphenBreaks(lines) {
  const out = [];
  for (const line of lines) {
    const prev = out[out.length - 1];
    // 'дого-' + 'вор' -> 'договор': это перенос строки, а не настоящий дефис.
    if (prev && prev.endsWith('-') && startsWithLowerCase(line)) {
      out[out.length - 1] = prev.slice(0, -1) + line;
    } else {
      out.push(line);
    }
  }
  return out;
}

function startsWithLowerCase(line) {
  const first = line.charAt(0);
  return first !== '' && first === first.toLowerCase() && first !== first.toUpperCase();
}


