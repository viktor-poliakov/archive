// ─────────────────────────────────────────────────────────────────
// Чтобы понять, насколько два текста похожи, сравнивают не сами
// числа, а НАПРАВЛЕНИЕ их векторов: насколько они «смотрят в одну
// сторону». Результат — одно число примерно от 0 до 1.
// Ближе к 1 — похоже. Ближе к 0 — не похоже.
// ─────────────────────────────────────────────────────────────────

function cosineSimilarity(a, b) {
  // Шаг 0. Разная длина — это не «чуть-чуть другое», это разные
  // модели. Сравнивать нечего, лучше упасть сразу.
  if (a.length !== b.length) {
    throw new Error('Векторы разной длины: они от разных моделей'); // [!error]
  }

  let dot = 0; // насколько согласованно ведут себя координаты
  let lengthA = 0; // «длина» первого вектора
  let lengthB = 0; // «длина» второго

  for (let i = 0; i < a.length; i++) {
    // Координаты совпадают по знаку — вклад плюсовой,
    // расходятся — минусовой. Так набирается «согласие».
    dot += a[i] * b[i];

    // Попутно копим длины обоих векторов.
    lengthA += a[i] * a[i];
    lengthB += b[i] * b[i];
  }

  // Делим на длины, чтобы остался только угол между векторами,
  // а не их размер. Иначе длинный текст «перевешивал» бы короткий.
  return dot / (Math.sqrt(lengthA) * Math.sqrt(lengthB));
}

