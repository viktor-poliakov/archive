const CONTEXT_BUDGET = 3000; // токенов на все фрагменты вместе

function fitToBudget(chunks, budget) {
  const kept = [];
  let used = 0;

  for (const chunk of chunks) {
    // считаем стоимость уже оформленного фрагмента — вместе с пометками,
    // они тоже занимают место в контексте
    const cost = countTokens(renderChunk(chunk, kept.length + 1));
    if (used + cost > budget) break; // дальше куски только дальше по смыслу
    kept.push(chunk);
    used += cost;
  }

  return kept;
}

// ── 4. Порядок. Самое близкое — по краям: середину модель видит хуже ──
function orderForAttention(chunks) {
  const head = [];
  const tail = [];

  chunks.forEach((chunk, i) => {
    if (i % 2 === 0) head.push(chunk); // 1-й, 3-й, 5-й — в начало
    else tail.unshift(chunk);          // 2-й, 4-й — в конец, задом наперёд
  });

  return head.concat(tail); // самый релевантный первый, второй — последний
}

