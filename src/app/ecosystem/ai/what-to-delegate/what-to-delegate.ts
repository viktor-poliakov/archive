  const percent = promo ? Math.min(promo.percent, MAX_PERCENT) : 0;
  const discountKop = Math.round((goodsKop * percent) / 100);

  // 3.3. Порог бесплатной доставки считается ПОСЛЕ скидки. Это решение бизнеса,
