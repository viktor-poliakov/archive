function findSecrets(text) {
  const hits = [];
  for (const pattern of SECRET_PATTERNS) {
    pattern.re.lastIndex = 0; // регулярка с флагом g помнит позицию между вызовами
    let match;
    while ((match = pattern.re.exec(text)) !== null) {
      hits.push({ id: pattern.id, title: pattern.title, at: match.index });
      if (match[0].length === 0) pattern.re.lastIndex += 1; // защита от зацикливания
    }
  }
  return hits.sort((a, b) => a.at - b.at);
}

function maskSecrets(text) {
  let out = text;
  for (const pattern of SECRET_PATTERNS) {
    pattern.re.lastIndex = 0;
    // Модель обычно прекрасно понимает текст с пометкой вместо ключа.
    out = out.replace(pattern.re, '[ВЫРЕЗАНО: ' + pattern.title + ']');
  }
  return out;
}

