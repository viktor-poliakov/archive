const SAMPLE_RATE = 0.05; // 5 случаев из 100 смотрит человек постфактум

function shouldSample(letterId, rate) {
  // Выборка именно СЛУЧАЙНАЯ. «Посмотрим первые двадцать за день» — это не выборка,
  // а замер утра понедельника: оценка будет смещённой и бесполезной.
  //
  // Но случайность здесь УСТОЙЧИВАЯ: решение считается из идентификатора письма,
  // а не из Math.random(). Одно и то же письмо всегда попадает в выборку либо
  // всегда не попадает, поэтому повтор обработки после сбоя не меняет картину,
  // а по логам можно заново объяснить, почему конкретное письмо туда попало.
  let h = 0;
  for (const ch of String(letterId)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return (h % 10000) / 10000 < rate;
}

