function deliveryDate(fromIso, workDays, holidays) {
  // Сроки считает производственный календарь, а не интуиция модели.
  //
  // Всё считаем в UTC и только в UTC. Строка '2026-09-16' разбирается как полночь
  // UTC, а getDay() и setDate() работают в часовой зоне сервера. Смешаешь одно
  // с другим — и в зонах с отрицательным смещением проверка выходного и сверка
  // с holidays попадут на разные сутки. Для UTC+3 сходится, поэтому такую ошибку
  // не видно на машине разработчика и видно в проде, развёрнутом в другом регионе.
  const date = new Date(fromIso);
  let left = workDays;
  while (left > 0) {
    date.setUTCDate(date.getUTCDate() + 1);
    const weekday = date.getUTCDay();
    const iso = date.toISOString().slice(0, 10);
    if (weekday !== 0 && weekday !== 6 && !holidays.includes(iso)) left -= 1;
  }
  return date.toISOString().slice(0, 10);
}

