// ═══ 2. РЕЖИМ ВЫБИРАЕМ НЕ ДЛЯ ФИЧИ ЦЕЛИКОМ, А ДЛЯ КОНКРЕТНОГО ПИСЬМА ═══

const SAFE_TOPICS = ['order-status', 'delivery', 'assortment'];
