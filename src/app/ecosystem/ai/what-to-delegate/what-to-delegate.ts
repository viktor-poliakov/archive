function amountsAreOurs(text, allowed) {
  // Нормализуем ОБА конца сравнения, убирая пробелы целиком: «1 170 ₽» с
  // разделителем разрядов — нормальная русская типографика и та же самая сумма,
  // что '1170 ₽'. \\s в регулярке ловит и обычный пробел, и неразрывный.
  function normalize(piece) {
    return piece.replace(/\\s+/g, '');
  }

  const ours = allowed.map(normalize);
  const found = text.match(/[0-9][0-9\\s]*₽/g) || [];
  return found.every(function (piece) {
    return ours.indexOf(normalize(piece)) !== -1;
  });
}

