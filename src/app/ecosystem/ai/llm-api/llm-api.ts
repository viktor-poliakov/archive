// Адрес, набор полей и имя заголовка с ключом у каждого поставщика свои.
// Точные значения берите из его документации, а не из этого примера.
const API_URL = process.env.LLM_API_URL;
const API_KEY = process.env.LLM_API_KEY;
const MODEL = process.env.LLM_MODEL;

async function callModel(messages) {
  const response = await fetch(API_URL, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      authorization: 'Bearer ' + API_KEY,
    },
    body: JSON.stringify({
      model: MODEL,
      // Предел на длину ОТВЕТА. У части поставщиков поле называется иначе.
      max_tokens: 1000,
      messages,
    }),
  });

  if (!response.ok) {
    const details = await response.text();
    throw new Error('Модель ответила ошибкой ' + response.status + ': ' + details);
  }

  return response.json();
}

// Форма ответа тоже различается. Прячем её в одну функцию, чтобы остальной
// код от неё не зависел: у одних поставщиков текст лежит в массиве блоков
// content, у других — в массиве choices.
function extractText(data) {
  if (Array.isArray(data.content)) {
    return data.content
      .filter((block) => block.type === 'text')
      .map((block) => block.text)
      .join('');
  }
  if (Array.isArray(data.choices)) {
    return data.choices[0].message.content;
  }
  throw new Error('Неизвестная форма ответа — сверьтесь с документацией');
}


