// Наружу уходят не настоящие адреса и телефоны, а метки EMAIL_1, PHONE_1,
// CARD_1. Таблицу соответствий держим у себя, в памяти одного запроса.
const EMAIL_RE = /[\w.+-]+@[\w-]+\.[\w.-]+/g;
const PHONE_RE = /\+?\d[\d\s()-]{9,14}\d/g;
const CARD_RE = /\b\d{4}[\s-]?\d{4}[\s-]?\d{4}[\s-]?\d{4}\b/g;

function createRedactor() {
  const valueByLabel = new Map();
  const counters = { EMAIL: 0, PHONE: 0, CARD: 0 };

  function labelFor(kind, value) {
    // Одно и то же значение получает одну и ту же метку, иначе модель
    // решит, что перед ней два разных человека, и ответ поедет.
    for (const [existingLabel, storedValue] of valueByLabel) {
      if (storedValue === value) return existingLabel;
    }
    counters[kind] = counters[kind] + 1;
    const created = kind + '_' + counters[kind];
    valueByLabel.set(created, value);
    return created;
  }

  return {
    // Прячем значения перед отправкой.
    redact(text) {
      return text
        .replace(EMAIL_RE, (found) => labelFor('EMAIL', found))
        .replace(PHONE_RE, (found) => labelFor('PHONE', found))
        .replace(CARD_RE, (found) => labelFor('CARD', found));
    },
    // Возвращаем настоящие значения уже в ответе, у себя на сервере.
    restore(text) {
      let result = text;
      for (const [labelName, value] of valueByLabel) {
        result = result.split(labelName).join(value);
      }
      return result;
    }
  };
}


