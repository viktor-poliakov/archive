// ═══ СЧИТАЕМ ДЕНЬГИ: ТОКЕНЫ БЕРЁМ ИЗ ОТВЕТА, А НЕ НА ГЛАЗ ═══

// Цифры ниже условные и нужны только чтобы показать формулу.
// Реальные ставки у каждого поставщика и каждой модели свои, они меняются,
// и читать их надо из конфигурации и из действующего прайса.
const PRICING = {
  'model-small': { inputPerMillion: 0.3, outputPerMillion: 1.5 },
  'model-large': { inputPerMillion: 3, outputPerMillion: 15 }
};

function readUsage(payload) {
  const usage = payload.usage || {};
  // Поля называются по-разному: где-то input_tokens и output_tokens,
  // где-то prompt_tokens и completion_tokens. Смотрите свою документацию.
  const input = usage.input_tokens ?? usage.prompt_tokens ?? null;
  const output = usage.output_tokens ?? usage.completion_tokens ?? null;
  return { input, output };
}

function estimateCost(model, usage) {
  const price = PRICING[model];
  if (!price || usage.input === null || usage.output === null) return null;
  // null лучше нуля: ноль молча испортит среднюю стоимость, а null видно.
  return (usage.input / 1000000) * price.inputPerMillion +
    (usage.output / 1000000) * price.outputPerMillion;
}


// ═══ ОБЁРТКА: ОДИН ВЫЗОВ — ОДНА ЗАПИСЬ В УЧЁТЕ ═══

async function callModel(options) {
  const startedAt = Date.now();

  const event = {
    at: new Date().toISOString(),
    feature: options.feature,             // какая фича продукта дёргает модель
    userId: options.userId,               // чтобы найти одного тяжёлого клиента
    requestId: options.requestId,         // сквозной идентификатор запроса
    model: options.model,
    promptVersion: options.promptVersion, // версия инструкции
    status: 'unknown',
    httpStatus: null,
    durationMs: null,
    inputTokens: null,
    outputTokens: null,
    costUsd: null,
    answerLength: null,
    looksEmpty: null,
    errorKind: null
  };

  try {
    const response = await fetch(options.url, options.init);
    event.httpStatus = response.status;

    if (!response.ok) {
      event.status = 'error';
      // 429 считаем отдельно: это не авария, а ограничение частоты.
      event.errorKind = response.status === 429 ? 'rate-limit' : 'http';
      return { ok: false, status: response.status }; // [!error]
    }

    const payload = await response.json();
    const usage = readUsage(payload);
    const answer = payload.choices[0].message.content; // путь зависит от API

    event.status = 'ok';
    event.inputTokens = usage.input;
    event.outputTokens = usage.output;
    event.costUsd = estimateCost(options.model, usage);
    event.answerLength = answer.length;
    event.looksEmpty = answer.trim().length < 40; // подозрительно короткий ответ

    return { ok: true, answer };
  } catch (error) {
    event.status = 'error';
    event.errorKind = error.name === 'AbortError' ? 'timeout' : 'network';
    throw error;
  } finally {
    event.durationMs = Date.now() - startedAt;
    // finally — не для красоты: ошибки и таймауты обязаны попадать в учёт
    // наравне с успехами, иначе график получится гладкий и неправдивый.
    logger.info('llm_call', event);
    metrics.timing('llm.duration', event.durationMs, { feature: event.feature });
    budget.add(event.costUsd || 0);
  }
}


