function fitHistory(messages, limit) {
  const system = messages.filter((m) => m.role === 'system');
  const rest = messages.filter((m) => m.role !== 'system');

  const budget = limit - RESERVED_FOR_ANSWER - estimateMessages(system);
  const kept = [];
  let used = 0;

  // Идём с конца: самые свежие реплики важнее самых старых.
  for (let i = rest.length - 1; i >= 0; i--) {
    const cost = estimateTokens(rest[i].content) + 4;
    if (used + cost > budget) break;
    kept.unshift(rest[i]);
    used += cost;
  }

  // Не начинаем историю с ответа модели: пара «вопрос — ответ» должна
  // оставаться целой, иначе начало истории читается как обрывок.
  while (kept.length > 0 && kept[0].role === 'assistant') {
    kept.shift();
  }

  return system.concat(kept);
}

async function askSafely(history, userText) {
  const draft = history.concat([{ role: 'user', content: userText }]);
  const size = estimateMessages(draft);

  if (size + RESERVED_FOR_ANSWER > CONTEXT_LIMIT) {
    console.warn('Не помещаемся: примерно ' + size + ' токенов, обрезаю историю');
    return callModel(fitHistory(draft, CONTEXT_LIMIT));
  }

  return callModel(draft);
}


