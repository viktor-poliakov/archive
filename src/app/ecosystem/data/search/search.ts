async function reindexAll(targetIndex) {
  let lastId = 0;

  // Идём страницами по первичному ключу, а не OFFSET: на большой
  // таблице OFFSET заставляет базу каждый раз пролистывать начало.
  for (;;) {
    const batch = await db.query(
      'SELECT * FROM products WHERE id > $1 ORDER BY id LIMIT 1000',
      [lastId],
    );
    if (batch.length === 0) break;

    // Пачками! Тысяча документов одним запросом вместо тысячи запросов.
    await targetIndex.addDocuments(batch.map(toSearchDoc));

    lastId = batch[batch.length - 1].id;
    console.log('Проиндексировано до id', lastId);
  }
}

