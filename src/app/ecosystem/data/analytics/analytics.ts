//    ПУСТО. Если в этот момент кто-то откроет дашборд, он увидит нули.
// 4. Всё, что вы посчитали поверх этой таблицы, пересчитывается заново.


// ═══ ЗДОРОВЫЙ ВАРИАНТ: ИНКРЕМЕНТАЛЬНАЯ ЗАГРУЗКА ═══
// Идея простая: забираем только то, что изменилось с прошлого раза.
// Отметку «до какого момента уже забрали» называют водяным знаком
// (по-английски watermark) и хранят её в самом хранилище.

async function syncOrders() {
  // 1. Узнаём, на чём остановились в прошлый раз.
  const state = await warehouse.query(
    'SELECT max(updated_at) AS last_seen FROM orders_raw',
  );

  // ПЕРЕКРЫТИЕ В ПЯТЬ МИНУТ — не паранойя, а необходимость.
  // Транзакция могла начаться до прошлой выгрузки, а завершиться после:
  // её строки появились в базе «задним числом» и без перекрытия
  // были бы пропущены навсегда.
  const since = new Date(state.last_seen.getTime() - 5 * 60 * 1000);

  // 2. Забираем изменения ПАЧКАМИ, а не одним куском:
  //    так мы не держим на боевой базе один длинный запрос
  //    и не пытаемся уместить всё в память своего процесса.
  let cursor = since;
  for (;;) {
    const batch = await primary.query(
      'SELECT id, customer_id, status, total_cents, created_at, updated_at ' +
      'FROM orders WHERE updated_at > $1 ORDER BY updated_at LIMIT 50000',
      [cursor],
    );

    if (batch.rows.length === 0) break;

    // 3. Кладём в хранилище. Строка с тем же id могла приехать и вчера —
    //    поэтому загрузка должна быть идемпотентной: повтор не должен
    //    порождать дубликат. В колоночных базах для этого либо
    //    перезаписывают целую партицию, либо берут движок,
    //    умеющий схлопывать строки по ключу.
    await warehouse.insertOrReplace('orders_raw', batch.rows);

    cursor = batch.rows[batch.rows.length - 1].updated_at;
  }
}

