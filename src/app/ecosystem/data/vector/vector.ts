// Три идеи: резать по смысловым границам, делать перекрытие
// и приклеивать к каждому куску его происхождение.

function splitIntoChunks(doc, options = {}) {
  const targetSize = options.targetSize || 900;   // знаков в куске
  const overlap = options.overlap || 150;         // знаков перекрытия

  // 1. Сначала режем по границам, которые расставил АВТОР, — по абзацам.
  //    Абзац — это готовая смысловая единица; лучше линейки не придумать.
  const paragraphs = doc.body
    .split(/\\n\\s*\\n/)
    .map((p) => p.trim())
    .filter(Boolean);

  const chunks = [];
  let current = '';

  for (const paragraph of paragraphs) {
    // 2. Копим абзацы, пока кусок не дорос до целевого размера.
    if (current && (current + paragraph).length > targetSize) {
      chunks.push(current);

      // 3. ПЕРЕКРЫТИЕ: следующий кусок начинается с хвоста предыдущего.
      //    Это страховка от того, что нужная фраза разорвана границей.
      current = current.slice(-overlap) + '\\n\\n' + paragraph;
    } else {
      current = current ? current + '\\n\\n' + paragraph : paragraph;
    }
  }

  if (current) {
    chunks.push(current);
  }

  // 4. И самое недооценённое: в САМ ТЕКСТ куска подмешиваем заголовки.
  //    Кусок «срок составляет 14 дней» бесполезен: в нём нет ни слова
  //    про возврат. Кусок «Возврат товара. Сроки. Срок составляет
  //    14 дней» найдётся по вопросу «сколько дней на возврат», потому
  //    что нужные слова теперь ВНУТРИ куска, а значит, и внутри вектора.
  return chunks.map((text, i) => ({
    text: doc.title + '. ' + doc.section + '. ' + text,
    metadata: {
      documentId: doc.id,
      title: doc.title,
      section: doc.section,
      chunkIndex: i,
      url: doc.url,
      updatedAt: doc.updatedAt,
    },
  }));
}

