async function evaluate(searchFn, k = 10) {
  let hits = 0;
  let total = 0;
  const failures = [];

  for (const item of goldenSet) {
    const found = (await searchFn(item.query, k)).map((r) => r.id);
    const matched = item.expected.filter((id) => found.includes(id));

    hits += matched.length;
    total += item.expected.length;

    if (matched.length < item.expected.length) {
      failures.push({
        query: item.query,
        missing: item.expected.filter((id) => !found.includes(id)),
      });
    }
  }

  return {
    // Доля правильных ответов, попавших в первые k. Её называют
    // полнотой, в документации — recall@k.
    recall: hits / total,
    failures,   // а вот это читать глазами: тут видно, ЧТО именно сломалось
  };
}

