async function answerQuestion(question, user) {
  // ШАГ 1. Вопрос превращаем в вектор — ТОЙ ЖЕ моделью, что и документы.
  const questionVector = await embed(question);

  // ШАГ 2. Ищем куски, похожие по смыслу. Фильтры — прямо здесь, рядом
  // с поиском: человек не должен получить кусок чужого документа
  // только потому, что он оказался ближе по смыслу.
  const { rows } = await pool.query(
    'SELECT content, metadata, 1 - (embedding <=> $1::vector) AS similarity ' +
      'FROM doc_chunks ' +
      'WHERE workspace_id = $2 AND is_published ' +
      'ORDER BY embedding <=> $1::vector ' +
      'LIMIT 6',
    ['[' + questionVector.join(',') + ']', user.workspaceId],
  );

  // ШАГ 3. ОТСЕКАЕМ СЛАБЫЕ СОВПАДЕНИЯ — это обязательный шаг.
  // Поиск ближайших соседей всегда что-нибудь возвращает: на вопрос
  // «как приготовить плов» он честно выдаст шесть самых близких кусков
  // вашей документации по бухгалтерии. Без порога языковая модель
  // получит мусор и вежливо сочинит по нему уверенный ответ.
  const good = rows.filter((r) => r.similarity > 0.35);

  if (good.length === 0) {
    return { answer: 'В нашей базе знаний нет ответа на этот вопрос.', sources: [] };
  }

  // ШАГ 4. Собираем запрос к языковой модели. Найденные куски кладём
  // ПРЯМО В ТЕКСТ запроса — вот это и есть всё «дополнение поиском».
  const context = good
    .map((r, i) => '[' + (i + 1) + '] ' + r.metadata.title + '\\n' + r.content)
    .join('\\n\\n---\\n\\n');

  const prompt =
    'Ответь на вопрос, опираясь ТОЛЬКО на приведённые фрагменты.\\n' +
    'Если ответа в них нет — так и скажи, не придумывай.\\n' +
    'В конце укажи номера фрагментов, которыми ты воспользовался.\\n\\n' +
    'ФРАГМЕНТЫ:\\n' + context + '\\n\\n' +
    'ВОПРОС: ' + question;

  const answer = await llm.complete(prompt);

  // ШАГ 5. Возвращаем ответ ВМЕСТЕ С ИСТОЧНИКАМИ. Это не украшение:
  // ссылка на исходный документ — единственный способ для человека
  // проверить, не сочинила ли модель половину ответа.
  return {
    answer,
    sources: good.map((r) => ({ title: r.metadata.title, url: r.metadata.url })),
  };
}

