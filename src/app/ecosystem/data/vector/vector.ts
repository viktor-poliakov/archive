// Пачками, а не по одному: каждый вызов модели — это поход по сети,
// а за один запрос она принимает сразу много текстов.
const BATCH = 64;

async function embedBatch(texts) {
  const res = await fetch('https://api.openai.com/v1/embeddings', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: 'Bearer ' + process.env.OPENAI_API_KEY,
    },
    body: JSON.stringify({ model: MODEL, input: texts }),
  });

  const json = await res.json();

  // Порядок ответов совпадает с порядком входов, но проверять это
  // лучше по полю index, а не верить на слово: перепутанные местами
  // векторы дадут поиск, который правдоподобно врёт.
  return json.data.sort((a, b) => a.index - b.index).map((d) => d.embedding);
}

async function indexDocument(doc) {
  // Функция splitIntoChunks — из следующего раздела, про нарезку.
  const chunks = splitIntoChunks(doc);

  // СНАЧАЛА УДАЛЯЕМ СТАРЫЕ КУСКИ ЭТОГО ДОКУМЕНТА.
  // Документ отредактировали, абзацев стало меньше, кусков стало меньше —
  // а хвост прежней версии остался в базе и продолжает находиться.
  // Это одна из самых обидных ошибок: ответы «из ниоткуда».
  await pool.query('DELETE FROM doc_chunks WHERE document_id = $1', [doc.id]);

  for (let i = 0; i < chunks.length; i += BATCH) {
    const batch = chunks.slice(i, i + BATCH);
    const vectors = await embedBatch(batch.map((c) => c.text));

    for (let j = 0; j < batch.length; j++) {
      await pool.query(
        'INSERT INTO doc_chunks ' +
          '(document_id, chunk_index, content, metadata, embedding, model) ' +
          'VALUES ($1, $2, $3, $4, $5, $6)',
        [
          doc.id,
          batch[j].metadata.chunkIndex,
          batch[j].text,
          batch[j].metadata,
          '[' + vectors[j].join(',') + ']',   // вектор уезжает строкой
          MODEL,                               // и рядом — имя модели
        ],
      );
    }
  }
}

