// ═══ ЛЕЧЕНИЕ 2: ПОВТОР ТРАНЗАКЦИИ ═══
// Полностью исключить взаимные блокировки в большой системе не выйдет.
// Хорошая новость: база их САМА обнаруживает за доли секунды, убивает
// одну из двух транзакций и возвращает опознаваемую ошибку.
// В PostgreSQL это код 40P01, а 40001 — «не удалось сериализовать доступ»
// (её вы увидите на строгих уровнях изоляции). Обе означают одно:
// «повтори транзакцию, в этот раз, скорее всего, получится».

async function withRetry(action, attempts = 3) {
  for (let attempt = 1; attempt <= attempts; attempt++) {
    try {
      return await action();
    } catch (err) {
      const retriable = err.code === '40P01' || err.code === '40001';

      if (!retriable || attempt === attempts) {
        throw err;
      }

      // Небольшая случайная пауза, чтобы обе транзакции не рванули
      // повторяться в одну и ту же миллисекунду и не столкнулись снова.
      await new Promise((resolve) => setTimeout(resolve, 50 * attempt + Math.random() * 50));
    }
  }
}

