async function runOnce(taskName, work) {
  const lockKey = 'shop:lock:' + taskName;

  // Ключевые слова здесь два, и оба обязательны.
  //   'NX' — «запиши, только если ключа ещё нет». Проверка и запись
  //          происходят внутри Redis как одно неделимое действие,
  //          поэтому из пяти одновременных попыток удастся одна.
  //   'EX' — срок жизни. Процесс, взявший замок, может умереть,
  //          и без срока замок остался бы навсегда: задание
  //          перестало бы выполняться вообще, и тихо.
  const acquired = await redis.set(lockKey, process.pid, 'EX', 300, 'NX');

  if (!acquired) {
    // Кто-то другой уже работает. Спокойно уходим.
    return false;
  }

  try {
    await work();
    return true;
  } finally {
    await redis.del(lockKey);
  }
}

