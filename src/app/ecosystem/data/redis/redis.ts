async function checkRateLimit(ip) {
  // Ключ включает НОМЕР МИНУТЫ. За счёт этого каждую минуту
  // начинается новый ключ, и «окно» сдвигается само собой.
  const minute = Math.floor(Date.now() / 60000);
  const key = 'shop:ratelimit:login:' + ip + ':' + minute;

  // Две команды одной посылкой. multi отправляет их вместе,
  // и Redis выполняет их подряд, никого не впуская между ними.
  const [[, hits]] = await redis
    .multi()
    .incr(key)        // прибавить единицу (ключа нет — станет 1)
    .expire(key, 120) // и обязательно назначить срок жизни
    .exec();

  // ЗАЧЕМ EXPIRE. Без него ключей накопится по одному на каждую
  // минуту на каждый адрес — и они останутся в памяти НАВСЕГДА.
  // Через месяц это миллионы мёртвых счётчиков.
  // Срок берём с запасом (120 при окне в 60): так ключ переживёт
  // рассинхронизацию часов и не исчезнет посреди своей минуты.

  return hits <= 10;
}

