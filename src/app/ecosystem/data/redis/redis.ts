// ═══ ЛЕЧЕНИЕ 1. ЗАМОК: считает один, ждут остальные ═══

async function getProductCardLocked(id) {
  const key = 'shop:product:' + id + ':card';

  const cached = await redis.get(key);
  if (cached !== null) return JSON.parse(cached);

  // Пробуем взять замок. 'NX' означает «запиши, ТОЛЬКО ЕСЛИ ключа
  // ещё нет». Эта проверка происходит внутри Redis целиком,
  // поэтому из тысячи одновременных попыток удастся ровно одна.
  const lockKey = key + ':lock';
  const gotLock = await redis.set(lockKey, '1', 'EX', 10, 'NX');

  if (!gotLock) {
    // Замок у кого-то другого — значит, он уже считает.
    // Ждём чуть-чуть и пробуем прочитать кэш ещё раз.
    await new Promise((resolve) => setTimeout(resolve, 50));
    const retry = await redis.get(key);
    if (retry !== null) return JSON.parse(retry);

    // Не дождались — отдаём то, что можем, не ломая страницу.
    return buildProductCardLight(id);
  }

  try {
    const card = await buildProductCard(id);
    await redis.set(key, JSON.stringify(card), 'EX', 300);
    return card;
  } finally {
    // Замок снимаем ВСЕГДА, даже если запрос упал. Иначе следующие
    // десять секунд никто не сможет пересчитать этот ключ.
    // И обратите внимание на 'EX', 10 при взятии: даже если процесс
    // умрёт прямо здесь, замок протухнет сам. Замок без срока
    // годности — это заклинившая дверь.
    await redis.del(lockKey);
  }
}


