//
// Самый простой способ, до которого додумывается каждый. Идея:
// разбить время на равные отрезки («окна») и в каждом отрезке
// считать запросы с нуля.
//
// Аналогия. Вахтёр с блокнотом. В начале каждого часа он рвёт лист
// и начинает считать заново. Пришло больше сотни — «приходите
// в следующем часу».

const windowCounters = new Map();   // ключ → сколько запросов в текущем окне

function fixedWindowAllow(key, limit, windowMs) {
  const now = Date.now();

  // ГЛАВНАЯ СТРОКА. Целочисленное деление времени на длину окна
  // даёт НОМЕР окна. Все запросы одной минуты дают один и тот же номер.
  const windowId = Math.floor(now / windowMs);

  // Ключ счётчика включает номер окна — значит, при смене окна
  // мы просто начинаем писать в другую ячейку, а старая обнуляется сама.
  const counterKey = key + ':' + windowId;

  const used = windowCounters.get(counterKey) ?? 0;

  if (used >= limit) {
    return { allowed: false, remaining: 0 };
  }

  windowCounters.set(counterKey, used + 1);
  return { allowed: true, remaining: limit - used - 1 };
}


