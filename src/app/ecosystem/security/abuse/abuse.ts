app.post('/api/signup', async (req, res) => {
  // ─── ПРОВЕРКА 1. Приманка ───
  if (req.body.homepage) {
    // ВАЖНАЯ ДЕТАЛЬ: не пишем «вы бот». Отвечаем ровно так же, как
    // при успехе. Бот считает, что всё получилось, и уходит довольный,
    // а его хозяин не узнает, что именно его выдало.
    // Это называют «тихим отказом»: боту не дают обратной связи,
    // по которой можно подстроиться.
    metrics.increment('signup.honeypot_hit');
    res.json({ ok: true });
    return;
  }

  // ─── ПРОВЕРКА 2. Секундомер ───
  const formShownAt = readSignedTimestamp(req.body.form_ts);

  if (formShownAt === null) {
    // Подпись не сошлась: форму не отдавали мы, либо её переписали.
    res.status(400).json({ code: 'bad_form_token' });
    return;
  }

  const elapsedMs = Date.now() - formShownAt;

  if (elapsedMs < 2500) {
    // Слишком быстро. Порог берите с запасом: 2–3 секунды. Не 5 —
    // человек, у которого пароль в менеджере паролей, отправляет
    // форму действительно быстро.
    metrics.increment('signup.too_fast');
    res.status(400).json({ code: 'too_fast', message: 'Проверьте форму и отправьте снова.' });
    return;
  }

  if (elapsedMs > 2 * 60 * 60 * 1000) {
    // Слишком долго — форма провисела в открытой вкладке два часа.
    // Это не бот, но отметку надо считать просроченной, иначе
    // одну выданную форму можно переиспользовать бесконечно.
    res.status(400).json({ code: 'form_expired', message: 'Форма устарела, обновите страницу.' });
    return;
  }

  await createUser(req.body);
  res.json({ ok: true });
});


