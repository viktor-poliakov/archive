// ═══ ИДЕЯ: КЛЮЧ ИДЕМПОТЕНТНОСТИ ═══
//
// Слово «идемпотентный» означает: сколько раз ни повтори — результат
// один и тот же. Бытовая аналогия: нажать кнопку вызова лифта. Жмите
// её десять раз — приедет один лифт. Кнопка идемпотентна.
//
// Как сделать идемпотентной оплату: клиент придумывает УНИКАЛЬНУЮ
// строку на КАЖДОЕ НАМЕРЕНИЕ заплатить и присылает её в заголовке.
// Все повторы одного нажатия несут ОДИН И ТОТ ЖЕ ключ. Сервер видит
// знакомый ключ — значит, это повтор, и вместо второго списания
// отдаёт сохранённый результат первого.
//
// САМОЕ ВАЖНОЕ ПРО КЛЮЧ. Он генерируется один раз, когда человек
// нажал кнопку, и НЕ меняется при повторах. Если сгенерировать новый
// ключ на каждую отправку запроса — вся затея бессмысленна, потому что
// каждый повтор будет выглядеть как новая оплата.


// ═══ КОД КЛИЕНТА ═══

async function payOrder(orderId, cardToken) {
  // crypto.randomUUID() даёт случайную строку, повтор которой
  // практически невозможен. Генерируем её ЗДЕСЬ, до цикла повторов.
  const idempotencyKey = crypto.randomUUID();

  // Кнопку на время запроса блокируем — это не защита (запрос могут
  // отправить и в обход интерфейса), но самый частый случай двойного
  // нажатия закрывает.
  setButtonDisabled(true);

  try {
    // Все попытки внутри fetchWithRetry уйдут с ОДНИМ И ТЕМ ЖЕ ключом.
    return await fetchWithRetry('/api/orders/' + orderId + '/pay', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Idempotency-Key': idempotencyKey,
      },
      body: JSON.stringify({ cardToken }),
    });
  } finally {
    setButtonDisabled(false);
  }
}


// ═══ ЗДОРОВЫЙ КОД СЕРВЕРА ═══
//
// Ключ хранится в отдельной таблице. Схема примерно такая:
//
//   idempotency_keys
//     key           текст, ПЕРВИЧНЫЙ КЛЮЧ  ← вот это главное
//     user_id       чей это ключ
//     endpoint      какая ручка (один ключ на одну ручку)
//     request_hash  отпечаток тела запроса
//     status        'in_progress' | 'done'
//     response_body сохранённый ответ
//     created_at    когда
//
// Слова «ПЕРВИЧНЫЙ КЛЮЧ» здесь несут всю нагрузку. База физически
// не позволит вставить вторую строку с тем же значением — и именно
// она, а не наш код, разрешает гонку между двумя одновременными
// запросами. Побеждает тот, кто вставился; второй получает ошибку
// нарушения уникальности и понимает, что он повтор.

app.post('/api/orders/:id/pay', async (req, res) => {
  const key = req.get('Idempotency-Key');

  // Для операций с деньгами ключ ОБЯЗАТЕЛЕН. Не «если прислали» —
  // обязателен. Иначе о нём просто забудут в новом клиенте.
  if (!key) {
    res.status(400).json({ code: 'idempotency_key_required' });
    return;
  }

  // Отпечаток тела запроса. Нужен для защиты от чужой ошибки:
  // если по тому же ключу пришло ДРУГОЕ тело (другая сумма, другая
  // карта), это не повтор, а баг в клиенте, и его надо показать,
  // а не тихо отдать старый ответ.
  const requestHash = sha256(JSON.stringify(req.body));

  let claimed;
  try {
    // Пытаемся «занять» ключ. Одна вставка, атомарно.
    claimed = await db.insert('idempotency_keys', {
      key,
      user_id: req.user.id,
      endpoint: 'POST /api/orders/pay',
      request_hash: requestHash,
      status: 'in_progress',
    });
  } catch (error) {
    if (!isUniqueViolation(error)) throw error;

    // Ключ уже есть — это повтор. Достаём, что с ним было.
    const existing = await db.selectOne('idempotency_keys', { key });

    if (existing.request_hash !== requestHash) {
      // Тот же ключ, другое тело. Отвечаем 422: клиент ошибся.
      res.status(422).json({ code: 'idempotency_key_reuse_with_different_body' });
      return;
    }

    if (existing.status === 'in_progress') {
      // Первый запрос ещё выполняется. Честный ответ — 409 «конфликт»
      // плюс Retry-After: «подожди чуть-чуть и спроси снова».
      // Дожидаться внутри обработчика нельзя: заняли бы соединение.
      res.setHeader('Retry-After', '2');
      res.status(409).json({ code: 'request_in_progress' });
      return;
    }

    // Первый запрос завершён — отдаём ТОТ ЖЕ САМЫЙ ответ.
    // Именно тот же, а не «похожий»: клиент имеет право получить
    // на повтор ровно то, что получил бы на первый запрос.
    res.status(200).json(existing.response_body);
    return;
  }

  // Мы заняли ключ первыми — делаем работу.
  const order = await orders.findById(req.params.id);

  // Ключ идемпотентности передаём и дальше, платёжному провайдеру:
  // у всех серьёзных провайдеров такой заголовок есть, и он защищает
  // от двойного списания уже на их стороне.
  const charge = await paymentProvider.charge(
    { amount: order.total, card: req.body.cardToken },
    { idempotencyKey: key },
  );

  await orders.update(order.id, { status: 'paid', chargeId: charge.id });

  const responseBody = { ok: true, chargeId: charge.id };

  await db.update('idempotency_keys', { key }, {
    status: 'done',
    response_body: responseBody,
  });

  res.json(responseBody);
});


