// ═══ ЗДОРОВЫЙ КОД. Ключ выбирается по смыслу ручки ═══
//
// Главная мысль: единого правильного ключа не существует. Ключ зависит
// от того, ОТ ЧЕГО мы защищаемся на этой конкретной ручке.

function buildRateLimitKey(req) {
  // 1. ЕСТЬ ТОКЕН ПРИЛОЖЕНИЯ-ПАРТНЁРА — считаем по нему.
  //    Это самый честный ключ: он выдан вами, его нельзя подделать,
  //    и он ровно соответствует тому, кому вы продали доступ.
  if (req.apiKeyId) {
    return 'key:' + req.apiKeyId;
  }

  // 2. ПОЛЬЗОВАТЕЛЬ ВОШЁЛ — считаем по номеру пользователя.
  //    Адрес больше не важен: пусть человек ходит хоть с двадцати
  //    устройств, лимит у него один. И офис на четыреста человек
  //    перестаёт быть проблемой — у каждого свой счётчик.
  if (req.user) {
    return 'user:' + req.user.id;
  }

  // 3. ГОСТЬ — деваться некуда, считаем по сети.
  //    Для IPv4 берём адрес, для IPv6 — подсеть /64 (см. БЕДУ 2).
  return 'net:' + toNetworkKey(req.ip);
}

