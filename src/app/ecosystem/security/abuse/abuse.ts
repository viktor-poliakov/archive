// ═══ ЗДОРОВЫЙ КОД. Ответ 429 с полным набором подсказок ═══
//
// Код 429 Too Many Requests означает ровно то, что нам нужно:
// «запрос правильный, ты имеешь право, но слишком часто; подожди
// и повтори». Это единственный код с таким смыслом.

function rejectTooManyRequests(res, decision) {
  res.status(429);

  // ─── ЗАГОЛОВОК RETRY-AFTER: САМОЕ ГЛАВНОЕ ───
  //
  // Он описан в стандарте HTTP и понимается всеми. Значение — либо
  // число секунд ожидания, либо дата в формате HTTP. Числом проще
  // и надёжнее: не зависит от часов на клиенте.
  //
  // Без этого заголовка клиент вынужден ГАДАТЬ, сколько ждать.
  // И, как правило, гадает в сторону «попробую через секунду».
  res.setHeader('Retry-After', String(decision.retryAfterSeconds));

  // ─── ЗАГОЛОВКИ СЕМЕЙСТВА RATELIMIT-* ───
  //
  // ВАЖНАЯ ОГОВОРКА О СТАТУСЕ. Эти заголовки — не часть принятого
  // стандарта. В IETF есть черновик (draft) «RateLimit header fields
  // for HTTP», он много лет обсуждается и его написание менялось:
  // встречаются и варианты с приставкой X-, и с приставкой RateLimit-,
  // и новый вариант с одним структурированным полем.
  // Практический вывод: заголовки полезны и их стоит отдавать, но
  // рассчитывать, что чужой клиент их поймёт «по стандарту», нельзя.
  // Единственное, на что можно опираться всерьёз, — это код 429
  // и Retry-After. Остальное — вежливая подсказка человеку, который
  // будет разбираться с вашим API.
  res.setHeader('RateLimit-Limit', String(decision.limit));      // сколько всего можно
  res.setHeader('RateLimit-Remaining', String(decision.remaining)); // сколько осталось
  res.setHeader('RateLimit-Reset', String(decision.retryAfterSeconds)); // через сколько обновится

  // ─── ТЕЛО ОТВЕТА: ДЛЯ ЧЕЛОВЕКА И ДЛЯ ПРОГРАММЫ ───
  res.json({
    // Машинный код ошибки — по нему клиент ветвит логику. Строка
    // из закрытого списка, а не свободный текст.
    code: 'rate_limit_exceeded',

    // Текст для человека. По-русски, без слова «rate limit».
    message: 'Слишком много запросов. Попробуйте через минуту.',

    // Дублируем время ожидания в теле: заголовки читать умеют не все
    // клиентские библиотеки, а тело разбирают всегда.
    retryAfterSeconds: decision.retryAfterSeconds,

    // Идентификатор запроса — чтобы поддержка нашла эту строку
    // в журнале, если человек напишет «мне ничего не открывается».
    requestId: res.locals.requestId,
  });
}

// ЕЩЁ ОДНА ТОНКОСТЬ. Заголовки с остатком лимита полезно отдавать
// на УСПЕШНЫХ ответах тоже, а не только на отказах. Тогда аккуратный
// клиент видит, что у него осталось 3 запроса из 100, и сам сбавляет
// темп — вместо того чтобы наткнуться на стену и удивиться.


// ═══ ВТОРАЯ ПОЛОВИНА ЗАДАЧИ: КОД КЛИЕНТА ═══
//
// Отказ бесполезен, если клиент на него не реагирует по-человечески.
// А по-человечески — это «подождать и повторить», и оба слова здесь
// сложнее, чем кажутся.

async function fetchWithRetry(url, options = {}, maxAttempts = 5) {
  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    const response = await fetch(url, options);

    // Всё, что не 429 и не 5xx, — окончательный ответ. Повторять
    // 404 или 403 бессмысленно, ответ не изменится.
    if (response.status !== 429 && response.status < 500) {
      return response;
    }

    // Попытки кончились — отдаём последний ответ как есть, пусть
    // вызывающий код сам решает, что делать.
    if (attempt === maxAttempts) {
      return response;
    }

    // ─── СКОЛЬКО ЖДАТЬ ───
    //
    // ШАГ 1. Если сервер сказал сколько — слушаем сервер. Он знает
    // про свои лимиты больше нас.
    const serverHint = Number(response.headers.get('Retry-After'));

    // ШАГ 2. Не сказал — считаем сами, УДВАИВАЯ паузу на каждой
    // попытке (это называется экспоненциальная выдержка):
    //   попытка 1 → 1 с, 2 → 2 с, 3 → 4 с, 4 → 8 с.
    // Смысл: если сервер перегружен, наши повторы не должны добавлять
    // ему нагрузки. Чем дольше он не отвечает, тем реже мы стучимся.
    const backoffSeconds = Number.isFinite(serverHint) && serverHint > 0 ? serverHint : 2 ** (attempt - 1);

    // ШАГ 3. И САМОЕ ВАЖНОЕ — СЛУЧАЙНЫЙ РАЗБРОС (jitter).
    //
    // ЗАЧЕМ ОН НУЖЕН. Представьте, что сервер на минуту стал недоступен,
    // а на него смотрят десять тысяч приложений. Все десять тысяч
    // получили отказ примерно одновременно. Все посчитали «жду 1
    // секунду». Через секунду все десять тысяч ударили ОДНОВРЕМЕННО.
    // Сервер, который только-только начал вставать, падает снова.
    // Все ждут 2 секунды. Через 2 секунды — снова одновременный удар.
    //
    // Это называют «стадом» (thundering herd): повторы синхронизируются
    // и превращаются в самодельную атаку на отказ в обслуживании.
    // Причём атакуют вас ваши же клиенты, честно исполняющие ваш
    // собственный совет «повторите позже».
    //
    // ЛЕЧЕНИЕ ОДНОЙ СТРОКОЙ: размазать момент повтора случайно.
    // Здесь взято «от половины до полутора расчётных пауз» — стадо
    // растягивается в ровный ручеёк, и никакого удара нет.
    const jittered = backoffSeconds * (0.5 + Math.random());

    await sleep(jittered * 1000);
  }
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}


