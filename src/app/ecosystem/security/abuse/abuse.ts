//
// БЕДА 1. ОДИН АДРЕС — МНОГО ЛЮДЕЙ.
//   Офис на четыреста человек выходит в интернет через один внешний
//   адрес (это называется NAT — подмена адресов на выходе). Школа,
//   университет, кофейня, вагон поезда — то же самое.
