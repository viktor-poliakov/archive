// ═══ ГДЕ ЭТОТ КОД ВСЁ-ТАКИ УМЕСТЕН ═══
//
// Честно: он не всегда плох. Счётчик в памяти хорош как ВТОРОЙ,
// грубый рубеж — «не больше 500 запросов в секунду с одного адреса
