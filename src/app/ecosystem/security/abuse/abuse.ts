//   миллиардов адресов), и он может брать новый адрес на каждый запрос.
//   Итог: лимит по отдельному адресу IPv6 не ограничивает ничего вообще.
//   Поэтому для IPv6 считают не по адресу, а по подсети /64.
//
// БЕДА 3. АДРЕСА АРЕНДУЮТ ДЕШЕВО.
//   Тысяча адресов в облаке или в сети прокси стоит десятки долларов.
//   Скрейпер из примера в начале страницы ходил с разных адресов именно
//   поэтому — это не сложно и не дорого.


// ═══ И ГЛАВНАЯ ЛОВУШКА: КАК ВООБЩЕ УЗНАТЬ АДРЕС КЛИЕНТА ═══
//
// Если перед приложением стоит хоть что-нибудь — балансировщик, nginx,
// CDN, — то соединение к приложению приходит НЕ от пользователя, а от
// этого посредника. И req.ip покажет адрес посредника, один и тот же
// для всех. Лимит превратится в «100 запросов в минуту на весь мир».
//
// Чтобы этого не было, посредники добавляют заголовок X-Forwarded-For:
// «этот запрос я получил вот с такого адреса». Заголовок накопительный:
// каждый следующий посредник дописывает в конец адрес, от которого
// запрос пришёл лично к нему.
//
//   X-Forwarded-For: 203.0.113.77, 70.41.3.18, 150.172.238.178
//                    ▲             ▲           ▲
//                    │             │           └ добавил ваш nginx
//                    │             └ добавил CDN
//                    └ это написал КЛИЕНТ, и там может быть что угодно
//
// ВОТ ГДЕ ДЫРА. Заголовок — обычный текст в запросе. Клиент может
// прислать его сам, с любым содержимым. И если вы читаете первый адрес
// слева, атакующий просто подставляет новый выдуманный адрес в каждый
// запрос — и лимит не срабатывает никогда, потому что каждый запрос
// выглядит как «первый от нового человека».
//
// ПРАВИЛО, КОТОРОЕ НАДО ЗАПОМНИТЬ ДОСЛОВНО:
// доверять можно только той части заголовка, которую дописал ВАШ
// собственный прокси. Всё, что было в заголовке до него, — это данные
// от клиента, то есть ничего не значащий текст.

// ЗДОРОВЫЙ КОД. Явно говорим, сколько посредников перед нами.
//
// Настройка 'trust proxy' в Express принимает ЧИСЛО — сколько
// последних адресов в X-Forwarded-For поставлены нашими посредниками.
// Одна цифра, но она должна быть правильной:
//   1 — перед приложением только ваш nginx;
//   2 — CDN, затем ваш nginx;
