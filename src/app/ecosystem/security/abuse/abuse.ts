// ─── ВАРИАНТ 2А. ЖУРНАЛ ОТМЕТОК (sliding window log) ───
// Храним время КАЖДОГО запроса и выбрасываем те, что старше окна.
// Это самый ТОЧНЫЙ способ из всех четырёх.

const requestLog = new Map();   // ключ → массив времён запросов

function slidingLogAllow(key, limit, windowMs) {
  const now = Date.now();
  const cutoff = now - windowMs;   // всё, что раньше этого мгновения, нам не интересно

  const timestamps = requestLog.get(key) ?? [];

  // Выбрасываем протухшие отметки. Массив отсортирован по времени
  // (мы всегда добавляем в конец), поэтому достаточно отрезать начало.
  let firstFresh = 0;
  while (firstFresh < timestamps.length && timestamps[firstFresh] <= cutoff) {
    firstFresh++;
  }
  const fresh = timestamps.slice(firstFresh);

  if (fresh.length >= limit) {
    // Когда освободится место? Когда протухнет самая старая отметка.
    const retryAfterMs = fresh[0] + windowMs - now;
    requestLog.set(key, fresh);
    return { allowed: false, retryAfterMs };
  }

  fresh.push(now);
  requestLog.set(key, fresh);
  return { allowed: true, remaining: limit - fresh.length };
}

// ЦЕНА ТОЧНОСТИ — ПАМЯТЬ. Мы храним по одному числу на КАЖДЫЙ запрос.
// Лимит 1000 запросов в час × 50 000 активных пользователей — это
// 50 миллионов чисел в памяти. Способ отличный для лимита «5 попыток
// входа за 15 минут» и совершенно неподъёмный для «1000 запросов в час».


// ─── ВАРИАНТ 2Б. ВЗВЕШЕННЫЙ СЧЁТЧИК (sliding window counter) ───
// Хитрость, которой пользуются почти все крупные API. Храним ДВА
// числа — счётчик текущего окна и счётчик предыдущего — и берём
// от предыдущего пропорциональную долю.

function slidingCounterAllow(key, limit, windowMs) {
  const now = Date.now();
  const windowId = Math.floor(now / windowMs);

  const currentCount = windowCounters.get(key + ':' + windowId) ?? 0;
  const previousCount = windowCounters.get(key + ':' + (windowId - 1)) ?? 0;

  // Какая доля ТЕКУЩЕГО окна уже прошла: число от 0 до 1.
  const elapsedShare = (now % windowMs) / windowMs;

  // Оценка: весь текущий счётчик плюс «хвост» предыдущего окна,
  // взятый пропорционально тому, сколько его ещё попадает
  // в наши последние windowMs миллисекунд.
  const estimate = currentCount + previousCount * (1 - elapsedShare);

  if (estimate >= limit) {
    return { allowed: false };
  }

  windowCounters.set(key + ':' + windowId, currentCount + 1);
  return { allowed: true, remaining: Math.floor(limit - estimate - 1) };
}

