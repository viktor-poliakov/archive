// 3. РАЗНАЯ ЦЕНА ЗАПРОСОВ ДЕЛАЕТСЯ БЕСПЛАТНО. Обычный запрос забирает
//    1 жетон, тяжёлая выгрузка отчёта — 50. Одно ведро, разная стоимость.
//    Это как раз то, что нужно для «дорогих ручек» (раздел ниже).


// ─── ПРИМЕР НАСТРОЙКИ, ЧТОБЫ ЧИСЛА ОЖИЛИ ───
//
// new TokenBucket(20, 2)  — ёмкость 20, капает 2 в секунду.
//
//   Секунда 0:  ведро полное (20). Приложение делает 12 запросов подряд.
//               Все прошли. Осталось 8 жетонов.
//   Секунда 1:  накапало 2, стало 10. Пришло 3 запроса — прошли. Осталось 7.
//   Секунда 2:  бот начинает молотить по 50 запросов в секунду.
//               Первые 9 проходят (7 в ведре + 2 накапало), остальные 41 — отказ.
//   Секунда 3+: бот получает ровно 2 разрешённых запроса в секунду.
//               Ни одним больше, сколько бы он ни старался.
//
// Обратите внимание, что получилось: живой человек всплеска даже
// не заметил, а бот приведён к скорости капания за одну секунду.


// ═══ СПОСОБ 4. ДЫРЯВОЕ ВЕДРО (leaky bucket) ═══
//
// Похожая посуда, но работает наоборот. Здесь в ведро складываются
// САМИ ЗАПРОСЫ, а из дырки в дне они вытекают с постоянной скоростью
// и обрабатываются. Ведро переполнилось — новые запросы выбрасываются.
//
// АНАЛОГИЯ: воронка. Сколько бы вы ни лили сверху, снизу капает ровно
// столько, сколько пропускает горлышко.

class LeakyBucket {
  constructor(capacity, leakPerSecond, handler) {
    this.capacity = capacity;          // сколько запросов помещается в очередь
    this.leakPerSecond = leakPerSecond; // скорость обработки
    this.handler = handler;            // что делать с вытекшим запросом
    this.queue = [];

    // Здесь фоновая работа НУЖНА — кто-то должен выпускать запросы наружу.
    setInterval(() => this.leak(), 1000 / leakPerSecond);
  }

  offer(request) {
    if (this.queue.length >= this.capacity) {
      // Ведро полное — запрос выбрасываем сразу, не мучая ожиданием.
      return { accepted: false };
    }
    this.queue.push(request);
    return { accepted: true, positionInQueue: this.queue.length };
  }

  leak() {
    const request = this.queue.shift();
    if (request) this.handler(request);
  }
}

