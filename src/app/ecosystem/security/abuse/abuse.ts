const counters = new Map();

function rateLimitMiddleware(req, res, next) {
  const key = req.ip;
  const windowId = Math.floor(Date.now() / 60000);
  const counterKey = key + ':' + windowId;

  const used = counters.get(counterKey) ?? 0;

  if (used >= 100) {
    res.status(429).send('Слишком много запросов');
    return;
  }

  counters.set(counterKey, used + 1);
  next();
}


