// ─────────────────────────────────────────────────────────
// ШАГ 2. NONCE ДЛЯ СВОИХ ВСТРОЕННЫХ СКРИПТОВ
// ─────────────────────────────────────────────────────────
// Генерируем новое случайное значение НА КАЖДЫЙ ОТВЕТ.
