// Проверка на любом изменяющем запросе.
function checkCsrfToken(req, res, next) {
  const expected = req.session.csrfToken;
  const received = req.body.csrfToken || req.headers['x-csrf-token'];

  if (!expected || !received) {
    return res.status(403).json({ error: 'Нет CSRF-токена' });
  }

  // Сравниваем ПОСТОЯННЫМ ПО ВРЕМЕНИ сравнением. Обычное === выходит
  // тем быстрее, чем раньше строки разошлись, и по времени ответа
  // теоретически можно подбирать токен посимвольно. Тут это скорее
  // хорошая привычка, чем острая необходимость, но привычка правильная.
  const a = Buffer.from(String(expected));
  const b = Buffer.from(String(received));
  if (a.length !== b.length || !crypto.timingSafeEqual(a, b)) {
    return res.status(403).json({ error: 'Неверный CSRF-токен' });
  }
  next();
}

