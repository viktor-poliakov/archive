// ─────────────────────────────────────────────────────────
// Типичный список работ, и он всегда длиннее ожидаемого:
//   * атрибуты вроде onclick в разметке -> переносим в addEventListener;
//   * встроенные стили style="..." -> переносим в файл стилей;
//   * eval и new Function -> убираем (иногда прячутся в библиотеках);
