//   1. Значение НОВОЕ на каждый ответ. Одинаковое для всех = дыра.
//   2. Оно случайное и достаточно длинное. Счётчик не годится.
//   3. Страница НЕ КЕШИРУЕТСЯ вместе с заголовком. Если CDN
//      закеширует HTML с одним nonce, а заголовок будет другой —
