  // document.cookie её не покажет. Браузер всё равно приложит её
  // к запросам — но украсть значение чужой скрипт не сможет.
  httpOnly: true,

  // Secure: браузер приложит cookie только к запросу по HTTPS.
  // Без этого флага cookie однажды уедет по открытому каналу.
  secure: true,

  // SameSite: не прикладывать к кросс-сайтовым POST и фреймам.
  // 'lax' — рабочий компромисс: переходы по ссылкам не ломаются.
  sameSite: 'lax',

  // Path: для каких путей действует. '/' — для всего сайта.
  path: '/',

