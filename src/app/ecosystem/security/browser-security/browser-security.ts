//     либо отказываемся от виджета, либо хостим у себя;
//   * шрифты, картинки и обращения к API с других доменов ->
//     перечисляем в соответствующих директивах.
//
// Здесь и выясняется настоящая цена CSP: она заставляет навести
// порядок в том, что грузит ваша страница. Это полезно само по себе,
// но это работа, и её надо запланировать.

// ─────────────────────────────────────────────────────────
// ШАГ 4. ВКЛЮЧАЕМ БОЕВОЙ ЗАГОЛОВОК
// ─────────────────────────────────────────────────────────
// Меняем имя заголовка с Content-Security-Policy-Report-Only
