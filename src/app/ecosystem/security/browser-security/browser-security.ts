// Тогда CORS не нужен вообще, и это самый спокойный вариант.
// Делается на уровне обратного прокси: /api/* уходит на сервер API,
// всё остальное — на статику фронтенда. Снаружи это ОДИН источник
// https://shop.ru, кросс-доменных запросов нет, cookie работают
// без всяких SameSite=None, предварительных запросов не бывает.
//
// ЧЕСТНАЯ ЦЕНА такого решения: прокси надо настроить и поддерживать,
// а фронтенд и API становятся связаны общим доменом — развести их
// потом по разным адресам будет заметно сложнее.

