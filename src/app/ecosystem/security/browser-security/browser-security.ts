//   адресом в списке ответ всё равно зависит от Origin: чужому
//   источнику вы отдаёте ответ без разрешающего заголовка.
// * OPTIONS отвечаем до проверки прав, иначе предварительный запрос
//   будет вечно падать с 401.`;

