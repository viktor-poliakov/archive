// ВАЖНОЕ ПРЕДУПРЕЖДЕНИЕ ПРО ОТЧЁТЫ. Их будет МНОГО, и значительная
// часть — мусор от расширений браузера, антивирусов и провайдеров,
// вставляющих свой код в страницы. Не пытайтесь починить всё подряд:
// отфильтруйте отчёты, где заблокированный адрес — это схема
// расширения браузера, и смотрите только на то, что относится
