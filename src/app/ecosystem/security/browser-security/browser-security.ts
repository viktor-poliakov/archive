function checkRequestSource(req, res, next) {
  // Только изменяющие методы. GET ничего не меняет (см. правило выше).
  const isMutating = ['POST', 'PUT', 'PATCH', 'DELETE'].includes(req.method);
  if (!isMutating) {
    return next();
  }

  // Sec-Fetch-Site — современный заголовок, браузер выставляет его сам.
  // Значения: 'same-origin' (запрос с того же источника),
  // 'same-site' (тот же сайт, другой поддомен), 'cross-site' (чужой сайт),
  // 'none' (пользователь ввёл адрес руками или открыл закладку).
  const fetchSite = req.headers['sec-fetch-site'];
  if (fetchSite === 'cross-site') {
    return res.status(403).json({ error: 'Кросс-доменный изменяющий запрос' });
  }

  // Заголовок Origin как запасной вариант для браузеров постарше.
  const origin = req.headers.origin;
  if (origin && origin !== selfOrigin) {
    return res.status(403).json({ error: 'Чужой Origin' });
  }

  next();
}

