// Что тут не так — сразу четыре вещи:
//   1. Cookie доступна любому скрипту на странице (нет HttpOnly).
//      Одна дыра XSS — и сессия уехала.
//   2. Cookie уедет по обычному http (нет Secure). Любой,
//      кто видит трафик в открытом Wi-Fi, получит пропуск.
//   3. Cookie приложится к запросу с чужого сайта — в браузерах,
