// * Сторонние виджеты — постоянный источник боли и компромиссов.
// * Нужен человек, который смотрит на отчёты, иначе они превращаются
//   в поток, который все игнорируют.
// Взамен: даже пропущенная уязвимость вывода перестаёт быть
