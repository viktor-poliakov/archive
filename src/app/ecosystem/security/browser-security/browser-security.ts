// и понять, что она делает. Значения соответствуют набору
// OWASP Secure Headers Project.

app.use(function securityHeaders(req, res, next) {
  // ─── 1. ТОЛЬКО HTTPS ───
  // Разобран в отдельном разделе. Два года, вместе с поддоменами.
  res.setHeader('Strict-Transport-Security', 'max-age=63072000; includeSubDomains');

  // ─── 2. ПОЛИТИКА БЕЗОПАСНОСТИ СОДЕРЖИМОГО ───
  // Базовый вариант из набора OWASP. Строгий вариант с nonce —
  // в разделе про CSP, он сильнее, но требует работы.
  res.setHeader(
    'Content-Security-Policy',
    "default-src 'self'; form-action 'self'; base-uri 'self'; " +
      "object-src 'none'; frame-ancestors 'none'; upgrade-insecure-requests",
  );

  // ─── 3. НЕ УГАДЫВАТЬ ТИП ФАЙЛА ───
  // Без этого заголовка браузер имеет право «догадаться», что
  // на самом деле лежит в файле, и проигнорировать заявленный тип.
  // Классическая беда: пользователь загружает «картинку», внутри
  // которой на самом деле разметка. Сервер отдаёт её как image/png,
  // браузер приглядывается, решает «да это же HTML» — и выполняет
  // содержимое как страницу на вашем домене.
  // nosniff означает: верь заявленному типу и не умничай.
  res.setHeader('X-Content-Type-Options', 'nosniff');

  // ─── 4. ЧТО СООБЩАТЬ ЧУЖИМ САЙТАМ ОБ ИСТОЧНИКЕ ПЕРЕХОДА ───
  // Когда человек уходит с вашей страницы по ссылке, браузер
  // по умолчанию сообщает чужому сайту, ОТКУДА он пришёл, —
  // вместе с полным адресом. А в адресе бывает лишнее: номер
  // заказа, идентификатор, токен восстановления пароля.
  // 'no-referrer' — не сообщать ничего. Самый строгий вариант
  // из набора OWASP.
  // Мягче: 'strict-origin-when-cross-origin' — своим полный адрес,
  // чужим только имя домена, и ничего при переходе с https на http.
  res.setHeader('Referrer-Policy', 'no-referrer');

  // ─── 5. КАКИЕ ВОЗМОЖНОСТИ БРАУЗЕРА РАЗРЕШЕНЫ СТРАНИЦЕ ───
  // Камера, микрофон, геолокация, доступ к USB, платёжный интерфейс.
  // Пустые скобки означают «никому, включая нас самих». Отключаем
  // всё, чем не пользуемся: это же ограничение подействует
  // и на встроенные чужие фреймы, и на внезапно появившийся
  // чужой код.
  res.setHeader(
    'Permissions-Policy',
    'accelerometer=(), camera=(), geolocation=(), gyroscope=(), ' +
      'magnetometer=(), microphone=(), payment=(), usb=(), serial=()',
  );

  // ─── 6. ЗАЩИТА ОТ ВСТРАИВАНИЯ ВО ФРЕЙМ (КЛИКДЖЕКИНГ) ───
  // Основной механизм — директива frame-ancestors в CSP (см. пункт 2).
  // X-Frame-Options — более старый заголовок с той же задачей.
  // Набор OWASP на сегодня включает ОБА: frame-ancestors как основной
  // механизм и X-Frame-Options как запасной для старых браузеров.
  // Утверждение «X-Frame-Options полностью устарел, его надо убрать»
  // распространено, но текущей практике OWASP не соответствует.
  res.setHeader('X-Frame-Options', 'deny');

  // ─── 7. ИЗОЛЯЦИЯ ОТ ДРУГИХ ВКЛАДОК И ЧУЖИХ СТРАНИЦ ───
  // Cross-Origin-Opener-Policy: страница, открытая по ссылке
  // с вашей, теряет программную связь с вашим окном. Без этого
  // открытая страница может дёргать ваше окно через window.opener.
  res.setHeader('Cross-Origin-Opener-Policy', 'same-origin');

  // Cross-Origin-Resource-Policy: запрещает чужим сайтам подключать
  // ваши файлы к себе (картинки, скрипты, шрифты).
  res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');

  // Cross-Origin-Embedder-Policy: страница соглашается подключать
  // только те чужие ресурсы, которые это явно разрешили.
  // ВНИМАНИЕ: этот заголовок ломает подключение чужих ресурсов,
  // не отдающих нужных разрешений. Включать осознанно и постепенно,
  // как и CSP.
  res.setHeader('Cross-Origin-Embedder-Policy', 'require-corp');

  // ─── 8. НЕ КЕШИРОВАТЬ ЛИЧНЫЕ СТРАНИЦЫ ───
  // Иначе следующий человек за тем же компьютером нажмёт «назад»
  // и увидит чужой личный кабинет.
  //
  // ВАЖНО: этот заголовок, в отличие от предыдущих, нельзя ставить
  // на ВЕСЬ сайт подряд. Картинки, шрифты и файлы сборки кешировать
  // не только можно, но и нужно — иначе сайт будет грузиться медленно
  // у всех и всегда. Поэтому запрет кеширования ставят только
  // на личные страницы и ответы API. Здесь для примера — по адресу.
  if (req.path.startsWith('/api/') || req.path.startsWith('/account')) {
    res.setHeader('Cache-Control', 'no-store, max-age=0');
  }

  // ─── 9. МЕЛОЧИ ИЗ НАБОРА OWASP ───
  res.setHeader('X-DNS-Prefetch-Control', 'off');
  res.setHeader('X-Permitted-Cross-Domain-Policies', 'none');

  next();
});

