app.post('/api/orders', requireLogin, async (req, res) => {
  // От клиента принимаем только «что» и «сколько штук». Больше ничего.
  const requested = req.body.items;

  // Цены берём ИЗ СВОЕЙ БАЗЫ, по идентификаторам товаров.
  const products = await db.products.findByIds(requested.map((i) => i.productId));

  let total = 0;
  const items = [];

  for (const line of requested) {
    const product = products.find((p) => p.id === line.productId);
    if (!product || !product.isActive) {
      return res.status(400).json({ error: 'Товар недоступен' });
    }

    const quantity = Number.parseInt(line.quantity, 10);
    if (!Number.isInteger(quantity) || quantity < 1 || quantity > 99) {
      return res.status(400).json({ error: 'Некорректное количество' });
    }
    if (product.stock < quantity) {
      return res.status(400).json({ error: 'Недостаточно товара на складе' });
    }

    total += product.price * quantity;
    items.push({ productId: product.id, quantity, price: product.price });
  }

  // Скидку тоже считает сервер, по своим правилам.
  const discount = await pricing.calculateDiscount(req.user.id, total);
  const finalTotal = total - discount;

  const order = await db.orders.insert({ userId: req.user.id, items, total: finalTotal });
  await payments.charge(order.id, finalTotal);
  res.json(order);
});


