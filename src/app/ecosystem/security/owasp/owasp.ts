//    пользователя незаметны, а на миллиарде переборов — вечность.
async function register(email, password) {
  // Соль — случайная добавка к каждому паролю. argon2 генерирует её сам
  // и сам кладёт внутрь получившейся строки. Благодаря соли одинаковые
  // пароли двух пользователей дают РАЗНЫЕ хеши.
  const hash = await argon2.hash(password, {
    type: argon2.argon2id,
    memoryCost: 19456, // 19 МБ памяти на одну проверку
    timeCost: 2,
    parallelism: 1,
  });

  await db.users.insert({ email, passwordHash: hash });
}

async function login(email, password) {
  const user = await db.users.findOne({ email });

  // Проверяем всегда, даже если пользователя нет: иначе по времени ответа
  // посторонний поймёт, какие адреса зарегистрированы, а какие нет.
  const dummyHash = '\$argon2id\$v=19\$m=19456,t=2,p=1\$c29tZXNhbHQ\$fake';
  const hash = user ? user.passwordHash : dummyHash;

  const ok = await argon2.verify(hash, password);
  return ok && user ? user : null;
}

// 2. ШИФРОВАНИЕ ДАННЫХ. Готовый алгоритм, случайный вектор инициализации,
//    режим с проверкой целостности. Ключ — из хранилища секретов.
function encrypt(plainText) {
  const key = Buffer.from(process.env.DATA_KEY, 'hex'); // 32 байта
  const iv = crypto.randomBytes(12); // каждый раз НОВЫЙ

  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const encrypted = Buffer.concat([cipher.update(plainText, 'utf8'), cipher.final()]);
  const authTag = cipher.getAuthTag(); // подпись: данные не подменили

  return Buffer.concat([iv, authTag, encrypted]).toString('base64');
}

