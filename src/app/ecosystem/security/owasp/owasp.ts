const dns = require('node:dns').promises;
const net = require('node:net');

const ALLOWED_IMAGE_HOSTS = ['images.example.com', 'cdn.example.org'];

async function isPublicAddress(hostname) {
  // Разрешаем имя в IP-адрес и проверяем, что адрес не внутренний.
  const records = await dns.lookup(hostname, { all: true });

  return records.every((record) => {
    const ip = record.address;

    if (net.isIPv4(ip)) {
      const parts = ip.split('.').map(Number);
      if (parts[0] === 10) return false;                    // 10.0.0.0/8
      if (parts[0] === 127) return false;                   // localhost
      if (parts[0] === 169 && parts[1] === 254) return false; // метаданные
      if (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31) return false;
      if (parts[0] === 192 && parts[1] === 168) return false;
      if (parts[0] === 0) return false;
      return true;
    }

    // Для IPv6 внутренние диапазоны тоже есть — проще запретить IPv6 вовсе,
    // если он вам не нужен, чем перечислять их и ошибиться.
    return false;
  });
}

app.post('/api/profile/avatar', requireLogin, async (req, res) => {
  let url;
  try {
    url = new URL(req.body.imageUrl);
  } catch {
    return res.status(400).json({ error: 'Некорректная ссылка' });
  }

  // 1. Только http и https. Никаких file, ftp, gopher.
  if (url.protocol !== 'https:') {
    return res.status(400).json({ error: 'Разрешены только ссылки https' });
  }

  // 2. Только известные нам хосты.
  if (!ALLOWED_IMAGE_HOSTS.includes(url.hostname)) {
    return res.status(400).json({ error: 'Этот источник картинок не разрешён' });
  }

  // 3. Даже разрешённое имя проверяем на внутренний адрес: злоумышленник
  //    может завести домен, который указывает на 127.0.0.1.
  if (!(await isPublicAddress(url.hostname))) {
    return res.status(400).json({ error: 'Недопустимый адрес' });
  }

  // 4. Не идём по перенаправлениям: первый ответ может увести куда угодно.
  const response = await fetch(url, { redirect: 'error' });

  // 5. Ограничиваем размер и тип, иначе получим бомбу на 4 гигабайта.
  const contentType = response.headers.get('content-type') || '';
  if (!contentType.startsWith('image/')) {
    return res.status(400).json({ error: 'По ссылке не картинка' });
  }

  const buffer = Buffer.from(await response.arrayBuffer());
  if (buffer.length > 5 * 1024 * 1024) {
    return res.status(400).json({ error: 'Картинка слишком большая' });
  }

  await storage.save('avatars/' + req.user.id + '.jpg', buffer);
  res.json({ ok: true });
});

