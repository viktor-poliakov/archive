async function issueSession(res, user, req) {
  // 4. ИДЕНТИФИКАТОР СЕССИИ — СЛУЧАЙНЫЙ, 32 байта энтропии.
  //    Подобрать перебором невозможно, предсказать — тоже.
  const sessionId = crypto.randomBytes(32).toString('base64url');

  // 5. В БАЗЕ ХРАНИМ ХЕШ, а не сам идентификатор: утечка таблицы сессий
  //    тогда не даёт возможности войти.
  await db.sessions.insert({
    idHash: sha256(sessionId),
    userId: user.id,
    createdAt: Date.now(),
    expiresAt: Date.now() + 14 * 24 * 60 * 60 * 1000, // 14 дней
    ip: req.ip,
    userAgent: req.get('user-agent'),
  });

  // 6. ФЛАГИ COOKIE. Каждый закрывает свой класс проблем:
  res.cookie('sid', sessionId, {
    httpOnly: true,  // JavaScript страницы не может её прочитать — щит от XSS
    secure: true,    // отправляется только по https
    sameSite: 'lax', // не уходит на чужие сайты — щит от подделки запросов
    maxAge: 14 * 24 * 60 * 60 * 1000,
    path: '/',
  });
}

