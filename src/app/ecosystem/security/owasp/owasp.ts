function shutdownGracefully(code) {
  // Перестаём принимать новые запросы, даём завершиться текущим,
  // закрываем соединения с базой — и только потом выходим.
  server.close(() => {
    db.close().finally(() => process.exit(code));
  });
  setTimeout(() => process.exit(code), 10000).unref();
}

// 4. ЧАСТИЧНО ВЫПОЛНЕННАЯ ОПЕРАЦИЯ — ЭТО ТОЖЕ ИСКЛЮЧИТЕЛЬНАЯ СИТУАЦИЯ.
//    Классический пример: списали с одного счёта, а зачислить
//    на второй не успели. Лекарство — транзакция: либо всё, либо ничего.
async function transfer(fromId, toId, amount) {
  return db.transaction(async (trx) => {
    const from = await trx.wallets.findForUpdate(fromId);

    if (from.balance < amount) {
      // Бросаем ошибку ВНУТРИ транзакции — она откатится целиком.
      throw new UserFacingError('Недостаточно средств', 400, 'insufficient_funds');
    }

    await trx.wallets.decrement(fromId, amount);
    await trx.wallets.increment(toId, amount);
    await trx.transfers.insert({ fromId, toId, amount, at: new Date() });
  });
}

