class UserFacingError extends Error {
  constructor(message, statusCode = 400, code = 'bad_request') {
    super(message);
    this.statusCode = statusCode;
    this.code = code;
    this.isUserFacing = true; // явная пометка: это сообщение безопасно
  }
}

// Пример осмысленной ошибки для пользователя.
function parseQuantity(raw) {
  const quantity = Number.parseInt(raw, 10);
  if (!Number.isInteger(quantity) || quantity < 1 || quantity > 99) {
    throw new UserFacingError('Количество должно быть числом от 1 до 99');
  }
  return quantity;
}

// 2. Один общий обработчик ошибок в конце цепочки. Он и решает,
//    что показать. Правило умолчания: НЕ ПОКАЗЫВАТЬ.
app.use((error, req, res, next) => {
  const incidentId = crypto.randomUUID();

  // Полная картина уходит в журнал — там она нужна и там она в безопасности.
  logger.error({
    incidentId,
    event: 'request.failed',
    message: error.message,
    stack: error.stack,
    userId: req.user ? req.user.id : null,
    method: req.method,
    path: req.path,
    requestId: req.id,
  });

  if (error.isUserFacing) {
    return res.status(error.statusCode).json({
      error: error.message,
      code: error.code,
      incidentId,
    });
  }

  // Всё, что мы не пометили как безопасное, наружу уходит одинаково.
  res.status(500).json({
    error: 'Внутренняя ошибка сервера',
    incidentId, // по нему поддержка найдёт полную запись
  });
});

