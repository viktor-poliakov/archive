// без всякой защиты от перебора. Робот, который перебирает пароли
// круглосуточно, попадёт в это окно обязательно: он не спит.

// ═══ ЗДОРОВЫЙ КОД ═══
async function checkRateLimit(key, limit, windowSeconds) {
  try {
    const count = await redis.incr(key);
    if (count === 1) await redis.expire(key, windowSeconds);
    return { allowed: count <= limit, degraded: false };
  } catch (error) {
    logger.error({ event: 'ratelimit.store.unavailable', key, error: error.message });
    metrics.increment('ratelimit.store.failed');

    // Запасной счётчик в памяти процесса. Он хуже общего: у каждого
    // сервера свой, при перезапуске обнуляется. Но «хуже» — это
    // не «никак», и на время сбоя этого достаточно.
    const localCount = memoryCounter.increment(key, windowSeconds);

    return {
      allowed: localCount <= Math.max(1, Math.floor(limit / 2)),
      degraded: true, // помечаем, что работаем в ослабленном режиме
    };
  }
}

