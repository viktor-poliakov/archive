//   Он мешает менеджерам паролей (те генерируют длинные строки) и убивает
//   парольные фразы. А ещё «максимум 20» — почти всегда признак того, что
//   пароль кладут в столбец VARCHAR(20), то есть хранят его КАК ЕСТЬ.
//   Хеш-то всегда одной длины, ему верхний предел не нужен.
//
// БЕДА 3. ПРИНУДИТЕЛЬНАЯ СМЕНА КАЖДЫЕ 90 ДНЕЙ ДЕЛАЕТ ХУЖЕ.
//   Человек не придумывает двенадцать хороших паролей в год. Он делает
//   'Korova1!' → 'Korova2!' → 'Korova3!' и пишет текущий на бумажке.
//   NIST прямо запрещает такое требование: менять пароль принудительно
//   следует ТОЛЬКО при свидетельстве компрометации.

// ─── ЗДОРОВАЯ ПРОВЕРКА ───
async function validatePassword(password, email) {
  // 1. ДЛИНА. По NIST SP 800-63B-4: минимум 15 символов, если пароль —
  //    единственный фактор; минимум 8 — если он один из факторов MFA.
  //    Ставьте 15, если второго фактора у вас нет.
  if (password.length < 15) {
    return 'Пароль должен быть не короче 15 символов. Проще всего взять фразу из нескольких слов';
  }

  // 2. ВЕРХНИЙ ПРЕДЕЛ — ЩЕДРЫЙ. NIST: разрешать не менее 64 символов.
  //    Ограничение всё же нужно, но не ради «правил», а чтобы никто
  //    не прислал мегабайт текста и не занял ваш процессор на минуту.
  if (password.length > 256) {
    return 'Слишком длинный пароль';
  }

  // 3. НИКАКИХ ПРАВИЛ СОСТАВА. NIST говорит «SHALL NOT»: не навязывать
  //    смесь регистров, цифр и спецсимволов. Ни одной проверки regexp.

  // 4. ЗАПРЕТ НА ИЗВЕСТНЫЕ И УТЁКШИЕ ПАРОЛИ. Это NIST предписывает (SHALL) —
  //    и это единственная проверка, которая реально что-то даёт.
  if (await isPasswordBreached(password)) {
    return 'Этот пароль встречается в известных утечках. Придумайте другой';
  }

  // 5. Заодно — очевидные производные от самого сервиса и адреса почты.
  const local = email.split('@')[0].toLowerCase();
  const lower = password.toLowerCase();
  if (local.length >= 4 && lower.includes(local)) {
    return 'Пароль не должен содержать ваш адрес почты';
  }
  if (lower.includes('shop') || lower.includes('магазин')) {
    return 'Пароль не должен содержать название сервиса';
  }

  return null;
}

