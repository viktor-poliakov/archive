// Часы на телефоне и на сервере никогда не совпадают идеально.
// Плюс человек видит код, тянется к клавиатуре, печатает — уходят секунды.
// Плюс код мог смениться ровно между «посмотрел» и «нажал Enter».
// Поэтому проверяют не одно окно, а несколько соседних.

function verifyTotp(secret, code, window = 1) {
  const now = Date.now();
  // window = 1 означает: предыдущее окно, текущее и следующее.
  // Итого допуск ±30 секунд, а всего кодов действительно три.
  for (let i = -window; i <= window; i++) {
    const candidate = generateTotp(secret, 30, now + i * 30 * 1000);
    // Сравнение за постоянное время: код — короткий секрет,
    // посимвольный подбор по времени тут теоретически возможен.
    if (safeEqual(candidate, String(code))) return true;
  }
  return false;
}

