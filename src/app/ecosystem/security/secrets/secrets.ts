// Обычное сравнение строк оператором === останавливается на первом
// несовпавшем символе. Значит, время сравнения зависит от того,
// сколько символов совпало, — и по этому времени можно подбирать
// секрет посимвольно. Для ХЕША ПАРОЛЯ это неважно (его всё равно
// нельзя подобрать по кусочкам), поэтому argon2.verify и bcrypt.compare
// вы просто вызываете и не думаете — внутри уже всё сделано правильно.
//
// А вот там, где вы сравниваете СЫРЫЕ СЕКРЕТЫ САМИ — токен сброса пароля,
// ключ API, подпись вебхука — надо явно брать сравнение за постоянное время:

function safeEqual(a, b) {
  const bufA = Buffer.from(a, 'utf8');
  const bufB = Buffer.from(b, 'utf8');
  // timingSafeEqual требует одинаковой длины и бросает исключение при разной.
  // Поэтому сначала сравниваем длины — она секретом не является.
  if (bufA.length !== bufB.length) return false;
  return crypto.timingSafeEqual(bufA, bufB);
}

