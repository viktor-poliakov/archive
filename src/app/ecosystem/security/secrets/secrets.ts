const redis = require('./redis');

async function checkLoginRateLimit(email, ip) {
  const now = Date.now();

  // СЧЁТЧИК 1. По аккаунту. Ловит перебор одного человека.
  const perAccount = await redis.incr('login:acct:' + email);
  if (perAccount === 1) await redis.expire('login:acct:' + email, 900); // окно 15 минут

  // СЧЁТЧИК 2. По адресу. Ловит массовый перебор с одной машины.
  const perIp = await redis.incr('login:ip:' + ip);
  if (perIp === 1) await redis.expire('login:ip:' + ip, 900);

  // СЧЁТЧИК 3. Глобальный. Ловит распределённую подстановку: с каждого
  // адреса по одной попытке, но всего их вдруг в двадцать раз больше нормы.
  const globalFails = await redis.get('login:fails:global');
  if (Number(globalFails) > GLOBAL_ALERT_THRESHOLD) {
    // Не блокируем всех — включаем повышенную осторожность: капчу
    // для новых устройств, подтверждение почтой при входе с нового IP.
    await enableHeightenedMode();
  }

  // НАРАСТАЮЩАЯ ЗАДЕРЖКА вместо блокировки. После каждой неудачи
  // ждать приходится дольше: 0, 1, 2, 4, 8, 16... секунд.
  // Человеку, который опечатался дважды, это почти незаметно.
  // Скрипту, которому нужны тысячи попыток, это ставит крест на затее.
  if (perAccount > 3) {
    const delaySeconds = Math.min(2 ** (perAccount - 3), 30);
    await sleep(delaySeconds * 1000);
  }

  return perAccount > 20 || perIp > 100;
}

