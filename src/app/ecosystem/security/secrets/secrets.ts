// ШАГ 1. ОДИН РАЗ, ПРИ ПОДКЛЮЧЕНИИ. Сервер придумывает случайный
//   СЕКРЕТ (обычно 20 байт) и показывает его в виде QR-кода.
//   Телефон считывает и сохраняет. Теперь ОДИН И ТОТ ЖЕ секрет
//   есть в двух местах: у вас на сервере и в телефоне человека.
//   Больше он никуда не передаётся НИКОГДА.
//
// ШАГ 2. КАЖДЫЕ ТРИДЦАТЬ СЕКУНД. И телефон, и сервер независимо
//   выполняют одно и то же вычисление:
//
//       код = функция(общий секрет, текущее время / 30)
//
//   Оба берут текущее время, делят на 30 и отбрасывают дробную часть.
//   Получается «номер получаса с 1 января 1970 года» — одинаковое
//   число у обоих. Дальше от пары «секрет + это число» считается
//   HMAC, из результата вырезаются шесть цифр.
//
//   ВОТ ПОЧЕМУ КОДЫ СОВПАДАЮТ: не потому, что телефон куда-то ходит
//   (он работает и в самолётном режиме), а потому, что оба считают
//   одно и то же от одних и тех же исходных данных.
//   Часы — единственный «канал связи» между ними.

const crypto = require('node:crypto');

function generateTotp(secret, timeStep = 30, at = Date.now()) {
  // 1. Номер текущего временного окна.
  const counter = Math.floor(at / 1000 / timeStep);

  // 2. Кладём его в 8 байт, старший разряд первым.
  const buf = Buffer.alloc(8);
  buf.writeBigUInt64BE(BigInt(counter));

  // 3. HMAC-SHA1 от этого числа с общим секретом в качестве ключа.
  //    SHA-1 здесь — часть стандарта (RFC 6238) и это не проблема:
  //    для HMAC его известные слабости не применимы.
  const hmac = crypto.createHmac('sha1', secret).update(buf).digest();

  // 4. «Динамическое усечение»: последние 4 бита говорят, откуда
  //    брать 4 байта результата. Так код зависит от всего HMAC целиком.
  const offset = hmac[hmac.length - 1] & 0x0f;
  const binary =
    ((hmac[offset] & 0x7f) << 24) |
    ((hmac[offset + 1] & 0xff) << 16) |
    ((hmac[offset + 2] & 0xff) << 8) |
    (hmac[offset + 3] & 0xff);

  // 5. Остаток от деления на миллион — вот и шесть цифр.
  return String(binary % 1000000).padStart(6, '0');
}

