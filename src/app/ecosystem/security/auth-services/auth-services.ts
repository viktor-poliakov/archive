import argon2 from 'argon2';

export async function hashPassword(password) {
  // argon2id — сегодняшний рекомендуемый выбор.
  // Все параметры уже подобраны авторами библиотеки; трогать их
  // без понимания не надо, а понимание требует отдельного изучения.
  return argon2.hash(password, { type: argon2.argon2id });
}

export async function checkPassword(hash, password) {
  // Проверка тоже готовая: внутри сравнение за постоянное время,
  // чтобы по скорости ответа нельзя было подбирать хеш посимвольно.
  return argon2.verify(hash, password);
}

