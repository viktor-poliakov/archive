// Грубая прикидка на своих данных (запустите у себя до подключения):
function estimateBilledMau(events) {
  // events — ваш журнал: { userId, type, at }
  // type: 'login' | 'token_refresh' | 'page_view'

  const productActive = new Set();  // как считает ваша аналитика
  const providerActive = new Set(); // как посчитает провайдер

  for (const e of events) {
    if (e.type === 'page_view' || e.type === 'login') {
      productActive.add(e.userId);
    }
    // А провайдер видит ЕЩЁ и фоновые продления.
    if (e.type === 'login' || e.type === 'token_refresh') {
      providerActive.add(e.userId);
    }
  }

  return {
    product: productActive.size,
    provider: providerActive.size,
    // Вот этот коэффициент и надо заложить в бюджет.
    ratio: providerActive.size / Math.max(productActive.size, 1),
  };
}

// ─── MRU: ЧЕСТНАЯ ВАРИАЦИЯ ТОЙ ЖЕ ИДЕИ ───
// Clerk считает не MAU, а MRU (monthly retained user) — «удержанный».
// Правило простое: пользователь попадает в счёт, только если ВЕРНУЛСЯ
// в приложение не раньше чем через 24 часа после регистрации.
//
// Что это меняет на практике:
//   * человек зарегистрировался, посмотрел и ушёл навсегда — БЕСПЛАТНО;
//   * бот наплодил тысячу учёток за ночь — БЕСПЛАТНО (боты не возвращаются);
//   * настоящий пользователь, который живёт в приложении — платно.
// Для продукта с широкой воронкой и слабым удержанием разница
// с обычным MAU получается кратной. Для зрелого продукта — почти нулевой.

function isBilledAsMru(signedUpAt, lastSeenAt) {
  const DAY_MS = 24 * 60 * 60 * 1000;
  return lastSeenAt.getTime() - signedUpAt.getTime() >= DAY_MS;
}

