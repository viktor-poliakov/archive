// ═══ ЗДОРОВЫЙ КОД. Основание фиксируется вместе с данными ═══

async function registerUser(req, res) {
  const { email, phone, name } = req.body;

  // 1. Данные, без которых магазин не выполнит заказ.
  //    Основание — договор. Согласие тут не нужно и даже вредно.
  const userId = await db.users.insert({
    email,
    phone,
    name,
    processing_basis: LEGAL_BASIS.CONTRACT,
    purpose: 'orders',          // цель — одна, конкретная, записанная
    collected_at: new Date(),
  });

  // 2. Всё, что сверх этого, — только по отдельному согласию,
  //    и каждое согласие сохраняется отдельной строкой.
  if (req.body.consentMarketing === true) {
    await db.consents.insert({
      user_id: userId,
      purpose: 'marketing_email',        // ровно одна цель
      text_version: 'consent-marketing-v4', // какой текст человек видел
      granted_at: new Date(),
      source: 'signup_form',
      ip: req.ip,                        // доказательство, что это был он
      revoked_at: null,
    });
    await marketing.subscribe(email);
  }

  // 3. Передача в рекламную сеть — ещё одна цель и ещё одно согласие.
  //    Не отметил — не передаём. Никаких «ну это же почти то же самое».
  if (req.body.consentAds === true) {
    await db.consents.insert({
      user_id: userId,
      purpose: 'ads_audience_upload',
      text_version: 'consent-ads-v2',
      granted_at: new Date(),
      source: 'signup_form',
      ip: req.ip,
      revoked_at: null,
    });
  }

  res.json({ ok: true });
}

