// ─── УРОВЕНЬ 3. ОТДЕЛЬНОЕ ПОЛЕ ───
// Что защищает: одно конкретное значение, даже внутри работающей базы.
// От кого: от всех, у кого нет ключа, — включая администратора базы,
//   включая ваше собственное приложение, если ему ключ не выдан.
// Аналогия: в сейфе стоит ещё одна шкатулка, и ключ от неё —
//   у другого человека.

const crypto = require('crypto');

// Ключ приходит из менеджера секретов, а НЕ из кода и НЕ из базы.
// Класть ключ рядом с зашифрованными данными — это как приклеить
// ключ от квартиры к двери снаружи.
function getKey(version) {
  const raw = process.env['FIELD_KEY_V' + version];
  if (!raw) throw new Error('Нет ключа версии ' + version);
  return Buffer.from(raw, 'base64'); // 32 байта для AES-256
}

const CURRENT_KEY_VERSION = 3;

function encryptField(plaintext) {
  const key = getKey(CURRENT_KEY_VERSION);
  // Случайный вектор инициализации на КАЖДОЕ шифрование.
  // Повторно использовать его нельзя — это ломает всю защиту.
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const enc = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()]);
  const tag = cipher.getAuthTag(); // подпись: данные не подменили

  // Версию ключа храним рядом — иначе после смены ключа старые записи
  // расшифровать будет нечем. Это самая частая ошибка при ротации.
  return { v: CURRENT_KEY_VERSION, iv, tag, data: enc };
}

function decryptField(record) {
  const key = getKey(record.v);
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, record.iv);
  decipher.setAuthTag(record.tag);
  return Buffer.concat([decipher.update(record.data), decipher.final()]).toString('utf8');
}

