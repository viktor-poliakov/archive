//   Сменить ключ = перешифровать все записи. На большой таблице это
//   отдельная фоновая задача на дни. Отсюда и поле с версией ключа:
//   оно позволяет жить с двумя ключами одновременно, пока идёт перешифровка.

// НЕУДОБСТВО 4. ПОТЕРЯЛИ КЛЮЧ — ПОТЕРЯЛИ ДАННЫЕ.
//   Не «долго восстанавливать», а именно потеряли, окончательно.
//   Это уже вопрос не безопасности, а надёжности: у ключа должна быть
//   резервная копия, хранящаяся отдельно и надёжнее самих данных.

// ВЫВОД: третий уровень применяют ТОЧЕЧНО — к нескольким полям,
