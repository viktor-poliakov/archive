// ═══ ХЕШИРОВАНИЕ: КОГДА ВОССТАНАВЛИВАТЬ ЗНАЧЕНИЕ НЕ НУЖНО ═══
// Шифрование обратимо (есть ключ — есть исходник). Хеш — нет:
// из хеша исходное значение не достать. И это часто именно то, что нужно.

// СЛУЧАЙ 1. ПАРОЛИ. Вам никогда не нужно знать пароль пользователя —
// нужно лишь проверить, что он ввёл тот же самый. Поэтому пароли
// не шифруют, а хешируют специальным медленным алгоритмом.
// Рекомендация OWASP — Argon2id; минимальная конфигурация из их
// шпаргалки: m=19456 (19 МиБ), t=2, p=1. Для bcrypt — рабочий фактор
// от 10 и выше, с ограничением входа в 72 байта.
// Подробный разбор — на предыдущей странице про пароли и секреты.

// СЛУЧАЙ 2. ПРОВЕРКА «ЭТОТ ЖЕ ЧЕЛОВЕК ИЛИ НЕТ» БЕЗ ХРАНЕНИЯ ДАННЫХ.
// Например, нужно понять, что почта уже участвовала в акции,
// но саму почту хранить не хочется.
function blindIndex(value, pepper) {
  // Нормализация обязательна: 'M.Ivanova@Example.com ' и
  // 'm.ivanova@example.com' должны дать одинаковый результат.
  const normalized = String(value).trim().toLowerCase();
  // Секретная добавка (pepper) лежит в менеджере секретов.
  // Без неё хеш почты подбирается перебором за минуты:
  // адресов в мире много, но не бесконечно.
  return crypto.createHmac('sha256', pepper).update(normalized).digest('hex');
}

