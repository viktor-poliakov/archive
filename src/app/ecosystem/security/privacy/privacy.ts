// ═══ ЗДОРОВЫЙ КОД. Логгер, который маскирует сам ═══
// Принцип тот же, что с согласием: не заставлять человека помнить,
// а сделать так, чтобы неправильное было трудно сделать.

// 1. Список полей, которые вырезаются всегда, на любой глубине.
const SECRET_KEYS = new Set([
  'password', 'pass', 'pwd', 'currentpassword', 'newpassword',
  'token', 'accesstoken', 'refreshtoken', 'idtoken', 'jwt',
  'authorization', 'cookie', 'setcookie', 'apikey', 'secret',
  'otp', 'code', 'smscode', 'pin',
  'cardnumber', 'pan', 'cvv', 'cvc', 'expiry',
]);

// 2. Поля, которые не вырезаются, а маскируются частично —
//    чтобы по журналу всё-таки можно было разбирать инциденты.
const PARTIAL_KEYS = new Set(['email', 'phone', 'ip', 'address']);

function maskEmail(value) {
  // m.ivanova@example.com → m*******@example.com
  const at = value.indexOf('@');
  if (at < 1) return '***';
  return value[0] + '*'.repeat(Math.max(1, at - 1)) + value.slice(at);
}

function maskPhone(value) {
  // +79161234567 → +7916***4567 (хвост нужен, чтобы узнать клиента в тикете)
  const digits = value.replace(/\\D/g, '');
  if (digits.length < 7) return '***';
  return digits.slice(0, 4) + '***' + digits.slice(-4);
}

function maskIp(value) {
  // 95.108.213.44 → 95.108.213.0 — сеть видно, конкретного человека нет.
  const parts = value.split('.');
  return parts.length === 4 ? parts[0] + '.' + parts[1] + '.' + parts[2] + '.0' : '***';
}

// 3. Рекурсивный обход. Секреты прячутся глубоко: в теле запроса,
//    внутри объекта ошибки, внутри вложенного ответа внешнего сервиса.
function sanitize(value, depth = 0) {
  // Защита от бесконечной вложенности и циклических ссылок.
  if (depth > 6) return '[too deep]';
  if (value === null || value === undefined) return value;

  if (Array.isArray(value)) {
    return value.slice(0, 50).map((v) => sanitize(v, depth + 1));
  }

  if (typeof value === 'string') {
    // Отдельная страховка: строка, похожая на номер карты или на токен,
    // вырезается, даже если поле называется безобидно (например, 'note').
    if (/\\b\\d{13,19}\\b/.test(value.replace(/[ -]/g, ''))) return '[redacted:pan]';
    if (/^(Bearer|Basic)\\s/i.test(value)) return '[redacted:auth]';
    if (value.length > 2000) return value.slice(0, 2000) + '…[truncated]';
    return value;
  }

  if (typeof value !== 'object') return value;

  const out = {};
  for (const [key, val] of Object.entries(value)) {
    const k = key.toLowerCase().replace(/[_-]/g, '');

    if (SECRET_KEYS.has(k)) {
      out[key] = '[redacted]';           // полностью, без вариантов
      continue;
    }

    if (PARTIAL_KEYS.has(k) && typeof val === 'string') {
      if (k === 'email') out[key] = maskEmail(val);
      else if (k === 'phone') out[key] = maskPhone(val);
      else if (k === 'ip') out[key] = maskIp(val);
      else out[key] = '[masked]';
      continue;
    }

    out[key] = sanitize(val, depth + 1);
  }
  return out;
}

// 4. Обёртка над журналом. Прямой console.log в проекте запрещаем
//    правилом линтера — тогда мимо маскирования пройти нельзя.
const logger = {
  info: (msg, ctx) => write('info', msg, ctx),
  warn: (msg, ctx) => write('warn', msg, ctx),
  error: (msg, ctx) => write('error', msg, ctx),
};

function write(level, msg, ctx) {
  const line = {
    level,
    msg,
    at: new Date().toISOString(),
    // Идентификатор запроса — чтобы связать строки между собой
    // БЕЗ персональных данных в каждой строке.
    requestId: currentRequestId(),
    ...sanitize(ctx ?? {}),
  };
  process.stdout.write(JSON.stringify(line) + '\\n');
}

