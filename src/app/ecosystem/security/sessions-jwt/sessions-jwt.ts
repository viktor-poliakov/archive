app.post('/api/token/refresh', async (req, res) => {
  // Refresh-токен лежит в отдельной cookie с УЗКИМ путём: браузер
  // приложит её только к этому адресу и никуда больше.
  //
  // ПОЧЕМУ ИМЯ НАЧИНАЕТСЯ С __Secure-, А НЕ С __Host-. Выше, для
  // сессии, мы брали префикс __Host- — он строже. Но он требует
  // Path=/, то есть «прикладывать ко всему сайту», а нам нужно ровно
  // обратное: узкий путь. Совместить нельзя, поэтому здесь берём
  // __Secure-: он требует только атрибут Secure (то есть HTTPS)
  // и позволяет любой Path. Если бы мы назвали эту cookie __Host-rt
  // и оставили узкий Path, браузер просто отказался бы её сохранять —
  // и обновление токенов не работало бы вообще.
  const presented = req.cookies['__Secure-rt'];
  if (!presented) return res.status(401).json({ error: 'Требуется вход' });

  const tokenHash = crypto.createHash('sha256').update(presented).digest('hex');
  const record = await db.refreshTokens.findByHash(tokenHash);

  if (!record) return res.status(401).json({ error: 'Требуется вход' });
  if (record.expiresAt < new Date()) return res.status(401).json({ error: 'Требуется вход' });

  // ═══ ОБНАРУЖЕНИЕ ПОВТОРНОГО ИСПОЛЬЗОВАНИЯ ═══
  // Вот ради чего вся конструкция.
  //
  // Каждый refresh-токен одноразовый: использовали — пометили как
  // использованный и выдали новый. Значит, если кто-то ПОВТОРНО
  // предъявляет уже использованный токен, случилось одно из двух:
  //   * токен украли, и вор идёт по следам настоящего пользователя;
  //   * либо настоящий пользователь идёт по следам вора.
  // Разобрать, кто есть кто, невозможно. Поэтому поступаем жёстко:
  // ОБРУШИВАЕМ ВСЁ СЕМЕЙСТВО. Оба — и вор, и пользователь — оказываются
  // выброшенными. Пользователь просто войдёт заново, а вор без пароля
  // сделать этого не сможет.
  if (record.usedAt !== null) {
    await db.refreshTokens.revokeFamily(record.familyId);
    await notifyUser(record.userId, 'Вход в аккаунт с нового устройства — проверьте, вы ли это');
    return res.status(401).json({ error: 'Сессия завершена по соображениям безопасности' });
  }

  // Обычный путь: помечаем предъявленный токен использованным
  // и выдаём новую пару в том же семействе.
  await db.refreshTokens.markUsed(tokenHash);

  const user = await db.users.findById(record.userId);
  // Проверяем пользователя ЗАНОВО — вдруг его заблокировали или
  // поменяли роль, пока действовал старый токен. Это и есть тот
  // момент, когда изменение прав наконец доезжает до токенов.
  if (!user || user.isBlocked) {
    await db.refreshTokens.revokeFamily(record.familyId);
    return res.status(401).json({ error: 'Учётная запись недоступна' });
  }

  const pair = await issueTokenPair(user, record.familyId);

  res.cookie('__Secure-rt', pair.refreshToken, {
    httpOnly: true,
    secure: true,                 // обязательно: этого требует префикс __Secure-
    sameSite: 'strict',
    path: '/api/token/refresh',   // УЗКИЙ путь: браузер шлёт только сюда
    maxAge: REFRESH_TTL_DAYS * 24 * 60 * 60 * 1000,
  });

  res.json({ accessToken: pair.accessToken, expiresIn: 900 });
});

// ─── КАК ЭТО ВЫГЛЯДИТ СО СТОРОНЫ КЛИЕНТА ───────────────────────────
// Клиент не следит за временем. Он просто идёт в API, а когда получает
// 401 с признаком «токен истёк» — обновляется и повторяет запрос.

let accessToken = null;
let refreshPromise = null;   // защита от десяти обновлений сразу

async function apiFetch(url, options = {}) {
  const withAuth = (t) => ({
    ...options,
    headers: { ...options.headers, Authorization: 'Bearer ' + t },
    credentials: 'include',
  });

  let response = await fetch(url, withAuth(accessToken));
  if (response.status !== 401) return response;

  // ВАЖНАЯ ДЕТАЛЬ. Если страница отправила десять запросов разом,
  // все десять получат 401 одновременно. Без этой защиты они начнут
  // десять параллельных обновлений — и девять из них принесут
  // «повторное использование», обрушив семейство. Пользователя выкинет
  // на ровном месте. Поэтому обновление всегда ровно одно.
  if (!refreshPromise) {
    refreshPromise = fetch('/api/token/refresh', { method: 'POST', credentials: 'include' })
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error('refresh_failed'))))
      .then((data) => { accessToken = data.accessToken; })
      .finally(() => { refreshPromise = null; });
  }

  try {
    await refreshPromise;
  } catch {
    window.location.href = '/login';       // обновиться не вышло — вход заново
    return response;
  }

  return fetch(url, withAuth(accessToken));   // повтор с новым токеном
}

