// Сервер проверяет совпадение:
function requireCsrf(req, res, next) {
  // Безопасные методы не меняют данные — их не проверяем.
  if (['GET', 'HEAD', 'OPTIONS'].includes(req.method)) return next();

  const fromCookie = req.cookies['csrf'];
  const fromHeader = req.get('x-csrf-token');
  if (!fromCookie || !fromHeader || fromCookie !== fromHeader) {
    return res.status(403).json({ error: 'Проверка CSRF не пройдена' });
  }
  next();
}

