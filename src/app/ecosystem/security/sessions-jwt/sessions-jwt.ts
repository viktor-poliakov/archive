async function revokeToken(payload) {
  // Срок жизни записи в списке = остаток жизни токена.
  // Дольше держать бессмысленно: токен и так протухнет.
  const secondsLeft = payload.exp - Math.floor(Date.now() / 1000);
  if (secondsLeft > 0) {
    await redis.set('revoked:' + payload.jti, '1', 'EX', secondsLeft);
  }
}

