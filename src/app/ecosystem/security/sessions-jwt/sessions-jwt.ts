// TTL (time to live, «время жизни») — так называют срок, после которого
// запись исчезает сама. Это слово встретится ещё много раз.
const SESSION_TTL_SECONDS = 60 * 60 * 24 * 14;

// ─── ШАГ 1. ВЫДАЧА НОМЕРКА ПРИ ВХОДЕ ───────────────────────────────

app.post('/api/login', async (req, res) => {
  const user = await findUserByEmail(req.body.email);

  // Пароль сверяем медленной функцией (bcrypt/argon2). Ответ при ошибке
  // одинаковый для «нет такого пользователя» и «неверный пароль» —
  // иначе форма входа превращается в справочник, кто у нас зарегистрирован.
  if (!user || !(await verifyPassword(req.body.password, user.passwordHash))) {
    return res.status(401).json({ error: 'Неверная почта или пароль' });
  }

  // ВОТ ОН, НОМЕРОК. 32 случайных байта из криптографического источника.
  // randomBytes — не тот же генератор, что Math.random(): он берёт
  // случайность у операционной системы и предназначен именно для секретов.
  // base64url — способ записать байты буквами, безопасными для адресов
  // и заголовков (без символов +, / и = на конце).
  const sessionId = crypto.randomBytes(32).toString('base64url');

  // Всё содержимое сессии остаётся НА СЕРВЕРЕ.
  const session = {
    userId: user.id,
    role: user.role,
    createdAt: Date.now(),
    // Полезно для страницы «мои устройства» и для расследования инцидентов.
    userAgent: req.get('user-agent') || '',
    ip: req.ip,
  };

  // Пишем в Redis со сроком жизни. Аргумент 'EX' — срок в секундах.
  // Ключ протухнет сам: чистить старые сессии вручную не придётся.
  await redis.set('sess:' + sessionId, JSON.stringify(session), 'EX', SESSION_TTL_SECONDS);

  // Заодно ведём список сессий этого человека — понадобится для кнопки
  // «выйти со всех устройств» ниже на странице. Без такого списка сессии
  // пришлось бы искать перебором по всем ключам Redis, а это тяжёлая
  // операция, которая на живом сервере задерживает всех остальных.
  await redis.sadd('user-sessions:' + user.id, sessionId);
  await redis.expire('user-sessions:' + user.id, SESSION_TTL_SECONDS);

  // Отдаём номерок браузеру. Набор атрибутов здесь не украшение —
  // каждый закрывает свою дыру, разбор был в предыдущем примере.
  res.cookie('__Host-sid', sessionId, {
    httpOnly: true,                        // скрипт не прочитает
    secure: true,                          // только по HTTPS
    sameSite: 'lax',                       // не поедет по чужим запросам
    path: '/',                             // требование префикса __Host-
    maxAge: SESSION_TTL_SECONDS * 1000,    // здесь миллисекунды, не секунды
  });

  res.json({ ok: true, name: user.name });
});

// ─── ШАГ 2. ЧТЕНИЕ СЕССИИ НА КАЖДОМ ЗАПРОСЕ ────────────────────────
// Это промежуточный обработчик: он выполняется перед всеми остальными
// и превращает строку из cookie в объект пользователя.

async function loadSession(req, res, next) {
  const sessionId = req.cookies['__Host-sid'];
  if (!sessionId) return next();          // гость, просто идём дальше

  const raw = await redis.get('sess:' + sessionId);
  if (!raw) return next();                // номерок есть, а сессии нет:
                                          // истекла или её удалили при выходе

  const session = JSON.parse(raw);
  req.session = session;

  // СКОЛЬЗЯЩИЙ СРОК. Пользователь активен — продлеваем сессию.
  // Без этого человека выкинет ровно через 14 суток после входа,
  // даже если он пользуется сайтом каждый день.
  await redis.expire('sess:' + sessionId, SESSION_TTL_SECONDS);

  next();
}
