const crypto = require('node:crypto');
const jwt = require('jsonwebtoken');

const ACCESS_TTL = '15m';
const REFRESH_TTL_DAYS = 30;

// ─── ВЫДАЧА ПАРЫ ПРИ ВХОДЕ ─────────────────────────────────────────

async function issueTokenPair(user, familyId) {
  // ACCESS. Обычный подписанный JWT. В базу не пишется — в этом идея.
  const accessToken = jwt.sign(
    { sub: user.id, role: user.role },
    process.env.JWT_PRIVATE_KEY,
    {
      algorithm: 'RS256',
      expiresIn: ACCESS_TTL,
      issuer: 'https://auth.shop.ru',
      audience: 'shop-api',
    },
  );

  // REFRESH. НЕ JWT, а просто случайная строка. Так лучше по двум причинам:
  //   1. Внутри ничего нет — значит, нечего утечь.
  //   2. Он всё равно проверяется по базе, так что подпись не нужна.
  const refreshToken = crypto.randomBytes(32).toString('base64url');

  // В БАЗУ КЛАДЁМ ХЕШ, А НЕ САМ ТОКЕН. Точно так же, как с паролями:
  // если базу украдут, из хешей нельзя получить рабочие токены.
  // Здесь достаточно быстрого sha256 — в отличие от пароля, наш токен
  // и так состоит из 32 случайных байт, подбирать его бессмысленно.
  const tokenHash = crypto.createHash('sha256').update(refreshToken).digest('hex');

  await db.refreshTokens.insert({
    tokenHash,
    userId: user.id,
    // СЕМЕЙСТВО. Все токены, выданные по цепочке от одного входа,
    // помечены одним идентификатором. Ниже станет ясно, зачем.
    familyId: familyId || crypto.randomUUID(),
    usedAt: null,
    // Каждый новый токен получает свои 30 суток. Обратите внимание,
    // к чему это приводит: пока человек заходит хотя бы раз в месяц,
    // цепочка продлевается бесконечно и пароль он больше не вводит
    // никогда. Часто это и нужно, но если требуется «раз в 90 дней
    // войти заново», добавляют второй, жёсткий срок на всё семейство
    // и проверяют его отдельно от срока конкретного токена.
    expiresAt: new Date(Date.now() + REFRESH_TTL_DAYS * 24 * 60 * 60 * 1000),
    createdAt: new Date(),
  });

  return { accessToken, refreshToken };
}

