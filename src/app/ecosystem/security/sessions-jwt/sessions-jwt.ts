// на localhost жертвы может слушать любая программа.
//
// ЗДОРОВЫЙ ПОДХОД:
//   * перечислять адреса возврата ПОЛНОСТЬЮ, без шаблонов
//     и подстановочных знаков;
//   * заводить ОТДЕЛЬНОЕ приложение у провайдера для разработки
//     и отдельное — для боевого сайта;
//   * если после входа надо вернуть человека на страницу, где он был,
//     передавать её НЕ в redirect_uri, а отдельно — и проверять,
//     что это адрес вашего сайта.

function safeReturnPath(raw) {
  // Принимаем только путь внутри своего сайта. Никаких схем,
  // никаких доменов. '//evil.example' браузер считает адресом
  // ДРУГОГО сайта — это классическая ловушка, поэтому проверка
  // на две косые черты в начале обязательна.
  if (typeof raw !== 'string') return '/';
  if (!raw.startsWith('/')) return '/';
  if (raw.startsWith('//')) return '/';
  return raw;
}

