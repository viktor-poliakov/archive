// ЧЕМ ЭТО ПЛОХО. Две исторические разновидности одной и той же ошибки:
//
//   «alg: none». В стандарте есть значение none — «токен без подписи».
//   Задумано для случаев, когда подлинность обеспечена иначе. Библиотека,
//   послушно читающая alg, встречает none и радостно сообщает: подпись
//   в порядке, проверять нечего. Третья часть токена при этом пустая.
//
//   Подмена RS256 на HS256. Сервер проверяет токены публичным ключом,
//   а публичный ключ — не тайна, он лежит в открытом доступе. Если
//   заставить библиотеку считать, что алгоритм симметричный, она возьмёт
//   этот публичный ключ как ОБЩИЙ СЕКРЕТ. А он известен всем.
//
// Обе дыры давно закрыты в популярных библиотеках, но появляются заново
// в самописных проверках и в редких пакетах. Отсюда и правило.

// ═══ ПРАВИЛО. АЛГОРИТМ ЗАДАЁТ ПРОВЕРЯЮЩИЙ, А НЕ ТОКЕН ═══

// ─── ЗДОРОВЫЙ КОД ──────────────────────────────────────────────────

function checkToken(token) {
  return jwt.verify(token, PUBLIC_KEY, {
    // 1. СПИСОК ДОПУСТИМЫХ АЛГОРИТМОВ ЗАДАЁМ САМИ. Всё остальное,
    //    включая none, будет отвергнуто, что бы ни было написано в токене.
    algorithms: ['RS256'],

    // 2. КТО ВЫДАЛ. Токен, выданный другой системой, нам не подходит,
    //    даже если он идеально подписан своим собственным ключом.
    issuer: 'https://auth.shop.ru',

    // 3. ДЛЯ КОГО. Защита от «пересылки»: токен, выданный мобильному
    //    приложению для другого API, не должен открывать двери здесь.
    audience: 'shop-api',

    // 4. ДОПУСК ПО ЧАСАМ. Часы серверов расходятся на секунды.
    //    30 секунд — разумная поблажка. Ставить минуты не надо.
    clockTolerance: 30,
  });
  // Срок действия (exp) библиотека проверяет сама и без просьбы —
  // но только если поле вообще есть. Токен без exp живёт вечно,
  // поэтому выпускать такие нельзя.
}

// Применение: одна проверка на входе, дальше по коду данные считаются
// достоверными. Ошибку разбираем по типу — истёк или подделан.
function requireAuth(req, res, next) {
  const header = req.get('authorization') || '';
  if (!header.startsWith('Bearer ')) {
    return res.status(401).json({ error: 'Требуется вход' });
  }
  try {
    req.user = checkToken(header.slice('Bearer '.length));
    next();
  } catch (error) {
    if (error.name === 'TokenExpiredError') {
      // Отдельный код, чтобы клиент понял: надо обновить пару токенов,
      // а не показывать человеку форму входа.
      return res.status(401).json({ error: 'token_expired' });
    }
    return res.status(401).json({ error: 'Недействительный токен' });
  }
}

