app.get('/auth/login', (req, res) => {
  // 1. state — случайная строка «против чужого входа».
  const state = crypto.randomBytes(16).toString('base64url');

  // 2. code_verifier — секрет PKCE. Никуда не уезжает.
  const codeVerifier = crypto.randomBytes(32).toString('base64url');

  // 3. code_challenge — его односторонний отпечаток. Уезжает открыто.
  const codeChallenge = crypto
    .createHash('sha256')
    .update(codeVerifier)
    .digest('base64url');

  // 4. nonce — понадобится в следующем разделе, для проверки id_token.
  const nonce = crypto.randomBytes(16).toString('base64url');

  // ГДЕ ХРАНИТЬ ЭТИ ТРИ ЗНАЧЕНИЯ МЕЖДУ ДВУМЯ ЗАПРОСАМИ.
  // Правильно — в серверной сессии (да, той самой, из начала страницы;
  // она нужна даже проектам «полностью на JWT»). Допустимо — в короткой
  // подписанной cookie. Неправильно — в глобальной переменной сервера:
  // при двух серверах вход будет ломаться через раз, а при нескольких
  // вкладках значения затрут друг друга.
  req.session.oauth = { state, codeVerifier, nonce, createdAt: Date.now() };

  const params = new URLSearchParams({
    response_type: 'code',
    client_id: OAUTH.clientId,
    redirect_uri: OAUTH.redirectUri,
    scope: 'openid email profile',
    state,
    nonce,
    code_challenge: codeChallenge,
    code_challenge_method: 'S256',   // 'plain' не используем никогда
  });

  res.redirect(OAUTH.authorizeUrl + '?' + params.toString());
});

