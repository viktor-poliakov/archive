// id_token подписан ПРИВАТНЫМ ключом Google. Проверить его надо
// ПУБЛИЧНЫМ. Где взять публичный? Google его публикует.
//
// Адрес публикации находится не наугад: у каждого провайдера есть
// «карта возможностей» по стандартному адресу.
//   https://accounts.google.com/.well-known/openid-configuration
// Это обычный JSON, откройте его в браузере. Внутри — адреса
// всех обработчиков и, в частности, поле jwks_uri: адрес, по которому
// лежат публичные ключи (набор называется JWKS — JSON Web Key Set).
//
// ПОЧЕМУ КЛЮЧИ НАДО БРАТЬ ПО АДРЕСУ, А НЕ ВПИСАТЬ В КОД.
// Провайдеры регулярно меняют ключи — это нормальная гигиена.
// Вписанный в код ключ однажды перестанет подходить, и вход у всех
// сломается в случайный день. Поэтому ключи загружают и кешируют.
// В каждом токене есть поле kid (key id) — номер ключа, которым
// он подписан. По нему из набора выбирают нужный.

const jwt = require('jsonwebtoken');
const { createRemoteJWKSet, jwtVerify } = require('jose');

// Библиотека сама скачает ключи, сама закеширует и сама обновит,
// когда встретит незнакомый kid. Писать это руками не надо.
const JWKS = createRemoteJWKSet(new URL('https://www.googleapis.com/oauth2/v3/certs'));

async function verifyIdToken(idToken, expectedNonce) {
  const { payload } = await jwtVerify(idToken, JWKS, {
    // КТО ВЫДАЛ. Строгое совпадение. Токен, выданный кем-то другим,
    // не подходит, даже если он безупречно подписан своим ключом.
    issuer: 'https://accounts.google.com',

    // ДЛЯ КОГО. Здесь должен быть ВАШ client_id. Без этой проверки
    // токен, выданный Google для СОВЕРШЕННО ДРУГОГО приложения,
    // откроет вход на ваш сайт. А получить такой токен легко:
    // достаточно зарегистрировать своё приложение у того же Google.
    audience: process.env.OAUTH_CLIENT_ID,

    // Алгоритм задаём сами — правило из раздела про подпись.
    algorithms: ['RS256'],

    clockTolerance: 30,
  });

  // NONCE. Мы отправили случайную строку на шаге 1 и ждём её обратно
  // внутри токена. Это привязывает токен к нашему конкретному входу:
  // подсунуть заранее полученный чужой id_token не выйдет.
  if (payload.nonce !== expectedNonce) {
    throw new Error('nonce не совпал: токен от другого входа');
  }

  // ПОЧТА. Проверяем ОТДЕЛЬНЫМ полем, а не наличием строки email.
  // Подробно про эту ловушку — в следующем разделе.
  if (payload.email && payload.email_verified !== true) {
    throw new Error('Почта не подтверждена провайдером');
  }

  return {
    providerId: payload.sub,       // <- вот по этому и опознаём человека
    email: payload.email,
    emailVerified: payload.email_verified === true,
    name: payload.name,
    picture: payload.picture,
  };
}

