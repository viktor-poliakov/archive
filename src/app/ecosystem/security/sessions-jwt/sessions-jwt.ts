app.get('/auth/callback', async (req, res) => {
  const saved = req.session.oauth;

  // ПРОВЕРКА 0. Провайдер мог вернуть ошибку вместо кода —
  // например, если человек нажал «Отмена».
  if (req.query.error) {
    return res.redirect('/login?error=' + encodeURIComponent(req.query.error));
  }

  // ПРОВЕРКА 1. Мы вообще начинали этот вход?
  if (!saved) {
    return res.status(400).send('Вход не начинался или сессия истекла');
  }

  // ПРОВЕРКА 2. STATE. Сравнение постоянного времени — по той же
  // причине, по которой так сравнивают подписи.
  const received = String(req.query.state || '');
  const expected = saved.state;
  const ok =
    received.length === expected.length &&
    crypto.timingSafeEqual(Buffer.from(received), Buffer.from(expected));
  if (!ok) {
    return res.status(400).send('Проверка state не пройдена');
  }

  // ПРОВЕРКА 3. Не слишком ли давно всё началось. Вход, начатый
  // сорок минут назад, почти наверняка чужой или брошенный.
  if (Date.now() - saved.createdAt > 10 * 60 * 1000) {
    delete req.session.oauth;
    return res.status(400).send('Время входа истекло, начните заново');
  }

  // ОБМЕН КОДА НА ТОКЕНЫ. Запрос идёт С СЕРВЕРА НА СЕРВЕР:
  // ни код, ни секрет, ни verifier браузер не видит.
  const response = await fetch(OAUTH.tokenUrl, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({
      grant_type: 'authorization_code',
      code: String(req.query.code || ''),
      redirect_uri: OAUTH.redirectUri,
      client_id: OAUTH.clientId,
      client_secret: OAUTH.clientSecret,
      code_verifier: saved.codeVerifier,
    }),
  });

  if (!response.ok) {
    // Тело ошибки полезно записать в журнал ЦЕЛИКОМ — но именно
    // в журнал, а не пользователю: там бывают подробности настройки.
    console.error('Обмен кода не удался', await response.text());
    return res.status(502).send('Не удалось завершить вход');
  }

  const tokens = await response.json();

  // Одноразовые значения больше не нужны — убираем сразу,
  // чтобы повторный заход на callback ничего не сделал.
  const nonce = saved.nonce;
  delete req.session.oauth;

  // Разбор id_token — в следующем разделе.
  const profile = await verifyIdToken(tokens.id_token, nonce);

  // ═══ КЛЮЧЕВОЙ МОМЕНТ ВСЕЙ СТРАНИЦЫ ═══
  // Вход через Google ЗАКОНЧИЛСЯ. Дальше начинается ВАША сессия.
  // Токены Google в браузер не отдаём — они нужны только серверу
  // и только если вы собираетесь ходить в API Google.
  const user = await findOrCreateUser(profile);

  // Защита от подмены сессии: старый идентификатор выбрасываем
  // и выдаём новый. Если до входа кто-то подсунул человеку
  // свой идентификатор сессии, он станет бесполезен.
  await req.session.regenerate();
  req.session.userId = user.id;

  res.redirect('/');
});

