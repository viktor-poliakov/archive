const crypto = require('node:crypto');

// ─── КАК ПОДПИСЬ УСТРОЕНА ВНУТРИ. Делаем её руками ─────────────────
// Никакой магии: берём первые две части токена, склеиваем через точку
// и считаем от них HMAC.
//
// HMAC (Hash-based Message Authentication Code, «код подлинности
// сообщения на основе хеша») — это обычный хеш, посчитанный не только
// от данных, но и от секретного ключа. Смысл добавки такой: хеш от
// текста может посчитать любой, а хеш от «текст + секрет» — только тот,
// кто знает секрет. Поэтому совпавший HMAC доказывает две вещи сразу:
// текст не менялся И его подписал владелец ключа.

const SECRET = process.env.JWT_SIGNING_KEY;   // длинная случайная строка

function signHs256(headerPart, payloadPart, secret) {
  return crypto
    .createHmac('sha256', secret)
    .update(headerPart + '.' + payloadPart)
    .digest('base64url');
}

// Проверка — это пересчёт того же самого и сравнение.
function verifyHs256(token, secret) {
  const [headerPart, payloadPart, signaturePart] = token.split('.');
  const expected = signHs256(headerPart, payloadPart, secret);

  // ВАЖНО: сравниваем через timingSafeEqual, а не через ===.
  // Обычное сравнение строк останавливается на первом несовпавшем
  // символе, и по времени ответа можно подбирать подпись символ
  // за символом. Функция ниже всегда тратит одинаковое время.
  const a = Buffer.from(signaturePart);
  const b = Buffer.from(expected);
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

