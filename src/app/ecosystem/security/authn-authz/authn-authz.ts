// в базе нет — ответ ВЫЧИСЛЯЕТСЯ обходом связей.

function rebacAllows(subject, object, visited = new Set()) {
  if (visited.has(object)) return false;   // защита от циклов в связях
  visited.add(object);

  const direct = relations.some(
    (r) => r.subject === subject && r.object === object,
  );
  if (direct) return true;

  const parents = relations
    .filter((r) => r.object === object && r.relation === 'parent')
    .map((r) => r.subject);

  return parents.some((parent) => rebacAllows(subject, parent, visited));
}

