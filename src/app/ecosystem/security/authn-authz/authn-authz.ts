// В Express (и в большинстве похожих фреймворков) запрос проходит
// через ЦЕПОЧКУ функций. Каждая такая функция называется middleware —
// «промежуточный обработчик». Она получает три вещи:
//   request  — что пришло от клиента,
//   response — чем мы будем отвечать,
//   next     — функция «я закончил, передавай дальше по цепочке».
// Если next не вызвать, а вместо этого ответить, — цепочка обрывается,
// и настоящий обработчик ручки просто не выполнится.
