// Форма на сайте отправляет два поля: имя и телефон.
//   {"name":"Пётр","phone":"+7 900 000-00-00"}
//
// Но форма — это не сервер. Отправить можно ЧТО УГОДНО:
//   {"name":"Пётр","role":"admin"}
//   {"name":"Пётр","balance":1000000}
//   {"name":"Пётр","emailVerified":true}
//   {"name":"Пётр","discountPercent":100}
//   {"name":"Пётр","id":1}
//
// И Object.assign честно запишет всё это в объект пользователя,
