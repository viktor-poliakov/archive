// ─── ОХРАННИК 1. АУТЕНТИФИКАЦИЯ: «кто ты?» ───

async function requireAuth(request, response, next) {
  // Достаём доказательство личности. Здесь — токен из заголовка,
  // но с тем же успехом это может быть cookie сессии.
  const header = request.headers.authorization || '';

  // Заголовок обязан начинаться со слова Bearer и пробела.
  if (!header.startsWith('Bearer ')) {
    return response
      .status(401)
      .set('WWW-Authenticate', 'Bearer realm="api"')
      .json({ error: 'Требуется вход' });
  }

  const token = header.slice('Bearer '.length);

  let payload;
  try {
    // Проверка подписи и срока действия. Если токен подделан
    // или просрочен — здесь будет исключение.
    payload = await verifyToken(token);
  } catch {
    // Здесь доказательство БЫЛО предъявлено и не подошло — вот в этом
    // случае в заголовке уместен и код ошибки. Когда токена не прислали
    // вовсе (ветка выше), сообщать нечего: там только схема и realm.
    return response
      .status(401)
      .set('WWW-Authenticate', 'Bearer realm="api", error="invalid_token"')
      .json({ error: 'Токен недействителен' });
  }

  // Пользователя берём ИЗ БАЗЫ, а не из токена целиком.
  // Причина: пока токен жил, человека могли заблокировать
  // или понизить в правах. Токен об этом не знает — база знает.
  const user = await db.users.findById(payload.sub);
  if (!user || user.blockedAt) {
    return response.status(401).json({ error: 'Учётная запись недоступна' });
  }

  // Кладём пользователя в запрос — дальше по цепочке им пользуются все.
  request.user = user;
  next();
}

// ─── ОХРАННИК 2. АВТОРИЗАЦИЯ ПО РОЛИ: «а можно ли тебе сюда?» ───
// Обратите внимание: requireRole — это функция, которая ВОЗВРАЩАЕТ
// middleware. Так делают, чтобы передать ей параметр (список ролей).

function requireRole(...allowedRoles) {
  return function (request, response, next) {
    // Страховка от неправильного порядка: если requireAuth забыли
    // поставить раньше, request.user будет пустым. Отвечаем 500,
    // а не 403 — потому что это ошибка НАША, а не пользователя.
    if (!request.user) {
      console.error('requireRole вызван без requireAuth — ошибка в настройке маршрутов');
      return response.status(500).json({ error: 'Внутренняя ошибка' });
    }

    if (!allowedRoles.includes(request.user.role)) {
      // 403: мы точно знаем, кто это, и точно решили — нельзя.
      return response.status(403).json({ error: 'Недостаточно прав' });
    }

    next();
  };
}

