async function authenticate(email, password) {
  const user = await db.users.findByEmail(email);

  // Пользователя с таким адресом нет. Отвечаем ровно так же, как
  // при неверном пароле — иначе по разнице ответов можно перебором
  // выяснить, кто зарегистрирован на сайте, а кто нет.
  if (!user) return null;

  // В базе лежит НЕ пароль, а его хеш — необратимый отпечаток.
  // Подробно про хеши и про то, чем bcrypt/argon2 отличаются от md5,
  // разбирается на странице про пароли и секреты.
  const passwordIsCorrect = await verifyPasswordHash(password, user.passwordHash);
  if (!passwordIsCorrect) return null;

  // Доказательство принято. Теперь мы ЗНАЕМ, кто перед нами.
  return user;   // { id: 42, email: 'anna@shop.ru', role: 'customer' }
}

// ─── ШАГ 3. АВТОРИЗАЦИЯ — «а можно ли тебе именно это?» ───
// Мы уже знаем, кто пришёл. Остался главный вопрос: разрешено ли
// этому конкретному человеку это конкретное действие над этим
// конкретным объектом. Сокращают по тому же правилу — authz:
// auth плюс последняя буква английского authorization.

function canDownloadInvoice(user, order) {
  // Правило 1. Свой заказ — можно.
  if (order.userId === user.id) return true;

  // Правило 2. Сотрудник поддержки — можно, работа такая.
  if (user.role === 'support') return true;

  // Правило 3. Всем остальным — нельзя. Это ответ ПО УМОЛЧАНИЮ,
  // и он должен быть именно «нельзя», а не «ну наверное можно».
  return false;
}

// ─── КАК ЭТИ ТРИ ШАГА СТОЯТ ВМЕСТЕ ───

async function handleDownloadInvoice(request, response) {
  // 1. Идентификация + 2. Аутентификация: кто пришёл и правда ли это он.
  //    Обычно это уже сделано раньше — по cookie сессии или по токену, —
  //    и результат лежит в request.user. Как именно — тема следующей страницы.
  const user = request.user;
  if (!user) {
    // Мы не знаем, кто это. Не «нельзя», а именно «не узнал».
    return response.status(401).json({ error: 'Требуется вход' });
  }

  const order = await db.orders.findById(request.params.id);
  if (!order) return response.status(404).json({ error: 'Заказ не найден' });

  // 3. Авторизация: знаем кто, теперь решаем — можно ли ему.
  if (!canDownloadInvoice(user, order)) {
    return response.status(403).json({ error: 'Нет доступа к этому заказу' });
  }

  return response.send(await renderInvoice(order));
}

