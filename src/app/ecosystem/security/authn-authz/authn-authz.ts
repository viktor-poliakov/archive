async function loginStepOne(request, response) {
  const { email, password } = request.body;

  const user = await authenticate(email, password);
  if (!user) {
    // Одинаковый ответ и на несуществующий адрес, и на неверный пароль.
    return response.status(401).json({ error: 'Неверный адрес или пароль' });
  }

  // Первый фактор пройден. Но если у человека включён второй —
  // полноценную сессию мы ещё НЕ ВЫДАЁМ.
  if (user.mfaEnabled) {
    // Выдаём временный «полупропуск»: он годится ровно для одного
    // действия — прислать одноразовый код — и живёт пять минут.
    const challengeToken = await createMfaChallenge(user.id, { ttlSeconds: 300 });
    return response.status(200).json({ mfaRequired: true, challengeToken });
  }

  await startSession(response, user);
  return response.json({ ok: true });
}

async function loginStepTwo(request, response) {
  const { challengeToken, code } = request.body;

  const challenge = await findMfaChallenge(challengeToken);
  if (!challenge || challenge.expiresAt < Date.now()) {
    return response.status(401).json({ error: 'Время истекло, войдите заново' });
  }

  // Ограничение попыток обязательно. У шестизначного кода всего миллион
  // вариантов, и если разрешить сколько угодно попыток, их спокойно
  // переберёт программа. Сколько именно это займёт времени — зависит
  // от того, как быстро отвечает сервер, так что рассчитывать на «не
  // успеют» нельзя. Правильный ответ — просто не давать больше
  // нескольких попыток.
  if (challenge.attempts >= 5) {
    await deleteMfaChallenge(challengeToken);
    return response.status(429).json({ error: 'Слишком много попыток' });
  }

  // TOTP (Time-based One-Time Password) — «одноразовый пароль на основе
  // времени». Это те самые шестизначные коды из приложения-аутентификатора,
  // которые сами меняются каждые тридцать секунд. Как они устроены внутри,
  // разбирается на странице про пароли, MFA и секреты.
  const codeIsCorrect = await verifyTotpCode(challenge.userId, code);
  if (!codeIsCorrect) {
    await incrementMfaAttempts(challengeToken);
    return response.status(401).json({ error: 'Неверный код' });
  }

  // Оба фактора пройдены. Только теперь появляется настоящая сессия.
  await deleteMfaChallenge(challengeToken);
  const user = await db.users.findById(challenge.userId);
  await startSession(response, user);
  return response.json({ ok: true });
}

