// ═══ ПОЧЕМУ ЭТО ПРОХОДИТ РЕВЬЮ ═══
// БЕДА 1. Строка выглядит аккуратно и «по-взрослому».
//   Object.assign — стандартная функция, никакого запаха.

// БЕДА 2. Опасные поля появляются ПОЗЖЕ.
//   В день написания кода в таблице users было три поля: имя, почта,
//   телефон, и ошибка была безобидной. Роль добавили через год,
//   баланс — через два. Никто не пошёл перечитывать старый обработчик.

// БЕДА 3. Тесты ничего не заметят.
//   Тест отправляет ровно то, что отправляет форма, и получает
//   ожидаемый ответ. Он проверяет, что нужное работает,
//   а не что ненужное запрещено.

// ═══ ЗДОРОВЫЙ КОД. Явный список разрешённых полей ═══
// Правило: перечисляем то, что МОЖНО, а не то, что нельзя.
// Это тот же отказ по умолчанию, только про поля.

const PROFILE_EDITABLE_FIELDS = ['name', 'phone', 'city', 'birthDate'];

function pickAllowed(source, allowedFields) {
  const result = {};
  for (const field of allowedFields) {
    // hasOwn нужен, чтобы отличить «поле прислали пустым»
    // от «поля не прислали вовсе»: первое надо записать, второе — нет.
    if (Object.hasOwn(source, field)) {
      result[field] = source[field];
    }
  }
  return result;
}

